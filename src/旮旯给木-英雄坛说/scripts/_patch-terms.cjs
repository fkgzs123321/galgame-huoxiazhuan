// 按术语表改面板文案：解释 → 专有名词
const fs = require('fs');
const p = 'src/旮旯给木-英雄坛说/正则/_面板逻辑.js';
let t = fs.readFileSync(p, 'utf8');
const 前 = t;

// ── 术语化（★ 顺序：长的先换，免得被短的吃掉）──
const 换 = [
  // 任务
  ['做成给什么', '任务奖励'],
  ['成了给什么', '任务奖励'],
  ['砸了怎么着', '失败惩罚'],
  ['谁给的', '委托人'],
  ['要多少', '所需进度'],
  ['能不能反复做', '可重复'],
  // 技能
  ['下一级要', '升级消耗'],
  ['养哪个天赋', '天赋反哺'],
  ['还 " + nf + " 级', '距反哺 " + nf + " 级'],
  ['"现在", 现 + " 级"', '"当前等级", 现 + " 级"'],
  ['"下一级就给天赋 +1"', '"可反哺：天赋 +1"'],
  ['类 + "　要 " + 要', '类 + "　" + 要 + " 潜能"'],
  // 前置
  ['折行("门槛"', '折行("前置条件"'],
  // 出招
  ['她摆出来的', '本轮选项'],
  [' + (倾 ? ("她要点第 " + E(倾) + " 条") : "还没点") +', ' + (倾 ? ("她的选择：第 " + E(倾) + " 条") : "她的选择：未定") +'],
  // 她
  ['手段记录已', '手段记录'],
  ['她用过的手段', '手段记录'],
  // 战斗
  ['这一带能动手的', '可交战目标'],
  ['这一带没有能动手的人。', '可交战目标：无。'],
  // 空占位
  ["(需 > 0 ? (进 + \" / \" + 需) : \"做\")", "(需 > 0 ? (进 + \" / \" + 需) : \"进行中\")"],
  [": \"做\" + \"</b>\",", ": \"进行中\" + \"</b>\","],
];

let 改了几处 = 0;
for (const [a, b] of 换) {
  if (t.includes(a)) {
    const n = t.split(a).length - 1;
    t = t.split(a).join(b);
    改了几处 += n;
  }
}

// ── 「屏幕外的她」→「操控者」（只改面向玩家的文案，不动目录名）──
const 称呼换 = [
  ['屏幕外的她', '操控者'],
  ['屏幕外那 ', '操控者共 '],
  ['屏幕外的人', '操控者'],
];
for (const [a, b] of 称呼换) {
  if (t.includes(a)) { t = t.split(a).join(b); 改了几处++; }
}

fs.writeFileSync(p, t);
console.log('✅ 文案术语化：改了 ' + 改了几处 + ' 处');
console.log('   文件 ' + Math.round(Buffer.byteLength(t, 'utf8') / 1024) + ' KB');

// 复查还有没有口语
const 残留 = ['做成给什么', '砸了怎么着', '谁给的', '屏幕外的她', '养哪个天赋', '下一级要'];
const 还有 = 残留.filter(w => t.includes(w));
console.log('   残留: ' + (还有.length ? 还有.join(' / ') : '无 ✅'));
