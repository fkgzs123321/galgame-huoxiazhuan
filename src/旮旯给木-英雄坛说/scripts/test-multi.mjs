#!/usr/bin/env node
// ════════════════════════════════════════════════════════════
// test-multi.mjs · 多单位战斗测试
//
// ★ 单独一份，不塞进 test-combat：1v1 和多单位是两件事，
//   塞在一起变量名会打架（试过，很乱），而且失败时看不清是谁挂的。
//
// 用例照四个来源写：
//   火影   影分身 / 团队战
//   魔兽   副本 / RAID
//   海贼   船战
//   本卡   坛主带三个喽啰
//
// 用法: node scripts/test-multi.mjs
// ════════════════════════════════════════════════════════════
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const F = path.resolve(path.join(__dirname, '..', '机制', '战斗引擎.txt'));
if (!fs.existsSync(F)) { console.error('[FAIL] 找不到 ' + F); process.exit(2); }
const code = [...fs.readFileSync(F, 'utf8').matchAll(/<%([\s\S]*?)%>/g)].map((m) => m[1]).join('\n');
for (const n of ['this.multi', 'this.编队', 'this.strike']) {
  if (!new RegExp(n).test(code)) { console.error('[FAIL] 未提取到 ' + n); process.exit(2); }
}
const lib = new Function('getvar', code + '\nreturn this;').call({}, () => null);

let pass = 0, fail = 0;
const ok = (c, n, e = '') => { if (c) { pass++; console.log('  [OK]   ' + n); } else { fail++; console.log('  [FAIL] ' + n + (e ? '  → ' + e : '')); } };
const section = (t) => console.log('\n' + t);

console.log('='.repeat(74));
console.log('多单位战斗测试 · 机制/战斗引擎.txt 的 multi()');
console.log('='.repeat(74));

const 造 = (名, 生命, 攻击, 防御, 总评, 出手, 额外) =>
  Object.assign({ 名, 生命, 上限: 生命, 攻击, 防御, 总评, 出手值: 出手, 有效值: 100 }, 额外 || {});
// ★ 引擎自带命中率（不再依赖成长引擎）——传 null 就走它自带的那一份
const 率 = null;
const 造随机 = (种) => { let s = 种; return () => { s = (1664525 * s + 1013904223) % 4294967296; return s / 4294967296; }; };

section('基本约束');
ok(lib.multi({ 我方: [], 对方: [造('甲', 10, 5, 1, 10, 5)] }).可以 === false, '一边没人 → 打不起来');
ok(lib.multi({ 我方: [造('甲', 10, 5, 1, 10, 5)], 对方: [] }).可以 === false, '另一边没人也不行');

section('① 次序（本卡的场景：坛主带三个喽啰）');
let 三打一 = lib.multi({
  我方: [造('喽啰甲', 60, 20, 5, 30, 30), 造('喽啰乙', 60, 20, 5, 30, 28), 造('喽啰丙', 60, 20, 5, 30, 26)],
  对方: [造('坛主', 400, 90, 40, 90, 60)],
  上限回合: 30,
}, 造随机(20260916), 率);
ok(三打一.可以 === true, '三打一跑得起来');
ok(三打一.日志.length > 0, '有回合日志');
ok(三打一.日志[0].动作.length >= 2, '第一回合有多个人动了');
ok(三打一.日志[0].动作[0].谁 === '坛主', '★★ 出手值最高的先动（坛主 60 > 喽啰 30）', 三打一.日志[0].动作[0].谁);
ok(三打一.日志[0].动作[0].边 === '对方', '并标明他是哪一边');

section('② 阵亡（倒下就退出轮转）');
let 倒了还动 = false;
const 已倒 = {};
for (const 回 of 三打一.日志) {
  for (const a of 回.动作) {
    if (已倒[a.谁] && !a.跳过) 倒了还动 = true;
    if (a.目标剩余 !== undefined && a.目标剩余 <= 0) 已倒[a.打] = 1;
  }
}
ok(倒了还动 === false, '★★ 倒下的人不再行动');
ok(三打一.摘要.存活.indexOf('/') >= 0, '★ 摘要给存活数：' + 三打一.摘要.存活);
ok(['我方', '对方', '同归', '未决'].includes(三打一.胜者), '胜负在四个值里：' + 三打一.胜者);
ok(三打一.摘要.写法约束.some((x) => x.indexOf('别写成一团') >= 0), '★★ 多人在场会提醒「别写成一团」');

section('③ 选目标（策略由 cfg 给，引擎不自己决定）');
const 两敌 = [造('壮', 300, 30, 10, 60, 20), 造('弱', 40, 10, 2, 20, 10)];
let r1 = lib.multi({ 我方: [造('我', 200, 60, 20, 80, 50)], 对方: 两敌.map((x) => ({ ...x })), 选目标: '打最弱' }, 造随机(1), 率);
ok(r1.日志[0].动作[0].打 === '弱', '★ 「打最弱」→ 先打弱的（先减员）', r1.日志[0].动作[0].打);
let r2 = lib.multi({ 我方: [造('我', 200, 60, 20, 80, 50)], 对方: 两敌.map((x) => ({ ...x })), 选目标: '打最强的' }, 造随机(1), 率);
ok(r2.日志[0].动作[0].打 === '壮', '★ 「打最强的」→ 先打强的', r2.日志[0].动作[0].打);
let r3 = lib.multi({ 我方: [造('我', 200, 60, 20, 80, 50)], 对方: 两敌.map((x) => ({ ...x })), 选目标: '打血最厚的' }, 造随机(1), 率);
ok(r3.日志[0].动作[0].打 === '壮', '★ 「打血最厚的」→ 打血多的那个', r3.日志[0].动作[0].打);
let r4 = lib.multi({ 我方: [造('我', 200, 60, 20, 80, 50)], 对方: 两敌.map((x) => ({ ...x })), 选目标: '按顺序' }, 造随机(1), 率);
ok(r4.日志[0].动作[0].打 === '壮', '★ 「按顺序」→ 打名单里第一个（壮在弱前面）', r4.日志[0].动作[0].打);

section('④ 群体范围（摊薄）');
const 群 = lib.multi({
  我方: [造('法师', 200, 60, 20, 80, 50, { 范围: '群体' })],
  对方: [造('甲', 300, 10, 2, 20, 10), 造('乙', 300, 10, 2, 20, 10)],
  群体摊薄: 0.6,
}, 造随机(1), 率);
const 群打 = 群.日志[0].动作.filter((a) => a.附带);
ok(群打.length >= 1, '★ 群体范围顺带打到其他人（附带 ' + 群打.length + ' 个）');
ok(群打.length === 0 || 群打[0].伤害 < 群.日志[0].动作[0].伤害, '★★ 附带伤害被摊薄（小于主目标）', 群打.length ? (群打[0].伤害 + ' < ' + 群.日志[0].动作[0].伤害) : '');
let 单 = lib.multi({
  我方: [造('剑客', 200, 60, 20, 80, 50)],
  对方: [造('甲', 300, 10, 2, 20, 10), 造('乙', 300, 10, 2, 20, 10)],
}, 造随机(1), 率);
ok(单.日志[0].动作.filter((a) => a.附带).length === 0, '★ 单体范围不波及别人');

section('⑤ 受控（呆若木鸡）在多人里也生效');
const 控 = lib.multi({
  我方: [造('我', 300, 50, 20, 70, 90)],
  对方: [造('被定住的', 300, 50, 20, 70, 10, { 呆若木鸡: 2 })],
  上限回合: 6,
}, 造随机(7), 率);
const 跳过 = 控.日志[0].动作.filter((a) => a.跳过);
ok(跳过.length === 1 && 跳过[0].原因 === '受控', '★ 被定住的人本回合跳过：' + (跳过[0] || {}).原因);

section('⑥ 确定性（★ 同一局面重跑必须一致）');
const 队 = () => ({ 我方: [造('我', 300, 50, 20, 70, 40)], 对方: [造('敌', 300, 50, 20, 70, 40)], 上限回合: 20 });
const 跑甲 = lib.multi(队(), 造随机(12345), 率);
const 跑乙 = lib.multi(队(), 造随机(12345), 率);
ok(跑甲.回合数 === 跑乙.回合数, '★★ 回合数一致（' + 跑甲.回合数 + '）');
ok(跑甲.胜者 === 跑乙.胜者, '★★ 胜负一致（' + 跑甲.胜者 + '）');
ok(JSON.stringify(跑甲.摘要) === JSON.stringify(跑乙.摘要), '★★ 整份摘要逐字一致 —— 不许 Math.random');

section('⑦ 大团战（魔兽副本那种：3 v 4）');
const 团 = lib.multi({
  我方: [造('坦', 800, 40, 60, 80, 30), 造('输出甲', 300, 90, 20, 80, 55), 造('奶', 250, 20, 30, 60, 45)],
  对方: [造('头目', 900, 80, 40, 90, 50), 造('爪牙甲', 200, 30, 10, 40, 35), 造('爪牙乙', 200, 30, 10, 40, 33), 造('爪牙丙', 200, 30, 10, 40, 31)],
  上限回合: 40, 选目标: '打最弱的',
}, 造随机(999), 率);
ok(团.可以 === true, '3 v 4 跑得起来');
ok(团.日志.length > 0, '有回合日志（' + 团.日志.length + ' 回合）');
ok(团.摘要.存活.indexOf('我方') >= 0 && 团.摘要.存活.indexOf('对方') >= 0, '★ 双方存活都给了：' + 团.摘要.存活);
ok(团.我方剩.length === 3 && 团.对方剩.length === 4, '★ 双方名单完整（我方 3 / 对方 4）');

section('⑧ 编队');
const 队2 = lib.编队(['甲', '乙', '丙'], (n) => 造(n, 100, 20, 5, 30, 20));
ok(队2.length === 3, '编队造出 3 个单位');
ok(队2[0].名 === '甲' && 队2[2].名 === '丙', '顺序保持');

console.log('\n' + '='.repeat(74));
console.log('通过 ' + pass + ' / 失败 ' + fail);
console.log('='.repeat(74));
process.exit(fail === 0 ? 0 : 1);
