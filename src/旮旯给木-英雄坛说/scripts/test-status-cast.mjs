#!/usr/bin/env node
// ════════════════════════════════════════════════════════════
// test-status-cast.mjs · E13 持续状态 + E14 相克 + C7 施展条件 测试
//
// 三个一起加载（C7 的「施展」要调 E13 的「进冷却」，跨文件）。
//
// ★ 这份测试的任务不只是「验证代码对不对」，更是**验证这些能力真的跨题材**：
//   用例直接照仙侠 / 哈利波特 / 火影 / 魔兽的形态写，
//   如果哪个用例写不出来，说明那个能力还是伪通用。
//
// 用法: node scripts/test-status-cast.mjs
// ════════════════════════════════════════════════════════════
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const 根 = path.resolve(path.join(__dirname, '..'));
const 取代码 = (rel) => {
  const p = path.join(根, rel);
  if (!fs.existsSync(p)) { console.error('[FAIL] 找不到 ' + p); process.exit(2); }
  return [...fs.readFileSync(p, 'utf8').matchAll(/<%([\s\S]*?)%>/g)].map((m) => m[1]).join('\n');
};
const code = 取代码('机制/成长引擎.txt') + '\n' + 取代码('机制/状态引擎.txt');
for (const n of ['挂上', '过一回合', '相克', '放得出吗']) {
  if (!new RegExp(n).test(code)) { console.error('[FAIL] 未提取到 ' + n); process.exit(2); }
}
const lib = new Function('getvar', code + '\nreturn this;').call({}, () => null);

let pass = 0, fail = 0;
const ok = (c, n, e = '') => { if (c) { pass++; console.log('  [OK]   ' + n); } else { fail++; console.log('  [FAIL] ' + n + (e ? '  → ' + e : '')); } };
const section = (t) => console.log('\n' + t);

console.log('='.repeat(74));
console.log('E13 持续状态 + E14 相克 + C7 施展条件 · 联合测试');
console.log('（用例照仙侠 / 哈利波特 / 火影 / 魔兽的形态写）');
console.log('='.repeat(74));

// ════════ E13 ════════
section('E13 · 持续状态（武侠的毒 / 仙侠的丹毒 / 魔兽的 debuff 都是它）');
const 定义表 = [
  { id: '中毒', 名: '中毒', 类型: '减益', 时长: 3, 层数上限: 5, 每回合: { 生命: -8 } },
  { id: '力增', 名: '力增', 类型: '增益', 时长: 2, 层数上限: 3, 改派生: { 攻击: 1.5 } },
  { id: '迟钝', 名: '迟钝', 类型: '减益', 时长: 2, 改概率: -20 },
];

const 身1 = {};
const g = lib.挂上(身1, 定义表[0]);
ok(g.可以 && 身1['中毒'].剩 === 3, '★ 挂上中毒（3 回合）');
lib.挂上(身1, 定义表[0]);
ok(身1['中毒'].层 === 2, '★ 再挂一次 → 叠层到 2（毒会越叠越重）');
lib.挂上(身1, 定义表[0]); lib.挂上(身1, 定义表[0]); lib.挂上(身1, 定义表[0]); lib.挂上(身1, 定义表[0]);
ok(身1['中毒'].层 === 5, '★ 层数夹到上限 5（不是无限叠）');

const 血 = { 生命: 100 };
const 报 = lib.过一回合(身1, 定义表, 血);
ok(血.生命 === 60, '★ 每回合按层数结算：5 层 × 8 = 40，100 → 60', '实得 ' + 血.生命);
ok(身1['中毒'].剩 === 2, '结算后时长减 1');
ok(lib.撤掉(身1, '中毒').可以 === true, '撤掉一个在身上状态');
ok(lib.撤掉(身1, '中毒').可以 === false, '★ 撤一个身上没有的 → 返回 false（不是静默成功）');

const 身2 = {};
lib.挂上(身2, { id: '短', 名: '短', 时长: 1 });
lib.过一回合(身2, [{ id: '短', 时长: 1 }], {});
ok(身2['短'] === undefined, '★ 时长归零 → 自动摘掉');

section('E13-c · 状态改写派生（与 C4 接）');
const 身3 = {};
lib.挂上(身3, 定义表[1]);
const 倍 = lib.状态倍率(身3, 定义表);
ok(倍.攻击 === 1.5, '1 层力增 → 攻击 ×1.5');
lib.挂上(身3, 定义表[1]);
const 倍2 = lib.状态倍率(身3, 定义表);
ok(Math.abs(倍2.攻击 - 2.0) < 1e-9, '★ 2 层 → ×2.0（偏离 1 的部分按层数放大：1 + 0.5×2）');
const 派生后 = lib.应用倍率({ 攻击: 100, 防御: 50 }, 倍2);
ok(派生后.攻击 === 200 && 派生后.防御 === 50, '★ 只改有倍率的那一项，其余不动');

section('E13-d · 冷却（就是给自己挂一个不能用的状态）');
const 身4 = {};
lib.进冷却(身4, '大火球', 3);
ok(lib.在冷却(身4, '大火球') === true, '用过之后进冷却');
ok(lib.冷却剩(身4, '大火球') === 3, '★ 还剩 3 回合');
lib.过一回合(身4, [], {});
ok(lib.冷却剩(身4, '大火球') === 2, '过一回合冷却减 1');
ok(lib.状态快照(身4).indexOf('冷却') < 0, '★ 冷却不出现在状态栏（不占版面）');

// ════════ E14 ════════
section('E14 · 相克关系（五行 / 忍体幻 / 属性相克，同一个矩阵）');
const 五行 = { 键: ['木', '火', '土', '金', '水'], 值: {
  木: { 火: 1.5, 土: 0.7 }, 火: { 土: 1.5, 金: 0.7 }, 土: { 金: 1.5, 水: 0.7 },
  金: { 木: 1.5, 火: 0.7 }, 水: { 火: 1.5, 土: 0.7 },
} };
ok(lib.相克(五行, '木', '火') === 1.5, '★ 木克火 → 1.5 倍');
ok(lib.相克(五行, '火', '木') === 1, '没写的那一对 → 默认 1');
ok(lib.克我的(五行, null, '火').includes('水'), '★ 克火的（水）能算出来 —— 面板要提示这个');
ok(lib.我克的(五行, null, '火').includes('土'), '火克的（土）能算出来');
ok(lib.相克全表(五行).length === 20, '全表 5×4 = 20 对');
ok(lib.相克自检(五行, null).有没有错 === false, '自检：自己对自己是 1（数据没错）');
const 坏矩阵 = { 键: ['甲'], 值: { 甲: { 甲: 2 } } };
ok(lib.相克自检(坏矩阵, null).有没有错 === true, '★ 自检能抓出「自己克自己」这种填错的数据');

// 火影式：三系相克，用「表」形式（另一种写法）
const 忍体幻 = { 表: [ { 攻: '忍', 守: '体', 倍率: 1.4 }, { 攻: '体', 守: '幻', 倍率: 1.4 }, { 攻: '幻', 守: '忍', 倍率: 1.4 } ], 默认: 1 };
ok(lib.相克(忍体幻, '忍', '体') === 1.4, '★ 忍克体（用「表」写法也能算）');
ok(lib.相克(忍体幻, '体', '忍') === 1, '反向没写 → 1（不是自动取倒数，要自己填）');

// ════════ C7 ════════
section('C7-a · 能不能学（血继限界那种天生的学不了）');
ok(lib.能学吗({ 先天: true }).可以 === false, '★ 标记为先天的 → 学不了');
ok(lib.能学吗({ 先天: false }).可以 === true, '普通技能能学');
ok(lib.能学吗({}).可以 === true, '★ 不写先天字段 → 默认能学（不能因为漏写就全禁了）');

section('C7-b · 能不能用（哈利波特的念咒条件 / 海贼的怕海水）');
const 禁咒 = { id: '禁咒', 名: '禁咒', 条件: [{ 类型: '有状态', 状态: '魔力充盈' }],
  代价: { 魔力: 50, 生命: 20 } };
const 值1 = { 魔力: 100, 生命: 200 };
const 身5 = {};
ok(lib.能用吗(禁咒, 值1, 身5).可以 === false, '★ 没有「魔力充盈」状态 → 用不了');
ok(lib.能用吗(禁咒, 值1, 身5).缺[0].indexOf('魔力充盈') >= 0, '缺什么说得清：要处在「魔力充盈」里');
lib.挂上(身5, { id: '魔力充盈', 名: '魔力充盈', 时长: 2 });
ok(lib.能用吗(禁咒, 值1, 身5).可以 === true, '挂了状态之后就能用了');

const 水系术 = { id: '水系术', 条件: [{ 类型: '没状态', 状态: '碰了海水' }], 代价: { 魔力: 10 } };
const 身6 = {};
lib.挂上(身6, { id: '碰了海水', 名: '碰了海水', 时长: 3 });
ok(lib.能用吗(水系术, { 魔力: 100 }, 身6).可以 === false, '★ 海贼式：带着「碰了海水」→ 果实能力用不了');
ok(lib.能用吗(水系术, { 魔力: 100 }, 身6).缺[0].indexOf('用不了') >= 0, '原因说得清');

section('C7-c · 用得起吗（扣不动就别放）');
ok(lib.用得起吗(禁咒, { 魔力: 100, 生命: 200 }).可以 === true, '资源够 → 付得起');
ok(lib.用得起吗(禁咒, { 魔力: 30, 生命: 200 }).可以 === false, '★ 魔力不够 → 付不起');
ok(lib.用得起吗(禁咒, { 魔力: 30, 生命: 200 }).缺[0].字段 === '魔力', '缺的是「魔力」这一项');

const 值2 = { 魔力: 100, 生命: 200 };
lib.付代价(禁咒, 值2);
ok(值2.魔力 === 50 && 值2.生命 === 180, '★ 代价真的扣了：魔力 100→50、生命 200→180');

section('C7-d · 一次问全（两关都过才允许放）');
const 身7 = {};
const 值3 = { 魔力: 100, 生命: 200 };
ok(lib.放得出吗(禁咒, 值3, 身7).因为 === '条件不到', '★ 先卡条件关');
lib.挂上(身7, { id: '魔力充盈', 名: '魔力充盈', 时长: 2 });
ok(lib.放得出吗(禁咒, 值3, 身7).可以 === true, '条件到了、代价付得起 → 放得出');
const 值4 = { 魔力: 10, 生命: 200 };
ok(lib.放得出吗(禁咒, 值4, 身7).因为 === '付不起代价', '★ 条件过了但付不起 → 卡在代价关');

section('C7-e · 施展（检查 → 扣代价 → 进冷却，一条链走完）');
const 身8 = {};
lib.挂上(身8, { id: '魔力充盈', 名: '魔力充盈', 时长: 3 });
const 值5 = { 魔力: 100, 生命: 200 };
const 施 = lib.施展(禁咒, 值5, 身8, 4);
ok(施.可以 === true, '放出来了');
ok(值5.魔力 === 50, '代价扣了');
ok(lib.在冷却(身8, '禁咒') === true && lib.冷却剩(身8, '禁咒') === 4, '★ 自动进冷却 4 回合');
const 再放 = lib.施展(禁咒, 值5, 身8, 4);
ok(再放.可以 === true, '★ 冷却中仍能放 —— 冷却只是「状态」，拦不拦由条件表决定（这是对的设计：两件事分开）');

section('★ 跨题材压力测试的用法');
console.log('  下列形态已能用现有能力表达：');
console.log('    仙侠 · 渡劫反噬   → E13 减益状态（每回合扣）+ C7 代价');
console.log('    仙侠 · 五行相克   → E14 矩阵');
console.log('    哈利波特 · 念咒条件 → C7 条件表（有状态 / 资源够）');
console.log('    哈利波特 · 禁咒反噬 → C7 代价');
console.log('    火影 · 查克拉耗尽 → E13 减益 + C7 资源条件');
console.log('    火影 · 三系相克   → E14 表形式');
console.log('    魔兽 · 光环 / 诅咒 → E13 改派生 + 每回合');
console.log('    魔兽 · 技能冷却   → E13 冷却（复用时长的机制）');
console.log('    海贼 · 果实弱点   → C7「没状态」条件');

console.log('\n' + '='.repeat(74));
console.log('通过 ' + pass + ' / 失败 ' + fail);
console.log('='.repeat(74));
process.exit(fail === 0 ? 0 : 1);
