#!/usr/bin/env node
// ════════════════════════════════════════════════════════════
// test-relations.mjs · 关系网（E15）测试
//
// ★ 这份测试盯的是关系网**最容易脏的两个地方**：
//   ① 键的方向（甲乙 / 乙甲 必须落到同一条，否则会存成两条）
//   ② 单向与双向（同一件事两边看法可以完全不同，不能混成一个值）
//
// 用例照五个题材的形态写（仙侠师徒 / 火影队友 / 哈利波特学院 / 魔兽公会 / 海贼船员）。
//
// 用法: node scripts/test-relations.mjs
// ════════════════════════════════════════════════════════════
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const F = path.resolve(path.join(__dirname, '..', '机制', '关系引擎.txt'));
if (!fs.existsSync(F)) { console.error('[FAIL] 找不到 ' + F); process.exit(2); }
const code = [...fs.readFileSync(F, 'utf8').matchAll(/<%([\s\S]*?)%>/g)].map((m) => m[1]).join('\n');
for (const n of ['对键', '建关系', '转几手', '查网']) {
  if (!new RegExp(n).test(code)) { console.error('[FAIL] 未提取到 ' + n); process.exit(2); }
}
const lib = new Function('getvar', code + '\nreturn this;').call({}, () => null);

let pass = 0, fail = 0;
const ok = (c, n, e = '') => { if (c) { pass++; console.log('  [OK]   ' + n); } else { fail++; console.log('  [FAIL] ' + n + (e ? '  → ' + e : '')); } };
const section = (t) => console.log('\n' + t);

console.log('='.repeat(74));
console.log('关系网 E15 测试（用例照五个题材的形态写）');
console.log('='.repeat(74));

section('E15-a · ★ 键的方向（最阴的 bug 在这）');
ok(lib.对键('甲', '乙') === lib.对键('乙', '甲'), '★★ 甲乙与乙甲 → 同一个键（不排序就会存成两条）');
const K = lib.对键('甲', '乙');
ok(/^.+\|.+$/.test(K), '键形如「某某|某某」：' + K);
ok(lib.对键('甲','乙') === lib.对键('乙','甲'), '★ 顺序无关（这正是「对键」要解决的事）');
ok(K.length === 3, '★ 键长度固定为「两字 + 竖线」= 3（长度不随次序变）');

const 网 = {};
ok(lib.建关系(网, '乙', '甲', '同门', 60).可以 === true, '用反序建关系也能成');
ok(Object.keys(网).length === 1, '★ 只存了一条（不是两条）');
ok(lib.查关系(网, '甲', '乙') !== null, '★ 正序查得到');
ok(lib.查关系(网, '乙', '甲') !== null, '★ 反序也查得到（同一条）');
ok(lib.建关系(网, '甲', '甲', '自恋').可以 === false, '不能和自己建关系');
ok(lib.建关系(网, '甲', '').可以 === false, '必须两个人');

section('E15-b · 单向 vs 双向（两边看法可以不同）');
const 网2 = {};
lib.建关系(网2, '徒弟', '师父', '师徒', 80, false);
const 条的甲 = 网2[lib.对键('徒弟','师父')].甲;
ok(lib.查关系(网2, '徒弟', '师父', 条的甲).正向 === true, '★ 单向：从存下来的「甲」那一侧看 → 正向（不假设中文排序）');
const 条的乙 = 网2[lib.对键('徒弟','师父')].乙;
ok(lib.查关系(网2, '徒弟', '师父', 条的乙).正向 === false, '★★ 从另一侧看 → 反向（同一段关系，两边不对称）');
lib.建关系(网2, '甲', '乙', '队友', 50, true);
ok(lib.查关系(网2, '甲', '乙', '甲').看法 === '彼此', '双向关系 → 看法是「彼此」');

section('E15-c · 改（关系是走出来的，不是设出来的）');
const 网3 = {};
lib.建关系(网3, '甲', '乙', '同门', 50);
ok(lib.改关系(网3, '甲', '乙', 20).到 === 70, '★ 加 20 → 50 变 70');
ok(lib.改关系(网3, '甲', '乙', -100).到 === 0, '★ 减到 0 就夹住（不会负）');
ok(lib.改关系(网3, '甲', '乙', 500).到 === 100, '★ 加到 100 也夹住');
ok(lib.改关系(网3, '甲', '丙', 10).可以 === false, '没关系的两个人 → 改不了（要先建）');
lib.建关系(网3, '甲', '丙', '宿敌', 90);
ok(lib.改类型(网3, '甲', '丙', '旧识').到 === '旧识', '★ 关系类型可以变（宿敌 → 旧识）');

section('E15-d · ★ 断关系不是删（别人还要知道曾经是什么）');
lib.断关系(网3, '甲', '乙');
ok(lib.查关系(网3, '甲', '乙').类型 === '断了', '断了');
ok(lib.查关系(网3, '甲', '乙').强度 === 0, '强度归 0');
ok(lib.与谁有关(网3, '甲').some((x) => x.曾经 === '同门'), '★★ 但「曾经是同门」还在 —— 删了就查不到了');
ok(lib.断关系(网3, '甲', '不存在').可以 === false, '没有这段关系 → 断不了');

section('E15-e · 从一个人出发看整张网');
const 网4 = {};
lib.建关系(网4, '师父', '徒弟', '师徒', 80);
lib.建关系(网4, '徒弟', '师弟', '同门', 70);
lib.建关系(网4, '徒弟', '仇家', '宿敌', 90);
lib.建关系(网4, '师父', '仇家', '宿敌', 60);
ok(lib.与谁有关(网4, '徒弟').length === 3, '★ 徒弟身边有三段关系');
ok(lib.按类型(网4, '徒弟', '宿敌').length === 1, '按类型取（徒弟的宿敌）');
ok(lib.按类型(网4, '徒弟', '宿敌')[0].对方 === '仇家', '取到的是「仇家」');
const 圈 = lib.一圈人(网4, '宿敌');
ok(圈.对数 === 2, '★ 同属「宿敌」的两对：师父-仇家、徒弟-仇家');
ok(圈.人.length === 3, '★ 涉及三个人（师父 / 徒弟 / 仇家）—— 实得 ' + 圈.人.length);

section('E15-f · ★★ 转几手（关系网最有用的功能）');
const 直 = lib.转几手(网4, '师父', '徒弟');
ok(直.步数 === 1 && 直.路.join('→') === '师父→徒弟', '一步：师父直接认识徒弟');
const 隔 = lib.转几手(网4, '师父', '师弟');
ok(隔.步数 === 2 && 隔.路.join('→') === '师父→徒弟→师弟', '★★ 两步：师父通过徒弟认识师弟');
ok(lib.转几手(网4, '徒弟', '徒弟').步数 === 0, '自己到自己 = 0 步');
const 搭不上 = lib.转几手(网4, '不存在的人', '徒弟');
ok(搭不上.步数 === -1, '★ 搭不上 → 返回 -1（不是 0，不能和「自己」混）');

section('E15-g · 查网（自己体检）');
ok(lib.查网(网4).有没有错 === false, '正常网 → 无错');
// ★ 造一个真的错键：把对键结果改一个字
const 真键 = lib.对键('甲','乙');
const 坏网 = { }; 坏网['X' + 真键.slice(1)] = { 甲: '甲', 乙: '乙', 类型: 'x', 强度: 1 };
ok(lib.查网(坏网).有没有错 === true, '★ 抓出「键与人不对应」（这种条目会正反查不到）');
const 自恋网 = { '甲|甲': { 甲: '甲', 乙: '甲', 类型: 'x', 强度: 1 } };
ok(lib.查网(自恋网).有没有错 === true, '抓出「自己和自己」');

section('面板快照');
lib.断关系(网4, '徒弟', '仇家');
const 快 = lib.快照(网4, '徒弟');
ok(快.indexOf('师父') >= 0 && 快.indexOf('师弟') >= 0, '★ 快照列出身边还成立的关系：' + 快);
ok(快.indexOf('仇家') < 0, '★ 断掉的（强度 0）不出现在快照里');

console.log('\n' + '='.repeat(74));
console.log('通过 ' + pass + ' / 失败 ' + fail);
console.log('='.repeat(74));
process.exit(fail === 0 ? 0 : 1);
