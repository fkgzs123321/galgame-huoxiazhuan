// ── ② 她的选择 ──
换('她要点第 ', '她的选择：第 ');
换('" 条"', '" 条"');
换('"还没点"', '"未定"');

// ── ③ 标签位不留说明（说明移到说明页）──
换('★ 失败也是结算 —— 好感掉、线关掉，不是「什么都没发生」。', '任务失败会结算惩罚（见「说明」页）。');
