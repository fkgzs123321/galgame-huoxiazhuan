// ── ③ 敌人风格（行为模式）──
console.log('\n【三、敌人风格】给敌人行为模式而非数值档');
const 火敌 = { 生命: 100, 生命上限: 100, 气: 5 };
let 火出重 = 0, 山出守 = 0, 林出集 = 0;
const rng = (() => { let i = 0; const a = [0.1, 0.3, 0.5, 0.7, 0.9, 0.2, 0.4, 0.6, 0.8, 0.05]; return () => a[(i++) % a.length]; })();
{
  let i = 0; const f = () => [0.1, 0.3, 0.5, 0.7, 0.9][(i++) % 5];
  for (let k = 0; k < 20; k++) if (B.敌方行动('火', 火敌, f) === '重攻击') 火出重++;
  i = 0;
  for (let k = 0; k < 20; k++) if (B.敌方行动('山', 火敌, f) === '防御') 山出守++;
  i = 0;
  const 林敌 = { 生命: 100, 生命上限: 100, 气: 0 };
  for (let k = 0; k < 20; k++) if (B.敌方行动('林', 林敌, f) === '集气') 林出集++;
}
测('★ 火 偏好重攻击（占比高）', 火出重 >= 8, 火出重);
测('★ 山 偏好防御（占比高）', 山出守 >= 8, 山出守);
测('★ 林 无气时优先集气（占比高）', 林出集 >= 10, 林出集);

