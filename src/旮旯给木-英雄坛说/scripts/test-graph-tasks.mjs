import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const 根 = path.resolve(path.join(__dirname, '..'));
const 取代码 = (rel) => {
  const p = path.join(根, rel);
  if (!fs.existsSync(p)) { console.error('[FAIL] 找不到 ' + p); process.exit(2); }
  return [...fs.readFileSync(p, 'utf8').matchAll(/<%([\s\S]*?)%>/g)].map((m) => m[1]).join('\n');
};
const code = 取代码('机制/成长引擎.txt') + '\n' + 取代码('机制/任务引擎.txt');
for (const n of ['可解锁', 'canTake', '推进', '结账']) {
  if (!new RegExp(n).test(code)) { console.error('[FAIL] 未提取到 ' + n); process.exit(2); }
}
const lib = new Function('getvar', code + '\nreturn this;').call({}, () => null);

let pass = 0, fail = 0;
const ok = (c, n, e = '') => { if (c) { pass++; console.log('  [OK]   ' + n); } else { fail++; console.log('  [FAIL] ' + n + (e ? '  → ' + e : '')); } };
const section = (t) => console.log('\n' + t);

console.log('='.repeat(72));
console.log('C6 解锁图 + E9 任务 联合测试');
console.log('='.repeat(72));

// ════════ C6 ════════
section('C6 · 解锁图（图上的先后）');
const 图 = { 节点: [
  { id: '基本拳脚', 名: '基本拳脚', 前置: [], 需要: [{ 字段: '基本拳脚', 至少: 0 }] },
  { id: '门派拳脚', 名: '门派拳脚', 前置: ['基本拳脚'], 需要: [{ 字段: '基本拳脚', 至少: 60 }] },
  { id: '绝招甲', 名: '绝招甲', 前置: ['门派拳脚'], 需要: [{ 字段: '基本拳脚', 至少: 120 }] },
  { id: '绝招乙', 名: '绝招乙', 前置: ['门派拳脚', '基本内功'], 需要: [{ 字段: '基本内功', 至少: 100 }] },
  { id: '基本内功', 名: '基本内功', 前置: [], 需要: [{ 字段: '基本内功', 至少: 0 }] },
] };

ok(lib.有没有环(图).有环 === false, '无环图 → 检测通过');
const 环图 = { 节点: [
  { id: 'A', 前置: ['B'] },
  { id: 'B', 前置: ['A'] },
] };
ok(lib.有没有环(环图).有环 === true, '★ A↔B 互相依赖 → 检测到环（否则「可解锁」永远为空）');

const 层 = lib.拓扑序(图);
ok(层[0].length === 2 && 层[0].includes('基本拳脚') && 层[0].includes('基本内功'), '拓扑序：根层是两门基本功');
ok(层[1].includes('门派拳脚'), '第二层是门派拳脚');
ok(层[2].includes('绝招甲') && 层[2].includes('绝招乙'), '第三层是两个绝招');

ok(lib.前置通了(图, '门派拳脚', []).通 === false, '没解锁基本功 → 门派拳脚的前置不通');
ok(lib.前置通了(图, '门派拳脚', ['基本拳脚']).通 === true, '解锁了基本功 → 前置通了');
ok(lib.前置通了(图, '绝招乙', ['基本拳脚', '门派拳脚']).缺.includes('基本内功'), '★ 绝招乙缺的是「基本内功」这一个前置');
ok(lib.前置通了(图, '不存在').通 === false, '图上没有的节点 → 不通');

const 值表 = { 基本拳脚: 0, 基本内功: 0 };
ok(lib.可解锁(图, [], 值表).length === 2, '★ 开局只有两个根节点能解锁（基本功 0 级就够）');
ok(lib.可解锁(图, ['基本拳脚'], { 基本拳脚: 50, 基本内功: 0 }).includes('门派拳脚') === false, '★ 拳脚 50 级 → 门派拳脚还解锁不了（要 60）');
ok(lib.可解锁(图, ['基本拳脚'], { 基本拳脚: 60 }).includes('门派拳脚'), '拳脚 60 级 → 门派拳脚可解锁了');
ok(lib.可解锁(图, ['基本拳脚', '基本内功'], { 基本拳脚: 60, 基本内功: 100 }).includes('门派拳脚'), '内功 100 也给绝招乙铺路');

const 距 = lib.距目标(图, [], '绝招甲');
ok(距.到了 === false && 距.步数 === 3, '★ 从零到绝招甲 = 3 步（基本拳脚 → 门派拳脚 → 绝招甲）', '实得 ' + 距.步数);
ok(距.路径[0] === '基本拳脚' && 距.路径[2] === '绝招甲', '路径顺序正确：' + 距.路径.join(' → '));
ok(lib.距目标(图, ['基本拳脚', '门派拳脚', '绝招甲'], '绝招甲').到了 === true, '已经解锁了 → 步数 0');

// ════════ E9 ════════
section('E9-a · 接取');
const 除恶 = { id: '除恶', 名: '除恶', 前置: [{ 字段: '经验', 至少: 1000 }], 类型: '计数', 需要: 15, 位: 1 };
const 持 = {};
ok(lib.canTake(除恶, { 经验: 500 }, 持, { 任务位上限: 3 }).可以 === false, '经验不够 → 接不了');
const 缺 = lib.canTake(除恶, { 经验: 500 }, 持, { 任务位上限: 3 }).缺;
ok(缺[0].字段 === '经验' && 缺[0].需 === 1000, '★ 缺项可读：经验 还差 500');
ok(lib.take(除恶, { 经验: 2000 }, 持, { 任务位上限: 3 }).可以 === true, '条件够 → 接下来了');
ok(持['除恶'].状态 === '进行' && 持['除恶'].进度 === 0, '新接的任务是「进行 0」');
ok(lib.canTake(除恶, { 经验: 2000 }, 持, { 任务位上限: 3 }).可以 === false, '★ 同一件不能接第二次（已在做）');

// 任务位
const 持2 = {};
lib.take({ id: 'a', 名: 'a', 前置: [] }, {}, 持2, { 任务位上限: 2 });
lib.take({ id: 'b', 名: 'b', 前置: [] }, {}, 持2, { 任务位上限: 2 });
ok(lib.canTake({ id: 'c', 名: 'c', 前置: [] }, {}, 持2, { 任务位上限: 2 }).可以 === false, '★ 任务位满了（2/2）');
const 持3 = { a: { 状态: '完成' }, b: { 状态: '进行' } };
ok(lib.canTake({ id: 'c', 名: 'c', 前置: [] }, {}, 持3, { 任务位上限: 2 }).可以 === true, '★ 完成的不占位（1 件在做，还能再接一件）');

section('E9-b · 进度');
lib.推进(除恶, 持, { 量: 5 });
ok(持['除恶'].进度 === 5 && 持['除恶'].状态 === '进行', '计数型：推进到 5/15，还在做');
lib.推进(除恶, 持, { 量: 10 });
ok(持['除恶'].状态 === '完成', '★ 凑够 15 → 自动置为完成');

const 打BOSS = { id: '打BOSS', 名: '打BOSS', 类型: '判定', 需要: 1 };
const 持4 = { 打BOSS: { 名: '打BOSS', 进度: 0, 状态: '进行' } };
lib.推进(打BOSS, 持4, { 成: false });
ok(持4['打BOSS'].状态 === '失败', '★ 判定型：一次失败就是失败，没有中间态');
const 持5 = { 打BOSS: { 名: '打BOSS', 进度: 0, 状态: '进行' } };
lib.推进(打BOSS, 持5, { 成: true });
ok(持5['打BOSS'].状态 === '完成', '判定型：成了就是完成');

section('E9-c · 结算（★ 失败也是结算）');
const 女角任务 = { id: '她的托付', 名: '她的托付', 类型: '判定', 需要: 1,
  完成后果: { 好感度: 8 }, 失败后果: { 好感度: -6 } };
const 持6 = { '她的托付': { 名: '她的托付', 进度: 0, 状态: '完成' } };
const 状态 = { 好感度: 30 };
const 结 = lib.结账(女角任务, 持6, 状态);
ok(结.了结 === true && 状态.好感度 === 38, '完成 → 好感 +8（30 → 38）');
ok(持6['她的托付'] === undefined, '★ 不可重复的任务，结算后从持有表清掉');

const 持7 = { '她的托付': { 名: '她的托付', 进度: 0, 状态: '失败' } };
const 状态2 = { 好感度: 30 };
lib.结账(女角任务, 持7, 状态2);
ok(状态2.好感度 === 24, '★★ 失败也照结算：好感 −6（30 → 24）—— 不是「什么都不发生」');

const 还没完 = lib.finished(女角任务, { '她的托付': { 状态: '进行' } });
ok(还没完.了结 === false, '还在做的 → 不结算');

const 可重 = { id: '搬石头', 名: '搬石头', 类型: '计数', 需要: 1, 可重复: true, 完成后果: { 潜能: 5 } };
