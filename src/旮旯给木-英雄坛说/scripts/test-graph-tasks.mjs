section('C6-b · 改图（★ 玩家自定义生成，参考色色灵感状态栏的天赋树）');
const 图2 = { 节点: [
  { id: '根', 名: '根', 前置: [], 需要: [] },
  { id: '中', 名: '中', 前置: ['根'], 需要: [] },
] };
const 代价表 = { 动作: { 加节点: { 经验: 100, 潜能: 200 }, 删节点: { 经验: 50 }, 改门槛: { 经验: 20 } }, 每次递增: 0.5 };

ok(lib.校验改动(图2, { 动作: '加节点', 节点: { id: '新' } }).合法 === true, '加一个没前置的节点 → 合法');
ok(lib.校验改动(图2, { 动作: '加节点', 节点: { id: '根' } }).合法 === false, '★ 加一个已存在的 id → 不合法（会撞）');
ok(lib.校验改动(图2, { 动作: '加节点', 节点: { id: '新2', 前置: ['不存在'] } }).合法 === false, '★ 前置指向不存在的节点 → 不合法（会留悬空边）');
ok(lib.校验改动(图2, { 动作: '删节点', id: '根' }).合法 === false, '★★ 删「根」不合法 —— 还有「中」依赖它（直接删会留悬空前置）');
ok(lib.校验改动(图2, { 动作: '删节点', id: '根' }).依赖.includes('中'), '并说清是谁在依赖：中');
ok(lib.校验改动(图2, { 动作: '删节点', id: '中' }).合法 === true, '删没被依赖的 → 合法');

ok(lib.算改动代价({ 动作: '加节点' }, 代价表, 0).经验 === 100, '第一次改：加节点 100 经验');
ok(lib.算改动代价({ 动作: '加节点' }, 代价表, 2).经验 === 200, '★ 改过 2 次之后：100 × (1 + 0.5×2) = 200（越改越贵）');
ok(lib.算改动代价({ 动作: '改门槛' }, 代价表, 0).经验 === 20, '改门槛比加节点便宜');

const 值 = { 经验: 1000, 潜能: 1000 };
const 改1 = lib.改图(图2, { 动作: '加节点', 节点: { id: '新', 前置: ['中'] } }, 代价表, 值, 0);
ok(改1.可以 === true, '一次完整的改图：成功了');
ok(改1.图.节点.length === 3, '图真的多了一个节点');
ok(值.经验 === 900 && 值.潜能 === 800, '★ 代价扣了：经验 1000→900、潜能 1000→800');
ok(改1.改了几次 === 1, '记下「改了几次」= 1');
ok(图2.节点.length === 2, '★★ 原图没被动过（改的是副本）—— 这就是「落盘失败不用退费」的底气');

const 值2 = { 经验: 10, 潜能: 10 };
