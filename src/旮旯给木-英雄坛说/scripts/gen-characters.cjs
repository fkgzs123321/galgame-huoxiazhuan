// 严格按 skills 的 contents-creation/character/ 组织：
//
//   基础信息.yaml      基本信息 / 外貌特征 / 背景设定 / 关系设定
//                      （basic-info.md：外貌只写能认出她的特征；背景只写有实际影响的事；
//                        关系写具体画面不写抽象评价）
