//                      （personality-palette.md：衍生是调色盘的核心，每个性格 2-3 条）
//   NSFW反差与剧情线.yaml  NSFW 反差 + 剧情线 + 选项池
//
// ── ★ 女角的色气内容为什么要拆成两半（2026-09-18 用户定）────────────
//   一份女角内容拆成「六档共用」和「每档各自」两部分：
//
//   ① 六档共用的 → NSFW反差与剧情线.yaml
//      她是谁 / 她的骚 / 身体 / 骚的反应 / 感官 / 语录 / 身体模板
//      （这些不管在哪一档都不变）
//
//   ② 每档各自的 → NSFW_陌生.yaml / NSFW_相识.yaml / … / NSFW_可婚.yaml
//      门槛 / 到这里会怎样 / 心理 / 身体边界 / 台词 / NSFW
//      （006 档各写各的，每档写详细）
//
//   **为什么要拆**：不拆的话，六档必须整份读进上下文 ——
//   结果就是每档只能写三两句（写多了太占地方），而且六档互相看着像。
//   拆开之后，读到她现在那一档就只给她那一档，别的不进 ——
//   这样每档才敢写详细，档与档之间也才会真的不一样。
//
//   **靠什么只读一档**：每档挂一条门控（写在 tavern-cards-state.json 里）——
//   只有 关系.<她>.关系阶段 等于这一档的名字时，那份文件才会被读。
//   门控条目名形如 `李青照_NSFW_亲密`，part 归 other。
//   ★ 注意：这种门控条目必须用 constant（不能用 selective）——
//     EJS 门控和关键词触发是两种机制，不并用（用 selective 会让 keys 变空，永不触发）。
//   ★ skill configuration.md:49 说「EJS 条目（@@if 前缀）在同 part 中最多计为 1」
//     → 35 位 × 6 档 = 210 条，预算上只算 1 条。
//     引擎模板/scripts/verify-prompt-budget.mjs 里的 MUTEX_GROUPS 已加对应规则
//     （`_NSFW_(陌生|相识|一见如故|亲密|热情如火|可婚)$`）。
//
//   **源在哪**：都是 底座_yingxiong/女角设定.yaml ——
//   每位写一个 NSFW.阶段，里面放六个档的键，本脚本自动拆成文件并生成清单。
//   清单落在 scripts/gen-char-stages.json，注册用 scripts/ 里配套的方式（见下）。
//
// ⚠️ 三面性**不在这里生成**：
//   tri-faceted.md 要求每张面五部件齐全，其中「语料」要 5-10 句纯对话，
//   且「语料必须从调色盘移出」（也就是先有定稿的调色盘）。本卡暂不做三面性，
//   等调色盘定稿后再补 —— 硬凑出来的三面性会让 AI 把连贯的人演成换频道。
//
// 用法: node scripts/gen-characters.cjs
// ════════════════════════════════════════════════════════════
