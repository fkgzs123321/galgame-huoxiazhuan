// ════════════════════════════════════════════════════════════
// 强化（四段式 + 垫子保底）测试 —— 从 机制/物品引擎.txt 抽真代码跑
//   出处：参考项目「主神空间」的装备强化
// ════════════════════════════════════════════════════════════
const fs = require('fs');
const 源 = fs.readFileSync('src/旮旯给木-英雄坛说/机制/物品引擎.txt', 'utf8');
const 段s = [...源.matchAll(/<%([\s\S]*?)%>/g)].map(m => m[1]);
let 码 = 段s.join('\n').replace(/\/\*[\s\S]*?\*\//g, '');
const 工厂 = new Function('getvar', 'var 自 = this;\n' + 码 + '\nreturn 自;');
const I = 工厂.call({}, () => undefined);

// 契约参数（照 强化.yaml 抄）
const CFG = {
  上限: 16,
  每层倍率: 0.1,
  每层材料: { 铁: 2, 灵石: 1 },
  保护石: { 门槛: 7 },
  垫子: { 上限: 10 },
  成功率表: [
    { 从: 0, 到: 1, 成功率: 1.00, 失败: '必成' },
    { 从: 1, 到: 2, 成功率: 1.00, 失败: '必成' },
    { 从: 2, 到: 3, 成功率: 1.00, 失败: '必成' },
    { 从: 3, 到: 4, 成功率: 0.95, 失败: '掉1级', 区: '降级区' },
    { 从: 4, 到: 5, 成功率: 0.90, 失败: '掉1级', 区: '降级区' },
    { 从: 5, 到: 6, 成功率: 0.80, 失败: '掉1级', 区: '降级区' },
    { 从: 6, 到: 7, 成功率: 0.75, 失败: '掉1级', 区: '降级区' },
    { 从: 7, 到: 8, 成功率: 0.62, 失败: '归零', 区: '归零区' },
    { 从: 8, 到: 9, 成功率: 0.54, 失败: '归零', 区: '归零区' },
    { 从: 9, 到: 10, 成功率: 0.41, 失败: '归零', 区: '归零区' },
    { 从: 10, 到: 11, 成功率: 0.34, 失败: '分解', 区: '分解区' },
    { 从: 11, 到: 16, 成功率: 0.20, 失败: '分解', 区: '分解区' },
  ],
};

let 过 = 0, 败 = 0;
function 测(名, 条, 看) { if (条) { 过++; console.log('  ✅ ' + 名); } else { 败++; console.log('  ❌ ' + 名 + '   → ' + JSON.stringify(看)); } }

console.log('═════ 强化（四段式 + 垫子）测试 ═════\n');

// ── ① 三个分界线 ──
console.log('【一、三段分界线】出处：主神空间');
测('+0~+2 必成（成功率 1.0）', I.强化档(0, CFG).成功率 === 1 && I.强化档(2, CFG).成功率 === 1, [I.强化档(0, CFG), I.强化档(2, CFG)]);
测('★ +3 起进入降级区，失败掉 1 级', I.强化档(3, CFG).区 === '降级区' && I.强化档(3, CFG).失败 === '掉1级', I.强化档(3, CFG));
测('★ +7 起进入归零区，失败归零', I.强化档(7, CFG).区 === '归零区' && I.强化档(7, CFG).失败 === '归零', I.强化档(7, CFG));
测('★ +10 起进入分解区，失败没了', I.强化档(10, CFG).区 === '分解区' && I.强化档(10, CFG).失败 === '分解', I.强化档(10, CFG));
测('成功率单调递减（+3 → +10）', I.强化档(3, CFG).成功率 > I.强化档(7, CFG).成功率 && I.强化档(7, CFG).成功率 > I.强化档(10, CFG).成功率, null);

// ── ② 失败后果的正确映射 ──
console.log('\n【二、失败后果】');
测('归零 → 层数 0，东西还在', I.应用失败(9, '归零').层数 === 0 && I.应用失败(9, '归零').没了 === false, I.应用失败(9, '归零'));
测('★ 分解 → 层数 0 且 没了', I.应用失败(12, '分解').层数 === 0 && I.应用失败(12, '分解').没了 === true, I.应用失败(12, '分解'));
测('掉1级 → 层数 −1', I.应用失败(5, '掉1级').层数 === 4, I.应用失败(5, '掉1级'));
测('保护石 → 无变化（停在原地）', I.应用失败(9, '无变化').层数 === 9, I.应用失败(9, '无变化'));

// ── ③ 强化符 ──
console.log('\n【三、强化符 +12%】');
{
  const 无 = I.强化判定(7, CFG, () => 0.99, {});          // 掷 0.99 必败
  const 有 = I.强化判定(7, CFG, () => 0.99, { 强化符: true });
  测('强化符把成功率 +12%', 有.成功率 === Math.round((0.62 + 0.12) * 1000) / 1000, 有.成功率);
  测('★ 临界值靠符翻盘（0.70 < 0.74）', I.强化判定(7, CFG, () => 0.70, {}).成功 === false && I.强化判定(7, CFG, () => 0.70, { 强化符: true }).成功 === true, null);
}

// ── ④ 保护石 ──
console.log('\n【四、保护石】（+7 起可用，失败不归零不分解）');
{
  const 无 = I.强化判定(9, CFG, () => 0.99, {});
  const 有 = I.强化判定(9, CFG, () => 0.99, { 保护石: true });
  测('★ 无石 → 归零', 无.失败后果 === '归零' && 无.新层数 === 0, 无.失败后果);
  测('★ 有石 → 停在原地（层数不变）', 有.新层数 === 9 && 有.护住了 === true, 有);
  测('★ +6 时石无效（门槛 +7）', I.强化判定(6, CFG, () => 0.99, { 保护石: true }).新层数 === 5, I.强化判定(6, CFG, () => 0.99, { 保护石: true }).新层数);
  测('★ +12 有石 → 东西不会没', I.强化判定(12, CFG, () => 0.99, { 保护石: true }).没了 === false, null);
}

// ── ⑤ 垫子保底 ──
console.log('\n【五、垫子保底】只有真的【分解】才计数');
{
  const 分解 = I.强化判定(12, CFG, () => 0.99, {});       // 无石 → 分解
  测('★ 分解 → 垫子 +1', 分解.没了 === true && 分解.垫子 === 1, 分解.垫子);
  const 归零 = I.强化判定(9, CFG, () => 0.99, {});
  测('★ 归零 → 垫子【不】涨（重要）', 归零.垫子 === 0, 归零.垫子);
  const 掉级 = I.强化判定(5, CFG, () => 0.99, {});
  测('★ 掉级 → 垫子【不】涨', 掉级.垫子 === 0, 掉级.垫子);

  const 满 = I.强化判定(15, CFG, () => 0.99, { 垫子: 10 });
  测('★★ 垫子满 → 必成（哪怕掷 0.99）', 满.成功 === true && 满.用了垫子 === true, 满);
  测('★ 用掉后垫子清零', 满.垫子 === 0, 满.垫子);
  测('垫子累加：9 → 10', I.垫子加一(9, CFG) === 10, I.垫子加一(9, CFG));
  测('垫子封顶 10', I.垫子加一(10, CFG) === 10, I.垫子加一(10, CFG));
}

// ── ⑥ 材料递增 ──
console.log('\n【六、材料】');
{
  const 一 = I.强化材料(0, CFG), 十 = I.强化材料(9, CFG);
  测('第 1 层要 铁2 灵石1', 一['铁'] === 2 && 一['灵石'] === 1, 一);
  测('★ 第 10 层要 铁20 灵石10（递增）', 十['铁'] === 20 && 十['灵石'] === 10, 十);
  const 花 = I.强化花费(7, CFG, { 强化符: true, 保护石: true });
  测('花费清单含符与石', 花.清单.join('').includes('强化符') && 花.清单.join('').includes('保护石'), 花.清单);
}

// ── ⑦ 结束强化（兑现）──
console.log('\n【七、结束强化】把 +号 兑现成加成');
{
  const 物 = { 名: '钢刀', 加成: { 攻击: 20 } };
  const r0 = I.结束强化(物, 0, CFG);
  const r10 = I.结束强化(物, 10, CFG);
  测('0 层加成不变（×1.0）', r0.加成.攻击 === 20, r0.加成);
  测('★ 10 层加成 ×2.0（20 → 40）', r10.加成.攻击 === 40, r10.加成);
  测('★ 每 4 级一条词缀（10 级 = 2 条）', r10.词缀数 === 2, r10.词缀数);
}

// ── ⑧ 统计：从头强到 +16 会碎几次 ──
console.log('\n【八、模拟：1000 次「从 +0 一路点到底」的两种打法】');
{
  // ① 裸冲（不带保护石）→ 会碎
  let 碎1 = 0, 高1 = 0;
  for (let k = 0; k < 1000; k++) {
    let 层 = 0, 垫 = 0, 步 = 0;
    while (层 < 16 && 步 < 200) {
      步++;
      const r = I.强化判定(层, CFG, Math.random, { 垫子: 垫 });
      层 = r.新层数; 垫 = r.垫子;
      if (r.没了) { 碎1++; break; }
    }
    高1 = Math.max(高1, 层);
  }
  测('★ 裸冲会碎（有风险）', 碎1 > 0, 碎1);
  console.log('     （裸冲碎了 ' + 碎1 + ' / 1000 次，最高摸到 +' + 高1 + '）');

  // ② 带保护石（+7 起挂）→ 不会碎
  let 碎2 = 0, 高2 = 0;
  for (let k = 0; k < 1000; k++) {
    let 层 = 0, 垫 = 0, 步 = 0;
    while (层 < 16 && 步 < 200) {
      步++;
      const r = I.强化判定(层, CFG, Math.random, { 垫子: 垫, 保护石: 层 >= 7 });
      层 = r.新层数; 垫 = r.垫子;
      if (r.没了) { 碎2++; break; }
    }
    高2 = Math.max(高2, 层);
  }
  测('★ 带保护石 → 一次都不碎', 碎2 === 0, 碎2);
  测('★ 带石能上到高位（≥ +10）', 高2 >= 10, 高2);
  console.log('     （带石 0 次碎，最高摸到 +' + 高2 + '）');

  // ③ 对比：保护石确实有意义
  测('★ 保护石的效果可测（裸冲碎 > 0 且带石 = 0）', 碎1 > 0 && 碎2 === 0, [碎1, 碎2]);
}

console.log('\n═════════════════════════════');
console.log('通过 ' + 过 + ' ｜ 失败 ' + 败);
process.exit(败 ? 1 : 0);
