const fs = require('fs');
const path = require('path');

const ROOT = 'E:/Games/写卡/tavern_helper_template';
const SRC = path.join(ROOT, 'src', '旮旯给木-同级生2');
const DST = path.join(ROOT, 'src', '旮旯给木-英雄坛说');
const 底座ID = 'yingxiong';

// ── 目录树 ──
const DIRS = [
  '世界书/世界观/引擎',
  `世界书/世界观/底座_${底座ID}`,
  '世界书/扮演准则',
  '世界书/时间线/plot',
  '世界书/地理',
  '世界书/角色/屏幕外的她',
  `世界书/角色/底座_${底座ID}`,
  '世界书/角色/主角',
  '世界书/NPC',
  '世界书/阶段指导',
  '世界书/事件',
  '世界书/变量',
  `底座_${底座ID}`,
  '机制',
  '正则',
  '脚本',
  '开场白/initvar',
  'scripts',
];
for (const d of DIRS) fs.mkdirSync(path.join(DST, d), { recursive: true });

// ── 禁用词（引擎层红线：不出现任何世界观/角色/地点/道具名）──
// 分两组：euphoria 专属 + nanpa2 专属。出现任意一个 = 它是要素，不许留在引擎层。
const 禁用 = [
  // euphoria
  '密室', '合欢', '安藤', '莳羽', '葵菜', '白夜', '真中', '帆刈', '乐园计划',
  '鬼畜', '学园篇', '记忆篇', '处刑', '电椅', '监视器', '装置房', '底座_euphoria',
  // nanpa2
  '八十八町', '八十八学园', '鸣泽', '水野', '筱原', '南川', '加藤', '舞岛', '杉本',
  '都筑', '野野村', '安田', '田中美沙', '片桐', '永岛', '川尻', '长冈', '西御寺',
  '天道新干线', '如月町', '底座_nanpa2',
];

// ── 待搬清单（相对 SRC）──
const 候选 = [
  // 世界观/引擎 → 世界规则（AI 行为之外的规则）
  ...['四态循环', '反抗与判定', '兴奋度机制', '出招', '交互循环', '剧情推进', '边界情况', '离线行动']
    .map(n => `世界书/世界观/引擎/${n}.yaml`),
  // 扮演准则 → AI 行为
  ...['加载纪律', '判定引擎', '思维链', '叙述准则', '感知禁令', '玩家的输入']
    .map(n => `世界书/扮演准则/${n}.yaml`),
  // 阶段指导（聚合条目）
  '世界书/阶段指导/阶段指导.yaml',
  '世界书/阶段指导/熟练度阶段.yaml',
  // 屏幕外的她（E6 载体）—— 她的手段是通用层，换游戏不换脑子
  ...['温砚', '丰娆', '舒晏', '唐响', '沈眠', '莫漾', '纪清', '郁灼']
    .map(n => `世界书/角色/屏幕外的她/${n}.yaml`),
  // 机制层实现
  '机制/判定引擎.txt',
];

// ── 通用化：引擎层不许出现具体人名（判据 2）──
// 同级生2 版遗留两处例子，搬运时按它自己已有的做法通用化（都子 → 「底座清单里新出现的目标」）
const 通用化 = [
  ['「叫她一声唯」「替她挡一次西御寺」', '「叫她的名字」「替她挡一次对她有威胁的那个人」'],
  ['叫她一声唯', '叫她的名字'],
  ['替她挡一次西御寺', '替她挡一次对她有威胁的那个人'],
];

// ── 路径改写：nanpa2 → yingxiong（接口引用，不是内容）──
function 改写文本(t) {
  for (const [a, b] of 通用化) t = t.split(a).join(b);
  return t
    .replaceAll('世界观/底座_nanpa2/', `世界观/底座_${底座ID}/`)
    .replaceAll('角色/底座_nanpa2/', `角色/底座_${底座ID}/`)
    .replaceAll("=== 'nanpa2'", `=== '${底座ID}'`)
    .replaceAll('底座_nanpa2', `底座_${底座ID}`);
}

const 已搬 = [];
const 未搬 = [];
for (const rel of 候选) {
  const s = path.join(SRC, rel);
  if (!fs.existsSync(s)) { 未搬.push([rel, '源文件不存在']); continue; }
  // ★ 先改写（接口），再判禁用词（内容）—— 顺序不能反，否则路径引用会被误判成内容泄漏
  const t = 改写文本(fs.readFileSync(s, 'utf8'));
  const 命中 = 禁用.filter(w => t.includes(w));
  if (命中.length) { 未搬.push([rel, '含禁用词：' + 命中.join(' / ')]); continue; }
  const d = path.join(DST, rel);
  fs.mkdirSync(path.dirname(d), { recursive: true });
  fs.writeFileSync(d, t);
  已搬.push(rel);
}

console.log(`目标：src/${path.basename(DST)}   底座 id = ${底座ID}`);
console.log(`\n已搬 ${已搬.length} 条（零耦合，路径已改写）：`);
已搬.forEach(x => console.log('  ' + x));
if (未搬.length) {
  console.log(`\n未搬 ${未搬.length} 条（需人工处理）：`);
  未搬.forEach(([r, w]) => console.log('  ' + r + '\n      ' + w));
}
