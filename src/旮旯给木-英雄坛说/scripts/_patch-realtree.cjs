// ★ 真技能树：父→子结构（childIds 分叉）+ 树形布局 + 折线连线 + 节点可点
const fs = require('fs');
const p = 'src/旮旯给木-英雄坛说/正则/_面板逻辑.js';
let t = fs.readFileSync(p, 'utf8');

const 真树 = [
  '  /* ════════════════════════════════════════════════════════════',
  '     技能树（★ 真树：父 → 子，一个节点可以分叉出多个子节点）',
  '',
  '     结构照 V3.738 的做法：index.nodes[id] = { 名, parentId, childIds }',
  '     依赖关系从契约推：',
  '       · 根   = 十门基本武功',
  '       · 中   = 门派武功（挂在门派上）',
  '       · 叶   = 绝招（★ 它条件里提到哪些功夫，就连到哪些节点 —— 这就是「分叉」）',
  '     ════════════════════════════════════════════════════════════ */',
  '  function 建树() {',
  '    var 节点 = {}, 根s = [], 序 = 0;',
  '    function 加(名, 父, 类, 品, 附) {',
  '      var id = "n" + (序++);',
  '      节点[id] = { id: id, 名: 名, 父: 父 || null, 子: [], 类: 类, 品: 品, 附: 附 || "" };',
  '      if (父 && 节点[父]) 节点[父].子.push(id);',
  '      else 根s.push(id);',
  '      return id;',
  '    }',
  '    // ── ① 根：十门基本功 ──',
  '    var 基表 = {};',
  '    (D.基本武功 || []).forEach(function (n) {',
  '      基表[n] = 加(n, null, "基本", "q1");',
  '    });',
  '    // ── ② 门派层：每个门派一个「门派」节点，下面挂它的功法 ──',
  '    var 武 = D.门派武功 || {};',
  '    var 当前派 = (状态.场景 || {}).当前门派;',
  '    var 门派根 = {};',
  '    Object.keys(武).forEach(function (派名) {',
  '      var 是当前 = (派名 === 当前派);',
  '      门派根[派名] = 加(派名 + "派", null, "门派", "q2", 是当前 ? "当前门派" : "");',
  '      var 列 = 武[派名] || [];',
  '      列.forEach(function (武名, i) {',
  '        var 品 = i === 0 ? "q2" : (i === 列.length - 1 ? "q4" : (i === 1 ? "q2" : "q3"));',
  '        加(武名, 门派根[派名], "门派武功", 品);',
  '      });',
  '    });',
  '    // ── ③ 叶层：绝招。★ 它条件提到哪些功夫，就连到哪些节点（分叉的来源）──',
  '    var 名到id = {};',
  '    Object.keys(节点).forEach(function (id) { 名到id[节点[id].名] = id; });',
  '    (D.绝招 || []).forEach(function (j) {',
  '      var 条 = String(j.条件 || "");',
  '      // 从条件里认出提到的功夫名',
  '      var 依赖 = Object.keys(名到id).filter(function (n) { return n.length >= 3 && 条.indexOf(n) >= 0; });',
  '      var 品 = (条.match(/≥|>=/g) || []).length >= 2 ? "q4" : "q3";',
  '      var id = 加(j.名, null, "绝招", 品, "冷却 " + (j.冷却 == null ? "—" : j.冷却));',
  '      // ★ 一个绝招可以挂在多个父下 —— 这就是交叉与分叉',
  '      if (依赖.length) {',
  '        依赖.forEach(function (n) {',
  '          var pid = 名到id[n];',
  '          if (!pid) return;',
  '          节点[id].父 = pid;',
  '          节点[pid].子.push(id);',
  '          var ri = 根s.indexOf(id); if (ri >= 0) 根s.splice(ri, 1);',
  '        });',
  '        // 若原本无父（不可能走到这），兜底挂到第一个依赖',
  '        if (根s.indexOf(id) >= 0 && 依赖[0]) { /* 已处理 */ }',
  '      }',
  '    });',
  '    return { 节点: 节点, 根: 根s };',
  '  }',
  '',
  '  /* ── 树形布局：递归算坐标（列 = 深度，行 = 叶子序）── */',
  '  function 布局(树) {',
  '    var 节点 = 树.节点;',
  '    var X0 = 10, 列宽 = 132, 行高 = 30, 已放 = {};',
  '    var 最深 = 0, 行数 = 0;',
  '    function 放(id, 深, 起行) {',
  '      var n = 节点[id];',
  '      if (!n || 已放[id]) return 起行;',
  '      var 子活 = (n.子 || []).filter(function (c) { return 节点[c]; });',
  '      var 本行;',
  '      if (!子活.length) { 本行 = 起行; 行数 = Math.max(行数, 起行 + 1); }',
  '      else {',
  '        var 行 = 起行;',
  '        for (var i = 0; i < 子活.length; i++) 行 = 放(子活[i], 深 + 1, 行);',
  '        本行 = (起行 + 行 - 1) / 2;',
  '      }',
  '      已放[id] = { x: X0 + 深 * 列宽, y: 0 };',
  '      已放[id].y = 本行 * 行高 + 22;',
  '      最深 = Math.max(最深, 深);',
  '      return 本行 + 1;',
  '    }',
  '    var 行 = 0;',
  '    for (var i = 0; i < 树.根.length; i++) 行 = 放(树.根[i], 0, 行);',
  '    return { 位: 已放, 宽: X0 * 2 + (最深 + 1) * 列宽, 高: Math.max(80, 行数 * 行高 + 44) };',
  '  }',
  '',
  '  /* ── 画树（SVG：先连线，再节点）── */',
  '  function 画技能树() {',
  '    var 树 = 建树();',
  '    var L = 布局(树);',
  '    if (!Object.keys(树.节点).length) return \'<div class="yx-e">契约层还没填技能树。</div>\';',
  '    var 技 = (状态.技能 || {}).基本 || {}, 门技 = (状态.技能 || {}).门派 || {};',
  '    var 已 = {};',
  '    for (var k in 技) 已[k] = 数(技[k]);',
  '    for (var j in 门技) 已[j] = 数(门技[j]);',
  '    var s = \'<svg viewBox="0 0 \' + L.宽 + " " + L.高 + \'" width="\' + L.宽 + \'" height="\' + L.高 + \'" style="min-width:100%">\';',
  '    // ① 先画边（父子折线）',
  '    Object.keys(树.节点).forEach(function (id) {',
  '      var n = 树.节点[id];',
  '      var p = L.位[id];',
  '      if (!p) return;',
  '      (n.子 || []).forEach(function (c) {',
  '        var q = L.位[c];',
  '        if (!q) return;',
  '        // ★ 折线：横出去 → 竖下来 → 横进去（树的标准画法）',
  '        var mx = p.x + 58;',
  '        s += \'<path d="M\' + (p.x + 116) + " " + p.y + " H" + mx + " V" + q.y + " H" + q.x + \'" fill="none" stroke="var(--ln3)" stroke-width="1" opacity=".7"/>\';',
  '      });',
  '    });',
  '    // ② 再画节点',
  '    Object.keys(树.节点).forEach(function (id) {',
  '      var n = 树.节点[id];',
  '      var p = L.位[id];',
  '      if (!p) return;',
  '      var 色 = 档色(n.品);',
  '      var v = 数(已[n.名]);',
  '      var 有 = v > 0;',
  '      var 宽 = 116, 高 = 22;',
  '      s += \'<g class="yx-tn" data-tn="\' + E(n.名) + \'" style="cursor:pointer">\';',
  '      s += \'<rect x="\' + p.x + \'" y="\' + (p.y - 11) + \'" width="\' + 宽 + \'" height="\' + 高 + \'" rx="5" \'',
  '        + \'fill="\' + (有 ? 色 + "26" : "var(--b0)") + \'" stroke="\' + 色 + \'" stroke-width="\' + (有 ? 1.2 : 0.6) + \'" opacity="\' + (有 ? 1 : 0.75) + \'"/>\';',
  '      s += \'<text x="\' + (p.x + 9) + \'" y="\' + (p.y + 4) + \'" fill="\' + 色 + \'" font-size="11" \'',
  '        + \'font-weight="\' + (有 ? 500 : 400) + \'" opacity="\' + (有 ? 1 : 0.85) + \'">\' + E(n.名) + "</text>";',
  '      if (有) s += \'<text x="\' + (p.x + 宽 - 8) + \'" y="\' + (p.y + 4) + \'" text-anchor="end" fill="\' + 色 + \'" font-size="10">\' + v + "</text>";',
  '      s += "</g>";',
  '    });',
  '    s += "</svg>";',
  '    return s;',
  '  }',
  '',
].join('\n');

// 替换旧的 画树 与 判绝招够没
const a = t.indexOf('  function 画树() {');
const b = t.indexOf('  /* ── 行囊 ── */');
if (a < 0 || b < 0) { console.error('找不到 画树 ' + a + ' ' + b); process.exit(1); }
t = t.slice(0, a) + 真树 + t.slice(b);

// 技能页里那一处调用改成 画技能树
t = t.replace("+ '<div class=\"yx-tree\">' + 画树() + '</div>'", "+ '<div class=\"yx-tree\">' + 画技能树() + '</div>'");

// 节点点击 → 详情
t = t.replace('    // ── 技能格 ──', [
  '    // ── 技能树节点 ──',
  '    [].forEach.call(document.querySelectorAll(".yx-tn"), function (c) {',
  '      c.addEventListener("click", function () { 开技能(c.getAttribute("data-tn")); });',
  '    });',
  '',
  '    // ── 技能格 ──',
].join('\n'));

fs.writeFileSync(p, t);
console.log('✅ 真技能树：父→子结构（childIds 分叉）+ 树形布局 + 折线连线 + 节点可点');
console.log('   文件 ' + Math.round(Buffer.byteLength(t, 'utf8') / 1024) + ' KB');
