let 做 = 0;
for (const f of fs.readdirSync(目录)) {
  if (!f.endsWith('.yaml')) continue;
  const 名 = f.replace('.yaml', '');
  const 章 = 各章[名];
  if (!章) continue;
  let t = 读(path.join(目录, f));
  if (t.includes('她的表现（八套速查）')) continue;

  const L = ['', '她的表现（八套速查）:', '  说明: \'★ 同一章，八个人做法完全不同。照当前「她.人设」取对应那一行\'', '  通用: \'（见上一行的「她的性子怎么表现」）\''];
  for (const [k, v] of Object.entries(章)) {
    L.push('  ' + k + ": '" + v.replace(/'/g, '') + "'");
  }
  L.push('  贯穿全书:');
  for (const [k, v] of Object.entries(基调)) {
    L.push('    ' + k + ": '" + v.replace(/'/g, '') + "'");
  }
  t = t.replace(/\s*$/, '') + '\n' + L.join('\n') + '\n';
  fs.writeFileSync(path.join(目录, f), t);
  console.log('  ✅ ' + 名 + '　+' + Math.round(Buffer.byteLength(L.join('\n'), 'utf8') / 1024 * 10) / 10 + ' KB');
  做++;
}
