// 加「面板配置」契约 —— 通用面板的开关层
const fs = require('fs');
const p = 'src/旮旯给木-英雄坛说/底座_yingxiong/物品与品质表.yaml';
let t = fs.readFileSync(p, 'utf8');

const 面板配置 = `
# ════════════════════════════════════════════════════════════
# 面板配置 —— ★ 通用面板的「开关层」
#
# 用户定的架构：**面板就是交互台，它是通用的，要考虑其他游戏。**
# 所以面板提供一套【通用交互能力】，而【这个底座开放哪些】写在这里。
#
# 换游戏时：面板代码一字不改，只改本节。
# ════════════════════════════════════════════════════════════
面板配置:
  说明: '通用面板的开关。语义：玩家的操作等同于「她在操作」——他是在替她按键。'
  分界: |
    · 操作类（他在动 / 她在操作）→ 面板给按钮
      （装备 / 使用 / 强化 / 加点 / 接任务 / 打人 …）
    · 状态类（她的状态是结果，不是操作）→ 面板只显示，不给控件
      （兴奋度 / 周期 / 倾向 / 目的进度）
    · 唯一属于玩家自己的 → 出招层：眼睁睁看着 / 拒绝某个选项 / 自定义

  开放:
    物品: [装备, 使用, 丢弃, 强化]
    技能: [请教, 强化, 突破]
    任务: [接取, 推进, 放弃]
    穿着: [换上, 脱下]
    战斗: [挑对手, 看上一场]
    交易: [买入, 卖出]
  暂不开放:
    兴奋度: '★ 设定原文：界面上没有任何提示，只能靠 <user> 自己盯着摄像头看'
    周期: '周期是剧情结果（孕 / 养伤 / 闭关），不是玩家起的'
    她的倾向: '倾向暗示只在出招层用光标位置表现，面板不重复'
    目的进度: '她在推的东西，只显示不操作'

  通用性备注: |
    ★ 这套「开放 / 暂不开放」是**契约声明**，不是写死在面板里的。
    另一个底座（仙侠 / 火影 / 魔兽）如果开放不同的交互，
    只改这一节，面板照旧读它决定显示哪些按钮。
`;

if (!t.includes('面板配置:')) {
  t = t.replace(/^物品与品质|^meta:/m, 面板配置 + '\nmeta:');
  fs.writeFileSync(p, t);
  console.log('✅ 契约加了「面板配置」');
} else console.log('（已有，跳过）');

const YAML = require('E:/Games/写卡/tavern_helper_template/node_modules/yaml');
const o = YAML.parse(fs.readFileSync(p, 'utf8'));
console.log('   顶层键: ' + Object.keys(o).join(' / '));
console.log('   开放: ' + JSON.stringify(o.面板配置 ? o.面板配置.开放 : null));
