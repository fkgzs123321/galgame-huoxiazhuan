// 修门派提取（列表不是字典）+ 补真技能树 / 绝招表 / 公式
const fs = require('fs');
const p = 'src/旮旯给木-英雄坛说/scripts/gen-panel.cjs';
let t = fs.readFileSync(p, 'utf8');

// ① 门派：源是列表，每项 { id, 名, 所在地, 特色, 入门条件, 师承[], 功法[], 绝招[] }
const 旧 = t.match(/\/\/ ── 武功（从门派表抽[\s\S]*?^}\n/m);
const 新 = `// ── 门派（源是列表，每项带师承/功法/绝招）──
const 门派列 = Array.isArray(门派表.门派) ? 门派表.门派 : [];
const 门派 = {};
const 绝招 = [];
for (const m of 门派列) {
  if (!m || !m.名) continue;
  门派[m.名] = {
    id: m.id, 所在地: m.所在地 || '', 特色: m.特色 || '', 入门条件: m.入门条件 || '',
    师承: m.师承 || [], 功法: m.功法 || [],
  };
  for (const j of (m.绝招 || [])) {
    绝招.push({ 派: m.名, 名: j.名, 条件: j.条件 || '', 效果: j.效果 || '', 冷却: j.冷却 });
  }
}
// 基本武功（状态表给的清单）
const 基本武功 = (状态表.技能 || {}).基本武功 || [];
const 门派武功 = (状态表.技能 || {}).门派武功 || {};

// 技能树：三层 —— 基本武功 → 门派武功 → 绝招
const 技能树 = {
  基本: 基本武功,
  门派: 门派武功,
  绝招,
};
`;
if (旧) { t = t.replace(旧[0], 新); console.log('✅ 门派提取已改成列表 + 技能树三层'); }
else console.log('⚠️ 门派段没匹配上');

// ② 数据包：加技能树 / 绝招 / 基本武功
t = t.replace('  门派, 武功,', '  门派, 武功, 技能树, 绝招, 基本武功, 门派武功,');
// 旁支/叛师也带上
t = t.replace('const 门派表 = 读(path.join(契约, \'门派表.yaml\'), {});',
  'const 门派表 = 读(path.join(契约, \'门派表.yaml\'), {});\nconst 旁支 = 门派表.旁支 || {};\nconst 叛师 = 门派表.叛师 || {};');
t = t.replace('  门派, 武功, 技能树, 绝招, 基本武功, 门派武功,', '  门派, 武功, 技能树, 绝招, 基本武功, 门派武功, 旁支, 叛师,');

fs.writeFileSync(p, t);
console.log('✅ 生成器已更新');
