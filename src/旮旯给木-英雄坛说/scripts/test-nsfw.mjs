#!/usr/bin/env node
// ════════════════════════════════════════════════════════════
// test-nsfw.mjs · NSFW 引擎测试（E17 穿着 / E18 两层 / E19 周期 / E20 反应）
//
// ★ 这份测试盯着三个「AI 最容易写错的地方」：
//   ① 两层写反（把临时痕迹写进基线 / 把长期特征写进即时）
//   ② 换成场景之后没清即时层（或把基线也清了）
//   ③ 兴奋度一上来就满格（没有递进）
//
// 用法: node scripts/test-nsfw.mjs
// ════════════════════════════════════════════════════════════
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const F = path.resolve(path.join(__dirname, '..', '机制', 'NSFW引擎.txt'));
if (!fs.existsSync(F)) { console.error('[FAIL] 找不到 ' + F); process.exit(2); }
const code = [...fs.readFileSync(F, 'utf8').matchAll(/<%([\s\S]*?)%>/g)].map((m) => m[1]).join('\n');
for (const n of ['从外往里脱', '写基线', '起周期', '推兴奋']) {
  if (!new RegExp(n).test(code)) { console.error('[FAIL] 未提取到 ' + n); process.exit(2); }
}
const lib = new Function('getvar', code + '\nreturn this;').call({}, () => null);

let pass = 0, fail = 0;
const ok = (c, n, e = '') => { if (c) { pass++; console.log('  [OK]   ' + n); } else { fail++; console.log('  [FAIL] ' + n + (e ? '  → ' + e : '')); } };
const section = (t) => console.log('\n' + t);

console.log('='.repeat(74));
console.log('NSFW 引擎测试 · E17 穿着 / E18 两层 / E19 周期 / E20 反应');
console.log('='.repeat(74));

// ════════ E17 ════════
section('E17 · 穿着（6 部位 + 脱衣顺序）');
const 穿 = {};
lib.新穿着(穿);
ok(Object.keys(穿).length === 6, '★ 初始化出 6 个部位（上装/下装/内衣/袜子/鞋子/饰品）');
lib.穿上(穿, '上装', '外衫');
lib.穿上(穿, '内衣', '里衣');
lib.穿上(穿, '鞋子', '布鞋');
lib.穿上(穿, '下装', '罗裙');
lib.穿上(穿, '袜子', '布袜');
lib.穿上(穿, '饰品', '玉簪');
ok(lib.穿着几件(穿) === 6, '穿上六件 → 数得出 6');
ok(lib.穿上(穿, '不存在的部位', 'x').可以 === false, '没有这个部位 → 穿不上');

ok(lib.露不露(穿).程度 === '整齐', '穿齐了 → 程度「整齐」');
const 脱1 = lib.从外往里脱(穿, 1);
ok(["上装","下装","鞋子"].includes(脱1.脱了[0].部位), '★ 第一件脱的是最外层（层次 1）', '实得 ' + (脱1.脱了[0] || {}).部位);
const 脱2 = lib.从外往里脱(穿, 2);
lib.从外往里脱(穿, 3);   // 把剩下三件也脱了，才谈得上「全裸」
ok(脱2.脱了.map(x=>x.部位).indexOf('内衣') < 0, '★★ 连脱两件都还没动到里衣（层次 1,1）', '实得 ' + 脱2.脱了.map(x=>x.部位).join('/'));
ok(lib.穿着几件(穿) === 0, '脱光了');
ok(lib.露不露(穿).程度 === '全裸', '★ 一件不剩 → 全裸');

const 穿2 = {};
lib.新穿着(穿2);
lib.穿上(穿2, '内衣', '里衣');
ok(lib.露不露(穿2).程度 === '只剩袜子鞋子' || lib.露不露(穿2).程度 === '内衣已除' || lib.露不露(穿2).程度 === '半褪',
  '只剩一件贴身 → 程度不是「整齐」（露不露判得出来）', lib.露不露(穿2).程度);

// ════════ E18 ════════
section('E18 · 身体两层（★ 本引擎的核心：基线与即时不能混）');
const 档 = {};
lib.新档案(档);
ok(Object.keys(档.基线).length === 5 && Object.keys(档.即时).length === 5, '两层各初始化 5 个字段');

ok(lib.写基线(档, '三围', 'B88-W60-H90，腰细').可以 === true, '写长期特征进基线 → 通过');
ok(lib.写基线(档, '三围', '正在被揉').可以 === false, '★★ 把「正在被揉」往基线写 → 拦下（那是即时层）');
ok(lib.写基线(档, '三围', '腰上留着红印').可以 === false, '★★ 「红印」也拦下');
ok(lib.写基线(档, '三围', '被揉出的红肿').疑点.length > 0, '并说清疑点在哪');

ok(lib.写即时(档, '胸部', '充血红肿').可以 === true, '写场景级反应进即时层 → 通过');
ok(lib.写即时(档, '胸部', 'B88，常年如此').可以 === false, '★★ 把「B88」写进即时层 → 拦下（那是基线）');
ok(lib.写即时(档, '胸部', '天生就这样').可以 === false, '★★ 「天生」也拦下');

const 清 = lib.换场景(档);
ok(清.基线保留 === 5, '★ 换场景：基线 5 项全留着（这是两层分开的意义）');
let 空 = true;
for (const k in 档.即时) if (档.即时[k]) 空 = false;
ok(空, '★ 换场景：即时层清空（临时反应不该跨场景）');
ok(档.基线['三围'] === 'B88-W60-H90，腰细', '基线内容原样保留');

// ════════ E19 ════════
section('E19 · 周期状态（怀孕 / 伤愈 / 毒发 / 闭关，同一个形状）');
const 周期表 = {
  孕: {
    id: '孕', 名: '孕', 总轮: 9, 叠加上限: 1, 可中断: true,
    阶段: [
      { 到第几轮: 0, 名: '初期', 表现: '看不出，只是容易累' },
      { 到第几轮: 3, 名: '中期', 表现: '小腹开始显，衣服紧了' },
      { 到第几轮: 6, 名: '后期', 表现: '走路慢了，容易气短' },
    ],
    结束时: { 人口: 1 },
    中断后果: { 身体: -20 },
  },
  伤: { id: '伤', 名: '养伤', 总轮: 4, 可中断: false, 结束时: { 生命: 50 } },
};
const 值 = { 人口: 0, 身体: 100, 生命: 10 };

const 起 = lib.起周期(周期表, 值, '孕', 0);
ok(起.可以 === true && 起.总轮 === 9, '起了「孕」这个周期（9 轮）');
ok(lib.起周期(周期表, 值, '不存在').可以 === false, '没定义的周期 → 起不来');
ok(lib.起周期(周期表, 值, '孕').可以 === false, '★ 叠加上限 1 → 不能再叠');

let 阶变化 = [];
for (let i = 0; i < 4; i++) 阶变化 = 阶变化.concat(lib.推周期(周期表, 值, 1, {}).阶段变化);
ok(阶变化.length >= 1, '★ 过 4 轮期间发生过阶段变化（累积看，不能只看最后一次）');
ok(lib.周期状态(周期表, 值)[0].当前阶段 === '中期', '现在阶段是「中期」', lib.周期状态(周期表, 值)[0].当前阶段);
ok(lib.周期状态(周期表, 值)[0].还剩 === 5, '还剩 5 轮');

const 后半 = lib.推周期(周期表, 值, 5, {});
ok(后半.结束.length === 1, '★ 走满 9 轮 → 结束');
ok(值.人口 === 1, '★★ 结束时落账（人口 +1）—— 结束不是「什么都不发生」');
ok(lib.周期状态(周期表, 值).length === 0, '结束后从表里清掉');

const 值2 = { 人口: 0, 身体: 100 };
lib.起周期(周期表, 值2, '孕', 0);
ok(lib.断周期(周期表, 值2, '孕').可以 === true, '可以中断（这个周期可中断）');
ok(值2.身体 === 80, '★★ 中断也落账（身体 -20）—— 中断同样不是「什么都不发生」');

const 值3 = { 生命: 10 };
lib.起周期(周期表, 值3, '伤', 0);
ok(lib.断周期(周期表, 值3, '伤').可以 === false, '★ 标了不可中断的 → 断不掉');
ok(值3.生命 === 10, '断不掉时什么都没变');

// ════════ E20 ════════
section('E20 · 反应推演（★ 不许一上来就满格）');
const 档位表 = [
  { 门槛: 0, 名: '无', 部位表现: { 胸部: '未变化' } },
  { 门槛: 20, 名: '微动', 部位表现: { 胸部: '呼吸稍快' } },
  { 门槛: 50, 名: '起了', 部位表现: { 胸部: '乳尖立起' } },
  { 门槛: 80, 名: '难忍', 部位表现: { 胸部: '充血发红' } },
];
ok(lib.当前档位(档位表, 10).名 === '无', '兴奋 10 → 档位「无」');
ok(lib.当前档位(档位表, 55).名 === '起了', '兴奋 55 → 档位「起了」');
ok(lib.当前档位(档位表, 100).名 === '难忍', '兴奋 100 → 档位「难忍」');
ok(lib.部位反应(档位表, 55).胸部 === '乳尖立起', '★ 部位表现跟着档位走（AI 只读结论）');

const 推1 = lib.推兴奋(0, 100, { 上限: 100, 单轮上限: 25 });
ok(推1.现在 === 25, '★★ 单轮封顶：给 100 的增量，实际只涨 25（不许一上来就满）');
ok(推1.封顶了吗 === true, '并标明「被封顶了」');
const 推2 = lib.推兴奋(25, 25, { 上限: 100, 单轮上限: 25 });
ok(推2.现在 === 50, '再一轮 → 50（一步一步来）');
const 推3 = lib.推兴奋(50, -10, { 上限: 100, 每轮衰减: 5 });
ok(推3.现在 === 35, '★ 不给刺激时会衰减：50 -10（减值）再 -5（每轮衰减）= 35');

const 局面 = lib.局面快照({ 兴奋度: 85, 档位表, 穿着: { 上装: '', 下装: '裙', 内衣: '' } });
ok(局面.档位 === '难忍', '★ 快照：档位「难忍」');
ok(局面.穿着.程度 === '内衣已除', '★ 快照：穿着「内衣已除」');
ok(局面.快照.indexOf('难忍') >= 0 && 局面.快照.indexOf('内衣已除') >= 0, '★ 一句话快照：' + 局面.快照);

console.log('\n' + '='.repeat(74));
console.log('通过 ' + pass + ' / 失败 ' + fail);
console.log('='.repeat(74));
process.exit(fail === 0 ? 0 : 1);
