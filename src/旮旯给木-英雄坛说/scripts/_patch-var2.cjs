// ① 补建「主角」块（含 对她的了解 —— 之前只有引用没有定义）
// ② 关系网改成「唯一 id 做键」+ 别名表
const fs = require('fs');
const ip = 'src/旮旯给木-英雄坛说/世界书/变量/initvar.yaml';
let iv = fs.readFileSync(ip, 'utf8');

if (!iv.includes('\n主角:')) {
  const 块 = [
    '',
    '# ── 底座层：G 主角（★ 2026-09-17 补建：之前只有引用、没有定义）──',
    '主角:',
    "  名: ''",
    '  对她的了解: 0        # 0~10：直接决定「倾向暗示」的清晰度（低=瞎猜／中=过半／高=看得出但不保证）',
    '  心性: 50            # 四天赋的余量（练武/打铁/学习时消耗，歇一歇回）',
    '  $骰子种子: 20260915  # LCG 种子（AI 不可见、不更新）',
    '',
  ].join('\n');
  iv = iv.replace('# ── 底座层：E 身体 ──', 块 + '# ── 底座层：E 身体 ──');
  console.log('✅ 加了 主角 块');
}

const 旧 = '关系网: {}';
if (iv.includes(旧)) {
  const 新 = [
    '关系网: {}',
    '# ★ 关系网的键用【唯一 id】而不是名字（出处：火影的 createSubjectId）',
    '#   为什么：AI 常写错名 / 改名 / 写简称 —— 用名字做键会「人还是那个人，关系却断了」',
    '#   约定：主体第一次出现时分配 甲_001 这样的 id，之后一律认 id',
    '关系主体: {}',
    "  # 形状：关系主体: { 甲_001: { 名: '苏晚', 别名: ['晚儿','苏姑娘'], 首次出现: '第7月' } }",
    '关系别名表: {}',
    "  # 形状：关系别名表: { '晚儿': '甲_001' }   ← AI 写别名也能认回来",
  ].join('\n');
  iv = iv.replace(旧, 新);
  console.log('✅ 关系网改成 id 做键');
}

fs.writeFileSync(ip, iv);
