const fs = require('fs');
const path = require('path');
const YAML = require('E:/Games/写卡/tavern_helper_template/node_modules/yaml');
const ROOT = 'E:/Games/写卡/tavern_helper_template';
const D = path.join(ROOT, 'src', '旮旯给木-同级生2');
const 记 = [];

// ── A 关系值 5→1 ──
{
  const p = path.join(D, '世界书/变量/initvar.yaml');
  const o = YAML.parse(fs.readFileSync(p, 'utf8'));
  let n = 0;
  if (o.女角) for (const k of Object.keys(o.女角)) {
    const v = o.女角[k] || {};
    const 新 = { 好感度: Number(v.好感度) || 0, 关系阶段: v.关系阶段 || '初识', 状态: v.状态 || '' };
    o.女角[k] = 新; n++;
  }
  if (!o.世界) o.世界 = {};
  o.世界.嫉妒值 = 0;                 // 世界级（不是每人一个）
  o.世界.关系封闭 = o.世界.关系封闭 || {};
  if (!o.主角.技能) o.主角.技能 = { 打工: 0, 学业: 0, 机车: 0 };
  fs.writeFileSync(p, YAML.stringify(o, { lineWidth: 0 }));
  记.push('A initvar：' + n + ' 位女角收成「好感度/关系阶段/状态」三项，嫉妒值升为 世界.嫉妒值，主角补 技能{打工,学业,机车}');
}

// ── A' 状态表同步 ──
{
  const p = path.join(D, '底座_nanpa2/状态表.yaml');
  let t = fs.readFileSync(p, 'utf8');
  t = t.replace(/\n  - 名: 信任度[\s\S]*?(?=\n  - 名: )/, '\n');
  t = t.replace(/\n  - 名: 嫉妒值[\s\S]*?(?=\n  - 名: )/, '\n');
  if (!t.includes('关系值只留一项')) {
    t = t.replace(/\n  - 名: 好感度/, `
  # ⚠️ 2026-09-15 用户裁决：关系值只留一项（好感度，正负皆可），阶段保留。
  #   删掉的：心动值（阈值与好感度重叠）／信任度（语义并入「欺骗扣更多好感」）／
  #   嫉妒值（升为**世界级** 世界.嫉妒值 —— 它是跨角色的，不该每人存一份）
  #   阶段的意义：不是第二个数值，是**能不能做某件事的门槛**（阶段决定可做的事不同）
  - 名: 好感度`);
    fs.writeFileSync(p, t);
    记.push("A' 状态表：删 信任度/嫉妒值，在 好感度 处写明依据与「阶段的意义」");
  }
  // 技能三条
  if (!t.includes('- 名: 打工')) {
    t = t.replace(/\n# ═+\n# 四、女角/, `
  - 名: 打工
    范围: 0 ~ 100
    初值: 0
    增长: 每次打工 +2~4（她让你去打工的日子）
    可见: 展开区
    意义: 离线行动「打工」的收益倍率。见 变量更新规则 的技能读点
    注: 同级生2 特有。原卡把它混在 12 技能里，本表只留三个真用得上的
  - 名: 学业
    范围: 0 ~ 100
    初值: 0
    增长: 上课、复习、调查 类行为 +2~4
    可见: 展开区
    意义: 结局分支与部分女角事件的门槛（3-B 的学生身份）
  - 名: 机车
    范围: 0 ~ 100
    初值: 0
    增长: 与洋子相处、骑车 类行为 +3~5
    可见: 展开区
    意义: 洋子线的关键；影响跨区域移动是否省时段

# ════════════════════════════════════════════════════════════
# 四、女角`);
    fs.writeFileSync(p, t);
    记.push('A\' 状态表：新增三个同级生2 特有技能（打工/学业/机车）');
  }
}

// ── B 「局面.当前选项」的写入规则（用户说解释不清 → 写成硬规则）──
{
  const p = path.join(D, '世界书/变量/变量更新规则.yaml');
  let t = fs.readFileSync(p, 'utf8');
  if (!t.includes('出招层要写什么')) {
    t += `
出招层要写什么（这是「她摆出的选项」进变量的唯一通道，不写前端就没东西可画）:
  谁写: AI，在每层的变量更新块里写
  局面.当前选项: 写成一个表，键是序号（"1"~"4"），每个值是
    { 文本: 她看到的选项名, 等级: micro|mid|strong|extreme|lock }
    等级与消耗的对应：micro 3~5 / mid 10~15 / strong 25~35 / extreme 50 以上 / lock 不可拒
  局面.她的倾向: 写她**将要点的**那个序号（"1"~"4"）。这是她自己的决定，AI 知道
  ⚠️ 只写序号，不在正文里写她盯着哪个 —— 正文写了赌就没了（见 叙述准则）
  什么时候清空: 这一层结算完之后，把 局面.当前选项 写成空表、局面.她的倾向 写成空串
  她转成打字态时: 局面.当前选项 留空，「她打的字」写上她打的那句（见 出招）

数值变化怎么写（正文里写出来的格式，正则靠它上色）:
  一段结算完，把变化的数写在括号里：如（反抗值 -12）（好感度 +6）
  只写真正变了的，没变的不写
`;
    fs.writeFileSync(p, t);
    记.push('B 变量更新规则：补「出招层要写什么」—— 局面.当前选项 / 她的倾向 的格式、谁写、什么时候清空');
  }
}

// ── C+D 强设定：三维修正的语义 + 技能读点 ──
{
  const p = path.join(D, '世界书/世界观/引擎/反抗与判定.yaml');
  let t = fs.readFileSync(p, 'utf8');
  if (!t.includes('三段修正各由谁负责')) {
    t += `
三段修正各由谁负责（强设定：不许混线）:
  兴奋度修正（她的状态）: 她越兴奋，鼠标越不稳，越容易点偏或被拦下。乘数 1 + 兴奋度÷100 × 0.5
    这是「她分心，所以他有机会」—— 不是她在帮他
  熟练度惩罚（她的状态）: 她玩得越熟，手越稳，越难拦。乘数 1 - 熟练度惩罚（新手 0 ／ 上手 .1 ／ 沉浸 .2 ／ 狂热 .3 ／ 收官 .4）
  三维系数（他的状态）: 他有多少底气做这个动作。乘数 0.6 + 0.8 × 三维平均 ÷ 100
  禁止: 不要把她的状态写进 <user> 的身体感受里，也不要把他的三维写进她的决策依据
  判定顺序: 先按对地方（否则未命中）→ 再乘这三个修正 → 与掷值比较

技能读点（三个技能只在下面这三处被读，别处不读）:
  打工: 离线行动「打工」的收益倍率。倍率 = 0.5 + 打工 ÷ 100
  学业: 结局分支与部分女角事件的门槛（3-B 身份相关），阈值由该事件写
  机车: 跨区域移动的时段折扣。机车 ≥ 40 时，跨区域移动少扣一档时段进度
  谁算: 引擎或前端算，AI 只读结论
`;
    fs.writeFileSync(p, t);
    记.push('C+D 反抗与判定：把兴奋度/熟练度/三维的语义切成「她的状态 vs 他的状态」，并写清三个技能的读点');
  }
}

