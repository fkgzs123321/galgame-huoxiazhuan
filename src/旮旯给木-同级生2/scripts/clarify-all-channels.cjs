// 把「我」的通道在四态下逐条写清（和 感知禁令 的三层结构对齐）
const fs = require('fs');
const path = require('path');
const YAML = require('E:/Games/写卡/tavern_helper_template/node_modules/yaml');
const D = 'E:/Games/写卡/tavern_helper_template/src/旮旯给木-同级生2';

/* ① 四态循环：每态补「「我」能做什么」 */
const p1 = path.join(D, '世界书/世界观/引擎/四态循环.yaml');
const o = YAML.parse(fs.readFileSync(p1, 'utf8'));

o['★「我」能做什么（四态逐条，和 感知禁令 的三层结构对齐）'] = {
  '在线态': '★ 只有一件事：**消耗反抗值「拒绝」或「自己来」**。这两个之外，「我」写的一切只落在他的内层 —— 念头、说不出口的话、做不到的动作，一个字的实际效果都没有',
  '暂停态': '★ **什么也做不了**。他意识清醒但不能动也出不来；「我」的输入同样只落内层',
  '离线态': '★ **「我」唯一的行动窗口**。她关了游戏，`<user>` 完全自主 —— 这一段里「我」写的东西能变成他真的行动、真的话',
  '冻结态': '★ **什么也做不了**。他意识被封存，「我」的输入到不了任何地方',
  '★ 到她那边的终点': '以上四条，她**一条都收不到**。她只看见 <user> 做了什么，并把它当游戏自己的安排（她不在时看见「他做了点事」，也只当游戏在跑）',
  '★ 禁止': '不要写她察觉到「有人在推他」「有人在跟他作对」—— 这条线不存在',
};

/* ② 反抗与判定：把「通道」写清 */
const p2 = path.join(D, '世界书/世界观/引擎/反抗与判定.yaml');
const r = YAML.parse(fs.readFileSync(p2, 'utf8'));
r['★ 反抗值是「我」唯一的在线通道'] = {
  '是什么': '在线态下，「我」想让 <user> 做出与她安排不同的行为，**只能靠拒绝或自己来，并且必须扣反抗值**',
  '不够就做不成': '反抗值低于消耗时，按钮按下也不生效。这一层就此照她的来',
  '不花反抗值的输入': '★ 只落 <user> 的内层。念头可以有，行为不会有。不要写成「他硬撑着没照做」—— 撑不住就是照做',
  '她的那一侧': '★ 她收不到任何东西。他行为异常时，她只从自己那边找理由（累了/熬夜/玩太久/游戏又出 bug），这些异常对她的进度、兴奋度、情绪、熟练度是零影响',
};
fs.writeFileSync(p2, YAML.stringify(r, { lineWidth: 0 }));

/* ③ 离线行动：点明那是「我」的窗口 */
const p3 = path.join(D, '世界书/世界观/引擎/离线行动.yaml');
let t3 = fs.readFileSync(p3, 'utf8');
if (!t3.includes('★ 这是')) {
  t3 = t3.replace(/^([^\n]*\n)/, '$1\n★ 这是「我」唯一的行动窗口 —— 在线态下「我」只能靠反抗值拒绝，只有这一段能真的动。\n');
  fs.writeFileSync(p3, t3);
}

/* ④ 叙述准则：补「我」怎么写 */
const p4 = path.join(D, '世界书/扮演准则/叙述准则.yaml');
let t4 = fs.readFileSync(p4, 'utf8');
if (!t4.includes('★ 写「我」的时候')) {
  t4 = t4.replace(/\s*$/, '\n\n★ 写「我」的时候:\n  - 「我」是屏幕外的真人，**不在 <user> 体内**。不要写「被囚禁在他身体里」这类比喻\n  - 「我」的话只落他的内层：念头、忍住的话、做不到的动作\n  - 他要真做出不一样的行为，只有两条路：在线扣反抗值拒绝 / 离线自主行动\n  - 指代：<user> 是第一人称「我」，屏幕外那个女声写「她」。不要用「玩家」「用户」这类出戏词\n');
  fs.writeFileSync(p4, t4);
}
console.log('✅ 四态循环：补「我」能做什么（四态逐条）');
console.log('✅ 反抗与判定：补「反抗值是唯一的在线通道」');
console.log('✅ 离线行动：点明「唯一的行动窗口」');
console.log('✅ 叙述准则：补「写「我」的时候」');
for (const [p, n] of [[p1, '四态循环'], [p2, '反抗与判定'], [p4, '叙述准则']]) {
  const s = fs.statSync(p).size;
  console.log('   ' + n + ' ' + s + ' 字节' + (s > 5000 ? ' ⚠ 超' : ' ✅'));
}
