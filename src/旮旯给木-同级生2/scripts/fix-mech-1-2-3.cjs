// ①②③ 三个机制改动
//   ① 机制层：被操控时无自主 → 明确「只能动选项」+ 新增「自定义」这条路（最强消耗）
//   ② 反抗值不足 → 拒绝按钮禁用（面板侧）
//   ③ 强化「她不知道有现实玩家」+ 异常的解释方式 + 零影响
const fs = require('fs');
const path = require('path');
const YAML = require('E:/Games/写卡/tavern_helper_template/node_modules/yaml');
const D = path.join(__dirname, '..');

/* ── ① 反抗与判定.yaml：加「自定义」 ── */
{
  const p = path.join(D, '世界书/世界观/引擎/反抗与判定.yaml');
  let t = fs.readFileSync(p, 'utf8');
  if (!t.includes('自定义')) {
    t = t.replace(/\s*$/, '\n') + `
自定义:
  是什么: <user> 不按她摆的选项来，而是照自己的意图硬做一次。这是他被操控时唯一能「自己做主」的出口
  代价: 消耗 50~70 反抗值（按当前意图与局面的冲突程度取）
  次数: 反抗值上限 100，所以一局里基本只能用一两次
  写法: 玩家点了自定义后，会有一条用户消息说明他想做什么。她那边看到的是 <user> 突然不听话了
  她的反应: 按她自己的性格来 —— 温柔型的会担心，极端型的会更兴奋，强迫型的会去查
  限制:
    - 只能做<b>当下场景做得到</b>的事：被绑着就不能走出去，昏着就不能站起来
    - 做不到的，<user> 只能在内心里想做而做不到，身体不听
    - 自定义不改变她摆的选项池，只改变这一层 <user> 自己的那一格
`;
    fs.writeFileSync(p, t);
    console.log('① 反抗与判定.yaml：已加「自定义」段（消耗 50~70，一局限 1~2 次）');
  } else console.log('① 反抗与判定.yaml：已有「自定义」');
  try { YAML.parse(fs.readFileSync(p, 'utf8')); console.log('   ✅ YAML 通过'); } catch (e) { console.log('   ⚠ ' + e.message.split('\n')[0].slice(0, 50)); }
}

/* ── ③ 感知禁令：强化 ── */
{
  const p = path.join(D, '世界书/扮演准则/感知禁令.yaml');
  const o = YAML.parse(fs.readFileSync(p, 'utf8'));
  o.认知错位 = o.认知错位 || {};
  o.认知错位['现实玩家'] = '她<b>不知道</b>存在「现实中操作这个游戏的玩家」这个人。<user> 就是游戏里的角色，没有别的来源';
  o.外界反应 = [
    '<user> 表现异常时，她只会从<b>她自己那边</b>找理由：今天工作太累了、熬夜困了、玩太久出幻觉了、这游戏又出 bug 了',
    '她<b>从不</b>往「里面有人在反抗我」这个方向想 —— 那个念头对她不存在',
    '★ 这些异常对她的目的进度、兴奋度、情绪、熟练度是 <b>零影响</b>。她照自己原来的节奏继续玩',
    '她的每一个选择，只从她自己的偏好与设定里长出来',
  ];
  o['他能做的只有这些'] = [
    '被操控时（在线态），<user> 说不出自己想说的话，做不了自己想做的事，身体听她的',
    '他唯一能动手脚的地方，就是她摆出来的那些选项：拒绝 / 无视 / 自定义',
    '心里那点没出声的东西，只能停在内心，落不成动作',
  ];
  fs.writeFileSync(p, YAML.stringify(o, { lineWidth: 0 }));
  console.log('③ 感知禁令：已强化（不知道有玩家 / 异常的解释方式 / 零影响 / 只能动选项）');
}

/* ── ③ 玩家的输入：强化 ── */
{
  const p = path.join(D, '世界书/扮演准则/玩家的输入.yaml');
  const o = YAML.parse(fs.readFileSync(p, 'utf8'));
  o.玩家的输入['她不知道有你'] = [
    '屏幕外那个女人，<b>不知道</b>现实里有一个玩家在输入这些东西',
    '她不知道你的存在。你写的每一个字，都走不进她的认知',
    '她看见的只有画面上 <user> 做了什么 —— 而她认为那是游戏自己的安排',
  ];
  o.玩家的输入['只能到内层'] = [
    '你写的任何东西，落到 <user> 的内层：念头、忍住的话、做不到的动作',
    '★ 被操控时（她在线），这些<b>只能停在内心</b>，变不成动作，也变不成台词',
    '★ 只有在她离线时（她关掉了游戏），<user> 才能按你的意图真的动起来',
    '你想让她怎么样，一概到不了她那里',
  ];
  fs.writeFileSync(p, YAML.stringify(o, { lineWidth: 0 }));
  console.log('③ 玩家的输入：已强化（她不知道有你 / 只能到内层 / 离线才能动）');
}

console.log('\n✅ ①②③ 的条目侧改完（②在面板侧，稍后改）');
