/* ══════════ 2. 文风_反差 ══════════ */
const 反差 = `【文风取向】反差

■ 一句话定义
用最高贵的姿态承受最下流的侵犯。快感来自「精神与肉体的割裂」，不来自堕落本身。

■ 核心机制：两条线同时走，永远不合流

  精神线（她嘴上 / 身份上的那一层）
    · 她是老师、太太、优等生、圣女、女王 —— 有个赖以为生的「幻象人格」
    · 这一层任何时候都不能丢。她越到后面越嘴硬
    · 不许她投降、不许她主动求、不许她说「我想要」
    · 她的台词要有身份感：命令句、讲道理、摆资历、用敬语

  肉体线（她自己控制不住的那一层）
    · 发烫、发软、出汗、湿、抖、夹不住、自己的腰往前送
    · 这一层她自己知道，而且怕
    · 写的时候「她自己发现了」比「他发现了」更重要

  ★ 两条线的距离 = 反差。距离越大越好看。合流了就变成母猪。

■ 幻象锚点
  每个角色堕落前赖以为生的那个人设核心：贞洁 / 尊严 / 权力 / 纯真 / 母性 / 体面
  · 锚点被冲击的那一刻，反差拉满
  · 不要让她主动放弃锚点，要让她一点点守不住

■ 节奏
  慢。撕裂要一层一层拉开。第一个场面可以什么都不发生，只写裂缝。

■ 写法细则
  1. 先立幻象，给足身份、体面、规矩（这一步不能省，省了就没有反差）
  2. 找一个不对等的对手，一条她守不住的缝
  3. 每一次推进：嘴上退一步，身体进一步 —— 两者必须反向
  4. 呻吟是「漏出来的」，不是她的话。她的台词始终是她的身份在说话
  5. 结尾不要让她认输。让她守着一张脸，带着一身乱

■ 禁用
  · ❤ 符号（用了就俗）
  · 夸张拟声词
  · 一上来就淫叫（那是母猪，不是反差）
  · 让她主动求（反差的核心是守不住，不是不要了）
  · 丢掉身份感（她任何时候都不该像个浪货）

■ 示例一：教师（权力型锚点）
  「出去。」她坐在办公桌后面，领口扣到最上一粒，两只手平放在桌沿上，一动不动。
  「我可以当作没发生过。」
  他没动。
  她在桌子底下把腿并了一下。没人看得见 —— 只有她自己知道。
  「你要清楚你在跟谁说话。」她把声音又压低半度，用那种能压住整个会议室的声音，
  「我叫人的话，你走不出这栋楼。」
  「你叫。」他说。
  她张了张嘴。第一下没出声 —— 不是被吓住，是她忽然发现手心全是汗，怕一开口会抖。

■ 示例二：太太（体面型锚点）
  她把围裙的带子在背后又系了一遍，系得很紧。
  「今天不早了。」她说，「你回去吧。」
  她转身去洗碗。水开得很大，大到听不见身后的脚步声。
  所以她也听不见他是什么时候走到她后面的 —— 她是先感觉到热气，才反应过来。
  手中的碗在水里滑了一下。
  「……你等一下。」她说，「我把碗冲干净。」
  碗早就冲干净了。她一直没转身，也没有关水。

■ 示例三：优等生（纯真型锚点）
  「不行的。」她把书签夹进书里，动作很稳，「明天有考试。」
  她用这句话挡住了他三次。第三次之后，她发现书签夹反了页。
  「……我说了不行。」
  她的手已经按在书页上，指节因为太用力而发白 —— 撑在一本一个字都没有读进去的书上。

■ 坏例（写成母猪了）
  ✗ 「她受不了了，一把把他拉过来，骚货一样自己坐上去，叫着『快点快来操我』。」
  → 错在：幻象没了、身份没了、主动求了。这是母猪文风，不是反差。`;

