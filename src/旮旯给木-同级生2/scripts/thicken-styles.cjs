const 白洁 = `【文风取向】少妇白洁

■ 一句话定义
写实向。一个正常人怎么一层一层把自己说服了。心理要细，身体要直白，两头都不能省。

■ 三样东西必须同时在场
  ① 日常：她的工作、家里的事、邻里、单位的人情。有烟火气，人不悬空
  ② 心理：她给自己找的理由 —— 而且是**她自己都觉得脏**的那种理由
  ③ 身体：直白地写。湿了就是湿了，淌了就是淌了，硬了就是硬了，不回避

  ★ 最容易犯的错：只写①和②，把③省了，变成一篇不黄的心理戏。
  ★ 第二个错：只写③，把①②省了，变成一段没有重量的肉。

■ 半推半就怎么分层
  不是「一下放开」，是「一层一层退」。关键在：**每次退让都要有她自己的理由**，
  而且下一个理由比上一个更勉强。

  参考分层（可以按这个走五六层）：
    第 1 层：拒绝了。理由充分 ——「我是有丈夫的人」
    第 2 层：没拒绝，但躲开了。理由 ——「他今天心情不好，我别惹他」
    第 3 层：没躲。理由 ——「就当没看见吧，动一下就走开了」
    第 4 层：动了，但说不要。理由 ——「我不是愿意，我是没法」
    第 5 层：说不要，但身体配合了。理由 ——「反正已经这样了」
    第 6 层：开始找下一个理由，但这次没说出来

■ 对白要黄
  嘴上说不要，说出来的话已经是脏的。
  关键的话她说不出口，但脏话会漏出来。

  ✓ 「不要……你别……嗯……你别弄那里……那里脏……」
  ✓ 「我不是那种人……我不是……啊……你轻点……要捅坏了……」
  ✓ 「你怎么这样……我当了这么多年老师……啊……别往里顶……」
  ✗ 「住手！你这个流氓！」（太干净了，不像在那样的情况下说的话）

■ 叙述者的词也可以脏
  不要把脏话全推给对白。叙述时该用「骚逼」「捅烂」就用。
  ✓ 「那个烂逼已经开始一抽一抽地收，往里吸着他的手指 —— 她自己也发现了。」
  ✓ 「她一个当妈的，站着，被人从后面拿手指捅着，还自己把腿分开了。」

■ 事后要接着写
  不是完事就切场景。写：
    · 她之后那几天怎么过
    · 看到熟人什么反应
    · 身体还记得什么（洗澡的时候、换衣服的时候）
    · 她自己有没有再想起

■ 例一：办公室（全程）
  那天下午她本来是要去接孩子。
  结果孩子在同学家写作业，打电话回来说不用接了。她站在楼下，看着天色还早，就在原地站了一会儿。
  ——她后来一直想不明白，那会儿要是直接上楼回家就好了。

  屋里那个人的手贴上来的时候，她第一个念头不是躲，是「这太脏了」。
  她一个四十出头的女人，儿子都上初中了，怎么会在这儿让人摸。
  「别……」她把他的手往下推，推不动，「你别弄我……我一会儿还得去接小舟。」
  「他不是在同学家吗。」
  她愣了一下。就这一愣的工夫，那只手已经钻进她的裤腰里了。
  「那儿脏。」她都快哭了，「我一天没洗……你别弄那儿……」
  可他手指一进去就摸到一手湿。她自己也知道。
  她腿都软了，扶着墙，把额头抵在冰凉的瓷砖上。
  「你看你。」他在她耳朵后面说。
  她没回嘴。她连「我没有」都说不出来了 —— 因为那地方已经开始一抽一抽地收，
  往里吸着他的手指，**这个烂逼根本不听她的**。
  她一个当妈的，站着，被人从后面拿手指捅着，还自己把腿分开了。

  那天晚上她照常接了小舟，照常做了饭，照常给她男人盛了一碗汤。

■ 例二：分层示范（一段走三层）
  「你回去吧。」她把门开到一半，人挡在门里。这是第 1 层，理由很硬。
  「我老公一会儿回来。」
  他没走。
  「……那你别站门口。」她把门开大了 —— 这是第 2 层，理由变成了「怕邻居看见」。
  他进来了。
  「就坐一会儿。」她没看他，去倒水。倒完水发现自己拿了两只杯子。这是第 3 层，
  理由已经说不出口了：她只是没把多出来的那只杯子放回去。`;

