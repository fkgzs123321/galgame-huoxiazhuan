/* ══════════ 1. 无尽骚妈（写厚）══════════ */
const 骚妈 = `【文风取向】无尽骚妈

■ 一句话定义
描写的颗粒度极高。核心不是「让所有人骚」，是**笔法**。

■ 五种手法（这是这套文风的全部）

  ① 远看与近看的反差
     先给一个体面的整体印象（身份、衣着、场合都正经），再贴到近处写细节。
     落差本身就是戏。**不要一开始就写透。**
     · 远看：灰色羊绒大衣扣到最上一粒，头发盘得整整齐齐，手里拎着的文件袋是皮的
     · 近看：大衣里面只有一件吊带，米白色，薄到能透出底下那圈乳晕的边
     ★ 顺序不能反。先让她体面三句，再揭。

  ② 衣料的物理性
     写材质、厚薄、光泽、来历，以及它在动作下怎么变形。
     **先把「隔着布」写好，再写露出来。**
     · 真丝：会贴、会透、会滑
     · 白棉：洗多了会软、会绷、会显出轮廓
     · 针织：会起球、会挂住、会被撑开
     · 校服裙：压得住走路，跑起来就不行
     ★ 「隔着」比「露出来」更有戏。脱之前那一段才是重点。

  ③ 身体的动态形变
     写形状在动的时候发生什么（晃、压、挤、勒出印子、被顶出一个尖）。
     不写静止的形容词。
     ✗「她胸部很大」
     ✓「她一弯腰，那两团就坠下去，坠成两个沉甸甸的袋子形状」

  ④ 旁人的视线
     周围人看见什么、怎么躲开视线、咽口水 —— **用他人反应代替直接描写**。
     ·「电梯里的那个年轻人一直在看楼层数字，耳朵是红的。」
     ★ 这一招最省字，也最高级。

  ⑤ 语言的质地
     口语、直白、脏话照说，但**句子要顺**；台词跟这个人的身份对得上。
     ★ 一个书店店员不会用总裁的措辞。

■ 实样一（远看近看 + 衣料）
  从走廊那头看过来，她是这层楼最体面的一个。灰色羊绒大衣扣到最上面一粒，头发盘得整整齐齐，
  手里拎着的文件袋是皮的。谁见了都会让一步。
  可如果站到她跟前，近到能看清那件大衣的纹理 ——
  大衣里面只有一件吊带。真丝的，米白色，薄到能透出底下那圈乳晕的边。
  她一动，那两团就跟着在领口里换位置，把真丝顶出一小片鼓。
  电梯里的那个年轻人一直在看楼层数字，耳朵是红的。
  「今天有点热。」她说，抬手把大衣解开了一粒。

■ 实样二（身体的动态 + 旁边人的视线）
  她端着那盘菜从厨房出来，弯着腰往桌上放。衬衫的下摆从腰上离开，露出一截后背，
  又随着她直起身滑回去。她弟弟在对面坐着，筷子掉在了地上。
  「你怎么了。」
  「……没。」

■ 实样三（不骚的人也用这套笔法）
  她照例把汤放在他右手边，位置每次都一样。转身的时候围裙带子在腰上松了半寸，
  她自己没察觉。做饭的这两年，她的腰细了一点，围裙还是那条围裙。
  他看了两秒，低头喝汤。

■ 禁用
  · 把不骚的人写成骚的
  · 为了露骨牺牲人物（先有人，再有身体）
  · 所有角色同一个腔调
  · 一上来就直接写裸的（那五种手法都用不上了）
` + 底线;

