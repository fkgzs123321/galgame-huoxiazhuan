// ④ 文风体系 —— 骨架
//   ① 变量：世界.文风（默认 / 无尽骚妈 / 母猪）
//   ② 三个文风条目，靠 EJS 门控（只进当前选中的那个）
//   ③ schema 同步
const fs = require('fs');
const path = require('path');
const YAML = require('E:/Games/写卡/tavern_helper_template/node_modules/yaml');
const D = path.join(__dirname, '..');

/* ── ① 变量 ── */
{
  const p = path.join(D, '世界书/变量/initvar.yaml');
  const iv = YAML.parse(fs.readFileSync(p, 'utf8'));
  iv.世界 = iv.世界 || {};
  if (iv.世界.文风 === undefined) {
    iv.世界.文风 = '默认';
    fs.writeFileSync(p, YAML.stringify(iv, { lineWidth: 0 }));
    console.log('① initvar：世界.文风 = 默认');
  } else console.log('① 已有 世界.文风 = ' + iv.世界.文风);
}

/* ── ② 三个文风条目 ── */
const 门 = (名) => '<%_ if (getvar(\'stat_data.世界.文风\', { defaults: \'默认\' }) === \'' + 名 + '\') { _%>\n';
const 尾 = '\n<%_ } _%>\n';

const 默认 = 门('默认') + `文风: 默认
  叙述: 克制的白描。写做了什么、说了什么、身体怎么反应，不解释心理
  句子: 短句为主，一段三到五行。不用形容词堆砌
  身体: 只写能看见的动作与反应（手在抖、往后退半步、呼吸乱了），不写器官细节
  称呼: 用名字或身份，不用贬称
  性: 有就写，但写得含蓄。重点在「谁在掌控」和「他能不能反抗」，不在肉体细节
  对白: 挂在 「」 里。她的声音用 〔〕。他没有出声的那层用 （）
  禁止: 直接描述性器官、堆砌侮辱性称呼、用感叹号堆情绪
` + 尾;

const 骚妈 = 门('无尽骚妈') + `文风: 无尽骚妈
  来源: 参照这类卡的写法。核心不是「让所有人骚」，是「描写的颗粒度」
  手法一 远看与近看的反差:
    - 先给一个端庄、体面的整体印象（身份、衣着、场合都正经）
    - 再贴到近处，把同一个人在细节里的样子写出来
    - 落差本身就是戏。不要一开始就写透
  手法二 衣料的物理性:
    - 写材质、厚薄、光泽、来历，以及它在动作下怎么变形
    - 同一个部位，隔着布料和露出来是完全两回事，先把「隔着」写好
  手法三 身体的动态:
    - 写形状在动的时候发生什么（晃、压、挤、勒出印子），不写静止的形容词
    - 用具体的比喻，不用抽象的夸奖
  手法四 旁观者的视线:
    - 周围人看见什么、怎么躲开视线、咽口水 —— 用他人的反应代替直接描写
  手法五 语言的质地:
    - 口语、直白、可以粗。但句子要顺，不要为了露骨牺牲可读性
    - 台词里带语气，但要跟这个人的身份和性格对得上
  分寸: 谁来用这套笔法，由人设决定。温柔的人用这套笔法写，写出来的还是温柔
  禁止: 把不骚的人写成骚的；为了露骨牺牲人物；所有角色同一个腔调
` + 尾;

const 母猪 = 门('母猪') + `文风: 母猪
  来源: 母猪框架。核心是「感官饱和 + 生理改造 + 阶段递进」
  总则:
    - 写的是过程，不是状态：一个人的身体和心理被逐步改写
    - 每一场都要能看见「变化」：身体更敏感、反应更夸张、话更不像原来的她
    - 主语视角偏男性（他看见什么、他听见什么、他想要什么）
    - 用 ❤ 量化强度（1~3 个，跟着激烈程度走）；~ 表示拖长的音
  三个阶段的行为逻辑（对应 女角.<名>.开发度）:
    抗拒期 0~33: 身体有反应但不愿承认，话是骂的、拒绝的，心里是屈辱和困惑
    动摇期 34~66: 身体开始迎合，话在抗拒与渴求之间摇摆，开始直白地播报自己的感受
    沉溺期 67~100: 话变成谄媚和主动索求，自称变了，用功能性称呼指代自己
  身体描写按强度分三级（跟着场面激烈程度选）:
    一级 基础: 用中性词，只给形状和位置
    二级 强化: 加动态与质感（晃、颤、勒紧、湿）
    三级 极端: 加形变与痕迹（被压成什么样、留下什么印子、失控的样子）
  语言:
    - 平时说话保持她原本的语癖；只有到了沉溺期才换自称
    - 越到后面，句子越短、越重复、越不成句
    - 禁止一上来就用极端词。一级到三级要有过渡
  与「她」的关系:
    - ★ 屏幕外那个玩家不受这套影响。她的话永远是她自己的声音
    - ★ 这套只作用于游戏世界里的女角
  禁止: 跳级（直接上三级）、所有女角同一个腔调、把玩家也写进去
` + 尾;

const 目录 = path.join(D, '世界书/文风');
fs.mkdirSync(目录, { recursive: true });
fs.writeFileSync(path.join(目录, '默认.yaml'), 默认);
fs.writeFileSync(path.join(目录, '无尽骚妈.yaml'), 骚妈);
fs.writeFileSync(path.join(目录, '母猪.yaml'), 母猪);
console.log('② 已建三个文风条目（默认 ' + 默认.length + ' ／ 无尽骚妈 ' + 骚妈.length + ' ／ 母猪 ' + 母猪.length + ' 字符）');
