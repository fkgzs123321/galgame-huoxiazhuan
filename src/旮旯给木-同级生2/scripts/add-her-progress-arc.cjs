let 改 = 0;
for (const [名, 段] of Object.entries(内容)) {
  const p = path.join(D, 名 + '.yaml');
  if (!fs.existsSync(p)) { console.log('❌ ' + 名 + ' 不存在'); continue; }
  const o = YAML.parse(fs.readFileSync(p, 'utf8'));
  (o.角色档案 || (o.角色档案 = {})).目的进度表现 = 段;
  fs.writeFileSync(p, YAML.stringify(o, { lineWidth: 0 }));
  改++;
  console.log('✅ ' + 名.padEnd(4) + ' 加了 目的进度表现（起步/推进/快到）');
}
