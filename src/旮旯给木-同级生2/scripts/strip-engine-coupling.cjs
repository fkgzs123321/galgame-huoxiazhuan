const 七个她 = ['温砚', '丰娆', '舒晏', '唐响', '沈眠', '莫漾', '纪清'];
const 待搬 = [
  ...Object.keys(替换),
  ...七个她.map(n => `角色/屏幕外的她/${n}.yaml`),
];

let 改动 = 0;
const log = [];
for (const rel of 待搬) {
  const src = path.join(SRC, rel);
  if (!fs.existsSync(src)) { log.push('⚠ 源不存在：' + rel); continue; }
  let t = fs.readFileSync(src, 'utf8');
  let n = 0;
  for (const [a, b] of (替换[rel] || [])) {
    if (!t.includes(a)) { log.push('⚠ 未命中（' + rel + '）：' + a.slice(0, 30)); continue; }
    t = t.split(a).join(b); n++;
  }
  if (/屏幕外的她/.test(rel)) {
    for (const [re, b] of 正则) {
      const m = t.match(re);
      if (m) { t = t.replace(re, b); n++; }
    }
  }
  const dst = path.join(DST, rel);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, t);
  改动 += n;
  log.push('✅ ' + rel.padEnd(34) + ' 改动 ' + n + ' 处');
}
console.log(log.join('\n'));
console.log('\n合计改动 ' + 改动 + ' 处，已写入 ' + DST);
