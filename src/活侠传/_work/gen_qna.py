# ── 解析对话体 ──
#   结构：### Q8-2 标题 / 空行 / > 提问 / 空行 / 鸟：答 / �into
def 提问答(文本: str):
    题s = []
    # 按 ### 切
    for m in re.finditer(r"^###\s*(Q[\d-]+)\s*(.*)$", 文本, re.M):
        题号 = m.group(1).strip()
        题名 = 简(m.group(2).strip())
        起 = m.end()
        下 = re.search(r"^###\s*Q", 文本[起:], re.M)
        止 = 起 + (下.start() if 下 else len(文本) - 起)
        体 = 文本[起:止]
        题s.append((题号, 题名, 体))
    return 题s


