console.log('\n══ ⑥ ★★ 传消息（沿关系网扩散）══');
{
  // ★ 关于跳数：跳数=2 意思是「熟人 → 熟人的熟人」，
  //   所以一条消息经大师兄转一道手就能到默铃那儿。这是有意的模型，不是 bug。
  const 变 = 造变量();
  初始化关系网(变);

  const 学到 = 传消息(变, '赵活', '门里要添新人', 2);
  console.log(`      从赵活传 2 手，${学到.length} 人知道: ${学到.join('、')}`);

  断言('传出去了', 学到.length > 1, 学到);
  // 赵活是玩家，不在 关系（玩家↔NPC 好感表）里，所以他的"认知"无处可记。
  // 他是消息的**起点**，不是"学到的人"。
  断言('起点（玩家）不记认知', !学到.includes('赵活'), 学到);

  // 1 手：只有直接相识且强度够的
  const 变1 = 造变量();
  初始化关系网(变1);
  const 一手 = 传消息(变1, '赵活', '门里要添新人', 1);
  console.log(`      只传 1 手，${一手.length} 人知道: ${一手.join('、')}`);
  // 赵活↔默铃 强度 15 < 门槛 30 → 一手传不到
  断言('★ 1 手时默铃收不到（强度 15 < 门槛 30）', !传得到吗(变1, '唐默铃', '门里要添新人'));
  // 赵活↔唐升 强度 40 ≥ 30 → 一手传得到
  断言('1 手时三师兄收得到（强度 40）', 传得到吗(变1, '唐升', '门里要添新人'));

  // 换个起点：从掌门出发
  const 变2 = 造变量();
  初始化关系网(变2);
  const 学到2 = 传消息(变2, '唐中翎', '有人要来拜师', 2);
  console.log(`      从掌门传 2 手，${学到2.length} 人知道: ${学到2.join('、')}`);
  断言('掌门级消息传得广', 学到2.length >= 5, 学到2);
  // 掌门↔默铃 强度 85 → 她直接就是一手
  断言('★ 默铃收得到（父女强度 85）', 传得到吗(变2, '唐默铃', '有人要来拜师'));
}

