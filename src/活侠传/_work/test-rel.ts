console.log('\n══ ⑩ 引擎原语直查 ══');
{
  // ★ 引擎的 `甲`/`乙` 字段**不是「第一个参数/第二个参数」**，
  //   而是「字典序小的那个 / 大的那个」。
  //   JS 按 UTF-16 码点比：乙(U+4E59) < 甲(U+7532)，
  //   所以 对键('乙','甲') === '乙|甲' 才是正确行为。
  //   （这一点开始被我按字面意思误解过，测试因此误报。）
  const 网: Record<string, any> = {};
  const r = L.建关系(网, '乙', '甲', '同门', 50, true);
  断言('★ 键按码点排序：乙<甲 → 乙|甲', r?.建了 === '乙|甲', r);
  const k = Object.keys(网)[0];
  断言('网里只有一条（不重复建）', Object.keys(网).length === 1, Object.keys(网));
  断言('甲字段存的是字典序小的那个', 网[k].甲 === '乙', 网[k]);
  断言('乙字段存的是字典序大的那个', 网[k].乙 === '甲', 网[k]);

  // 正着建、反着建，必须落到同一条
  const 网2: Record<string, any> = {};
  L.建关系(网2, '唐布衣', '唐铮', '同门', 50, true);
  L.建关系(网2, '唐铮', '唐布衣', '同门', 60, true);
  断言('★ 正反各建一次仍只一条', Object.keys(网2).length === 1, Object.keys(网2));
  断言('后建的覆盖了强度', Object.values(网2)[0].强度 === 60, Object.values(网2)[0]);
}

