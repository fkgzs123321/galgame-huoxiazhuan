/**
 * 精确验证防御减伤：让「命中」必然发生，看伤害是否减半。
 *
 * 办法：把对手的命中拉到极高（用一个超强对手），
 * 这样无论种子如何都会命中，就能比较防御前后的伤害。
 */
import { 出一手 } from '../脚本/战斗结算';

function 造变量(对方血上限: number) {
  return {
    世界: { 随机种子: 1 },
    你: { 轻功: 0, 八系: { 拳掌: 0, 暗器: 0 }, 战斗: { 攻击: 16, 防御: 21, 生命上限: 9999 } },
    战斗: {
      状态: '进行中', 对手: '强敌', 回合: 0,
      我方血: 9999, 我方血上限: 9999,
      对方血: 对方血上限, 对方血上限,
      气: 0, 对方气: 0,
      我方状态: {}, 对方状态: {}, 日志: '', 摘要: '', 我方防御: false,
    },
  };
}

console.log('══ 强敌（命中拉满）+ 多轮采样，比较防御前后 ══');
let 不防和 = 0;
let 防和 = 0;
let 不防命中数 = 0;
let 防命中数 = 0;
let 防御生效数 = 0;
const N = 200;

for (let i = 0; i < N; i++) {
  const s = 1 + i * 7919; // 分散的种子
  const a = 出一手({ ...造变量(210), 世界: { 随机种子: s } }, '轻攻击');
  const b = 出一手({ ...造变量(210), 世界: { 随机种子: s } }, '防御');
  if (a.报告.对方命中) {
    不防和 += a.报告.对方伤害;
    不防命中数++;
  }
  if (b.报告.对方命中) {
    防和 += b.报告.对方伤害;
    防命中数++;
  }
  if (b.报告.我方防御生效) 防御生效数++;
}

console.log(`  不防御: ${不防命中数}/${N} 次挨打，总伤 ${不防和}，均值 ${(不防和 / Math.max(1, 不防命中数)).toFixed(2)}`);
console.log(`  防御:   ${防命中数}/${N} 次挨打，总伤 ${防和}，均值 ${(防和 / Math.max(1, 防命中数)).toFixed(2)}`);
console.log(`  防御生效次数: ${防御生效数}`);
console.log();

const 均不防 = 不防和 / Math.max(1, 不防命中数);
const 均防 = 防和 / Math.max(1, 防命中数);
console.log('  伤害比 (防御/不防):', 均防 && 均不防 ? (均防 / 均不防).toFixed(3) : 'N/A');
console.log('  命中数比 (防御/不防):', 防命中数 && 不防命中数 ? (防命中数 / 不防命中数).toFixed(3) : 'N/A');
console.log();
console.log('  判定:');
console.log('    ', 防御生效数 > 0 ? '✓ 减伤分支被触发过' : '✗ 减伤分支从未触发');
console.log('    ', 均防 <= 均不防 ? '✓ 防御时挨的伤不多于不防御' : '✗ 防御反而更疼');
console.log('    ', 防命中数 <= 不防命中数 ? '✓ 防御时更不容易被打中' : '✗ 防御更容易被打中');
