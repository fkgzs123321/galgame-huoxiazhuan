const L = lib as any;

let 通过 = 0;
let 失败 = 0;

function 断言(名: string, 条件: boolean, 附加?: unknown) {
  if (条件) {
    通过++;
    console.log(`  ✓ ${名}`);
  } else {
    失败++;
    console.log(`  ✗ ${名}`);
    if (附加 !== undefined) console.log('      实际:', JSON.stringify(附加).slice(0, 300));
  }
}

function 造变量() {
  return {
    世界: {},
    你: {
      银两: 37,
      体力: { 当前: 40, 上限: 50 },
      内力: { 当前: 15, 上限: 20 },
      轻功: 10, 心相: 50, 抗毒: 0, 武学点: 120,
      八系: { 拳掌: 10, 暗器: 20 },
      战斗: { 攻击: 14, 防御: 18, 暗器威力: 16, 生命上限: 100 },
    },
    物品: {
      柴刀: { 数量: 1, 品质: '凡', 说明: '' },
      粗布衣: { 数量: 1, 品质: '凡', 说明: '' },
      鹿皮囊: { 数量: 1, 品质: '优', 说明: '' },
      金创药: { 数量: 2, 品质: '凡', 说明: '' },
      生铁: { 数量: 5, 品质: '凡', 说明: '' },
    },
    装备: { 兵器: '', 防具: '', 暗器袋: '', 饰品: '' },
    战斗: { 我方状态: {}, 气: 0 },
  };
}

console.log('══ ① 物表与品质 ══');
{
  const 柴 = 取定义('柴刀');
  断言('取得到定义', 柴.名 === '柴刀' && 柴.类 === '兵器', 柴);
  const 未知 = 取定义('不存在的东西');
  断言('未知物品有安全兜底', 未知.类 === '杂物', 未知);

  const 加 = 算加成('柴刀');
  断言('凡品柴刀 加成 = 2（1.0 倍）', 加.攻击 === 2, 加);

  const 鹿 = 算加成('鹿皮囊');
  // 优 = 1.5 倍 → 暗器威力 8*1.5 = 12
  断言('★ 优品鹿皮囊按 1.5 倍放大 → 12', 鹿.暗器威力 === 12, 鹿);

  const 柳 = 算加成('柳叶飞刀');
  // 优 = 1.5 → 12*1.5 = 18
  断言('优品飞刀 12*1.5 = 18', 柳.暗器威力 === 18, 柳);
}

console.log('\n══ ② 装备：穿 · 脱 · 加成合并 ══');
{
  const 变 = 造变量();
  const 前 = 装备后输入(变);
  console.log(`      裸装: ${JSON.stringify(前)}`);

  const r1 = 穿上(变, '兵器', '柴刀');
  断言('穿上柴刀', r1?.可以 === true, r1);
  const r2 = 穿上(变, '暗器袋', '鹿皮囊');
  断言('穿上鹿皮囊', r2?.可以 === true, r2);

  const 后 = 装备后输入(变);
  console.log(`      着装: ${JSON.stringify(后)}`);
  断言('攻击 +2（柴刀）', 后.攻击 === 前.攻击 + 2, { 前: 前.攻击, 后: 后.攻击 });
  断言('★ 暗器威力 +12（鹿皮囊优品）', 后.暗器威力 === 前.暗器威力 + 12, {
    前: 前.暗器威力, 后: 后.暗器威力,
  });

  const 明细 = 装备明细(变);
  console.log(`      明细: ${明细.map(x => `${x.槽}=${x.名}`).join(' ')}`);
  断言('明细列出 2 件', 明细.length === 2, 明细.length);

  // 换装
  const r3 = 穿上(变, '兵器', '柴刀');
  断言('重复穿同一件仍可以', r3?.可以 === true, r3);

  const r4 = 脱下(变, '兵器');
  断言('脱下成功', r4?.可以 === true, r4);
  断言('脱下后攻击回原值', 装备后输入(变).攻击 === 前.攻击, 装备后输入(变).攻击);
}

