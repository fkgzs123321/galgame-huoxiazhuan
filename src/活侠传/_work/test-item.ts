console.log('\n══ ④ 使用消耗品 ══');
{
  // ★ 体力 40，上限 50，金创药 +30 → 应当停在上限 50（不是 70）。
  //   早先这条断言写的是「+30」，那是按上限没生效的 bug 行为写的，已修正。
  const 变 = 造变量();
  const 前体 = 变.你.体力.当前;
  const r = 使用(变, '金创药', 1);
  断言('用药成功', r?.可以 === true, r);
  断言('★ 体力 40+30 被上限 50 夹住', 变.你.体力.当前 === 50, {
    前: 前体, 后: 变.你.体力.当前, 上限: 变.你.体力.上限,
  });
  断言('数量 2 → 1', 变.物品.金创药.数量 === 1, 变.物品.金创药);

  // 没到上限时应当正常加
  const 变1 = 造变量();
  变1.你.体力.当前 = 10;
  使用(变1, '金创药', 1);
  断言('体力 10+30 = 40（未触上限）', 变1.你.体力.当前 === 40, 变1.你.体力.当前);

  // 用完删除
  const 变2 = 造变量();
  变2.物品.金创药.数量 = 1;
  使用(变2, '金创药', 1);
  断言('★ 用完从背包移除', !变2.物品.金创药, 变2.物品);

  // 不能用的东西
  const 变3 = 造变量();
  const r3 = 使用(变3, '生铁', 1);
  断言('材料不能吃', r3?.可以 === false, r3);

  const r4 = 使用(变3, '金创药', 99);
  断言('数量不够被挡住', r4?.可以 === false, r4);
}

