console.log('\n══ ⑥ 前置链完整（叶氏七连）══');
{
  const 链 = 原作事件表.filter(e => e.id.startsWith('S_1_4_3_叶氏'));
  链.sort((a, b) => Number(a.id.slice(-1).charCodeAt(0)) - Number(b.id.slice(-1).charCodeAt(0)));
  console.log(`  七连共 ${链.length} 环`);
  断言('七连是 7 环', 链.length === 7, 链.map(e => e.id));
  // 第 2 环起都应有前置
  const 缺前置 = 链.slice(1).filter(e => !e.前置?.length);
  断言('★ 除第一环外都有前置', 缺前置.length === 0, 缺前置.map(e => e.id));
  // 前置指向真实存在的 id
  const ids = new Set(原作事件表.map(e => e.id));
  const 悬空: string[] = [];
  for (const e of 原作事件表) {
    for (const p of e.前置 ?? []) {
      // 允许引用「条件 id」（如 天赋_自恋）而不只是事件 id
      if (!ids.has(p) && !p.startsWith('天赋_')) 悬空.push(`${e.id} → ${p}`);
    }
  }
  断言('★ 没有悬空前置', 悬空.length === 0, 悬空);
}

console.log('\n══ ⑦ 时间窗全覆盖 ══');
{
  const 无窗 = 原作事件表.filter(e => !e.窗 || (e.窗 as any).类型 === '无');
  断言('每条都有时间窗', 无窗.length === 0, 无窗.map(e => e.id));
  const 坏 = 原作事件表.filter(e => {
    const w = e.窗 as any;
    if (w.类型 === '特定') return !Array.isArray(w.值) || w.值.length !== 3;
    if (w.类型 === '周期') return typeof w.每 !== 'number';
    return true;
  });
  断言('时间窗格式都对', 坏.length === 0, 坏.map(e => e.id));
}

