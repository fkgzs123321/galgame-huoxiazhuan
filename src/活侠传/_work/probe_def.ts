/**
 * 探查：为什么防御减伤测不出来？
 */
import { 出一手 } from '../脚本/战斗结算';

function 造变量(对手: string, 上限: number) {
  return {
    世界: { 随机种子: 5000 },
    你: { 轻功: 22, 八系: { 拳掌: 10, 暗器: 20 }, 战斗: { 攻击: 16, 防御: 21, 生命上限: 100 } },
    战斗: {
      状态: '进行中', 对手, 回合: 0,
      我方血: 100, 我方血上限: 100,
      对方血: 上限, 对方血上限: 上限,
      气: 0, 对方气: 0,
      我方状态: {}, 对方状态: {}, 日志: '', 摘要: '', 我方防御: false,
    },
  };
}

console.log('══ 不同对手下，我方挨的伤害 ══');
for (const [名, 上限] of [['杂役', 50], ['唐布衣', 170], ['唐中翎', 210]] as [string, number][]) {
  let 总 = 0;
  let 回合有伤 = 0;
  const N = 30;
  for (let i = 0; i < N; i++) {
    const r = 出一手(造变量(名, 上限), '轻攻击');
    总 += r.报告.对方伤害;
    if (r.报告.对方伤害 > 0) 回合有伤++;
  }
  const 强度 = Math.max(1, Math.round((上限 - 40) / 2));
  console.log(`  ${名.padEnd(6)} 上限${String(上限).padStart(4)} → 强度${String(强度).padStart(3)} 攻击约${Math.round(强度 * 0.6)}`);
  console.log(`         我方${N}回合共挨 ${总} 伤，有伤的回合 ${回合有伤}/${N}，均值 ${(总 / N).toFixed(2)}`);
  console.log(`         对方行动分布:`);
  const 分布: Record<string, number> = {};
  for (let i = 0; i < 30; i++) {
    const r = 出一手(造变量(名, 上限), '轻攻击');
    分布[r.报告.对方行动] = (分布[r.报告.对方行动] || 0) + 1;
  }
  console.log('        ', JSON.stringify(分布));
}

console.log();
console.log('══ 防御 vs 不防御（唐布衣，逐回合对比）══');
// ★ 每次都要新建变量 —— 出一手 会改 对方气，
//   复用同一个对象会让第二次调用拿到被改过的状态（探针踩过这个坑）。
for (let i = 0; i < 10; i++) {
  const a = 出一手(造变量('唐布衣', 170), '轻攻击');
  const b = 出一手(造变量('唐布衣', 170), '防御');
  console.log(
    `  seed 5000  不防御: 对方出「${a.报告.对方行动}」 伤害${a.报告.对方伤害}   |   防御: 对方出「${b.报告.对方行动}」 伤害${b.报告.对方伤害}`,
  );
}

console.log();
console.log('══ 连续多回合（对手会攒气，应当越打越凶）══');
{
  let 变 = 造变量('唐布衣', 170);
  for (let i = 0; i < 8; i++) {
    const r = 出一手(变, '轻攻击');
    变 = r.新变;
    console.log(
      `  第${变.战斗.回合}回合  对方出「${r.报告.对方行动}」 伤害${r.报告.对方伤害}  对方气${变.战斗.对方气}  我方血${变.战斗.我方血}`,
    );
  }
}
