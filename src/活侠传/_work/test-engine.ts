console.log('\n══ ⑪ ★ 产出字段与 schema 的交叉验证 ══');
{
  // 这个测试是为一个真实 bug 加的：
  //   早先 应用产出 用单字表（'拳'/'腿'…）匹配，而契约里写的是全名（'拳掌'/'暗器'），
  //   匹配不上 → 落到默认分支 → 写成 schema 里不存在的 `你.拳掌` → **静默无感**。
  //   只有把「契约里出现的每个字段」都拿来对一遍，才能防住这类错。

  // schema 的合法路径（与 schema.ts 对齐；改了 schema 要同步这里）
  const 合法路径 = new Set([
    '你.体力.当前', '你.内力.当前',
    '你.轻功', '你.魅力', '你.学问', '你.嘴力',
    '你.锻造', '你.炼丹', '你.武学点',
    '你.道德', '你.性情', '你.处世', '你.修养', '你.心相', '你.阴阳',
    '你.抗毒', '你.抗麻', '你.形意拳',
    '你.八系.刀剑', '你.八系.暗器', '你.八系.拳掌', '你.八系.腿法',
    '你.八系.奇门', '你.八系.软兵器', '你.八系.枪棍', '你.八系.内功',
    '你.三教.儒学', '你.三教.道学', '你.三教.释学',
    '世界.门人', '世界.向心', '世界.名声', '世界.贡献度', '世界.门派资产',
  ]);

  const 全部产出 = new Set<string>();
  for (const a of [...行动表, ...单元表] as any[]) {
    for (const k of Object.keys(a.产出 ?? {})) 全部产出.add(k);
  }
  console.log(`      契约里的产出字段: ${[...全部产出].join('、')}`);

  // ① 每个字段都能被 字段路径 表认出（认不出会 console.warn）
  const 未覆盖: string[] = [];
  const 原warn = console.warn;
  let 警告: string[] = [];
  console.warn = (...args: unknown[]) => {
    警告.push(args.map(String).join(' '));
  };

  for (const 字段 of 全部产出) {
    const 真行动 = ([...行动表, ...单元表] as any[]).find(a => a.产出 && 字段 in a.产出);
    if (!真行动) continue;
    警告 = [];
    // 单元可能需要窗口开启，但字段覆盖检查只看有没有 warn
    结算行动(造变量(), 真行动.id);
    if (警告.some(w => w.includes(字段))) 未覆盖.push(字段);
  }
  console.warn = 原warn;
  断言('★ 所有产出字段都被 字段路径 表覆盖（无静默丢弃）', 未覆盖.length === 0, 未覆盖);

  // ② 每个字段都真能改到 schema 内的值
  const 无效: string[] = [];
  for (const 字段 of 全部产出) {
    const 真行动 = ([...行动表, ...单元表] as any[]).find(a => a.产出 && 字段 in a.产出);
    if (!真行动) continue;
    const 候选 = [...合法路径].filter(p => p.endsWith(字段) || p.includes(`.${字段}`));
    if (!候选.length) {
      无效.push(字段);
      continue;
    }
    // 真跑一次，确认候选路径里至少有一个带着值变化
    const { 报告 } = 结算行动(造变量(), 真行动.id);
    if (报告.ok && !(字段 in 报告.数值变化)) {
      无效.push(`${字段}（结算没记进变化表）`);
    }
  }
  断言('★ 所有产出字段都能落到 schema 内并记入变化', 无效.length === 0, 无效);

  console.log(`      覆盖路径检查: ${全部产出.size} 个字段逐一验证完毕`);
}

