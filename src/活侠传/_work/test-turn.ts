import { 出一手, 可选行动, 克谁, 气上限 } from '../脚本/战斗结算';

let 通过 = 0;
let 失败 = 0;

function 断言(名: string, 条件: boolean, 附加?: unknown) {
  if (条件) {
    通过++;
    console.log(`  ✓ ${名}`);
  } else {
    失败++;
    console.log(`  ✗ ${名}`);
    if (附加 !== undefined) console.log('      实际:', JSON.stringify(附加).slice(0, 300));
  }
}

function 造变量(覆盖?: Record<string, unknown>) {
  return {
    世界: { 随机种子: 20260927, ...(覆盖?.世界 as object) },
    你: {
      轻功: 22,
      八系: { 拳掌: 10, 暗器: 20 },
      战斗: { 攻击: 16, 防御: 21, 生命上限: 100 },
    },
    战斗: {
      状态: '进行中',
      对手: '杂役',
      回合: 0,
      我方血: 100,
      我方血上限: 100,
      对方血: 50,
      对方血上限: 50,
      气: 3,
      对方气: 0,
      我方状态: {},
      对方状态: {},
      日志: '',
      摘要: '',
      我方防御: false,
      ...(覆盖?.战斗 as object),
    },
  };
}

console.log('══ ① 单回合：出一个行动 ══');
{
  const 变 = 造变量();
  const { 新变, 报告 } = 出一手(变, '轻攻击');
  断言('结算成功', 报告.ok === true, 报告.原因);
  断言('回合 +1', 新变.战斗.回合 === 1, 新变.战斗.回合);
  断言('对手出了招', !!报告.对方行动, 报告.对方行动);
  断言('有交战记录', 报告.交战.includes('第1回合'), 报告.交战);
  console.log(`      我方: ${报告.我方行动}  对方: ${报告.对方行动}`);
  console.log(`      交战: ${报告.交战}`);
  console.log(`      叙事: ${报告.叙事}`);
}

console.log('\n══ ② 气：耗气与集气 ══');
{
  // ★ 轻攻击**不耗气** —— 这是修过的设计：
  //   早先轻攻击耗 1 气、开局气为 0 → 第一手打不出任何攻击，只能先集气。
  //   现在耗气只用于「重攻击」以上，气是战术资源而非出手门槛。
  const 变 = 造变量({ 战斗: { 气: 3 } });
  const { 新变, 报告 } = 出一手(变, '轻攻击');
  断言('★ 轻攻击不耗气（拳脚免费）', 报告.气变 === 0, 报告.气变);
  console.log(`      气 3 → ${新变.战斗.气}（气变 ${报告.气变}）`);

  const 变重 = 造变量({ 战斗: { 气: 3 } });
  const { 报告: 报重 } = 出一手(变重, '重攻击');
  断言('重攻击耗 2 气', 报重.气变 === -2, 报重.气变);

  const 变2 = 造变量({ 战斗: { 气: 0 } });
  const { 新变: 新2, 报告: 报2 } = 出一手(变2, '集气');
  断言('集气 +3', 报2.气变 === 3, 报2.气变);
  断言('气 0 → 3', 新2.战斗.气 === 3, 新2.战斗.气);

  const 变3 = 造变量({ 战斗: { 气: 1 } });
  const { 报告: 报3 } = 出一手(变3, '绝招');
  断言('★ 气不够时绝招出不了', 报3.ok === false && 报3.原因 === '气不够', 报3);

  const 变4 = 造变量({ 战斗: { 气: 0 } });
  const { 报告: 报4 } = 出一手(变4, '轻攻击');
  断言('★ 气 0 也能打轻攻击（开局不会无招可出）', 报4.ok === true, 报4);
}

console.log('\n══ ③ 气不超上限 ══');
{
  const 变 = 造变量({ 战斗: { 气: 9 } });
  const { 新变 } = 出一手(变, '集气');
  断言(`气不超过 ${气上限}`, 新变.战斗.气 <= 气上限, 新变.战斗.气);
}

console.log('\n══ ④ 嘴炮无效化绝招 ══');
{
  // 造一个必出绝招的对手：气满 + 固定种子
  let 无效化次数 = 0;
  for (let i = 0; i < 30; i++) {
    const 变 = 造变量({ 战斗: { 气: 5, 对方气: 10 }, 世界: { 随机种子: 1000 + i } });
    const { 报告 } = 出一手(变, '嘴炮');
    if (报告.对方行动 === '绝招') {
      无效化次数++;
      断言(`种子${1000 + i}：嘴炮无效化绝招（对方伤害 0）`, 报告.对方伤害 === 0, 报告);
      break;
    }
  }
  if (!无效化次数) console.log('      （30 个种子里对手都没出绝招，跳过）');
}

console.log('\n══ ⑤ 防御减伤（用强对手，弱对手打不动看不出差别）══');
{
  // ★ 打杂役（强度5）打防御21的人只有最低伤害 1，样本区分不出来。
  //   换唐布衣（强度65）才看得出防御的价值。
  const 造强敌 = () => {
    const 变 = 造变量({ 战斗: { 气: 0, 对手: '唐布衣', 对方血: 170, 对方血上限: 170 } });
    return 变;
  };
  let 受伤和 = 0;
  let 正常和 = 0;
  const N = 60;
  for (let i = 0; i < N; i++) {
    正常和 += 出一手(造强敌(), '轻攻击').报告.对方伤害;
    受伤和 += 出一手(造强敌(), '防御').报告.对方伤害;
  }
  const r1 = 正常和 / N;
  const r2 = 受伤和 / N;
  console.log(`      不防御挨打均值 ${r1.toFixed(2)}，防御时均值 ${r2.toFixed(2)}`);
  断言('★ 防御时受伤更少', r2 < r1, { 不防御: r1, 防御: r2 });
  断言('防御减半（约 0.5 倍）', r2 > 0 && r2 < r1 * 0.75, { 比: r2 / r1 });
}

console.log('\n══ ⑥ 确定性：同种子同结果 ══');
{
  const a = 出一手(造变量({ 世界: { 随机种子: 777 } }), '重攻击');
  const b = 出一手(造变量({ 世界: { 随机种子: 777 } }), '重攻击');
  断言('同种子 → 同对手行动', a.报告.对方行动 === b.报告.对方行动, {
    a: a.报告.对方行动, b: b.报告.对方行动,
  });
  断言('同种子 → 同伤害', a.报告.我方伤害 === b.报告.我方伤害);
  断言('同种子 → 同交战文字', a.报告.交战 === b.报告.交战);
  断言('种子被推进', a.新变.世界.随机种子 !== 777, a.新变.世界.随机种子);
}

console.log('\n══ ⑦ 打到结束（★ 用能持续出招的打法）══');
{
  // ★ 连放绝招会在气耗尽后停住 —— 「气不够」是**正确的不消耗回合**，
  //   但测试里会变成死循环。真实玩法是集气→绝招交替，这里照那个打。
  let 变 = 造变量({ 战斗: { 气: 10, 对手: '杂役', 对方血: 50, 对方血上限: 50 } });
  let 报告: any = null;
  let 回合 = 0;
  for (let i = 0; i < 40; i++) {
    const 气 = Number(变.战斗.气) || 0;
    const 招 = 气 >= 5 ? '绝招' : '集气';
    const r = 出一手(变, 招);
    if (!r.报告.ok) break;
    变 = r.新变;
    报告 = r.报告;
    回合++;
    if (报告.结束) break;
  }
  断言('打出了结果', 报告?.结束 === true, { 回合, 胜者: 报告?.胜者, 对方血: 变.战斗.对方血 });
  断言('有胜者', !!报告?.胜者, 报告?.胜者);
  断言('战斗状态变为已结束', 变.战斗.状态 === '已结束', 变.战斗.状态);
  console.log(`      ${回合} 回合：${报告?.胜者}  对方血 ${变.战斗.对方血}  我方血 ${变.战斗.我方血}`);
}

console.log('\n══ ⑧ 叙事不含数字 ══');
{
  const 变 = 造变量();
  const { 报告 } = 出一手(变, '轻攻击');
  // 允许「第N回合」但报告里不该有
  const 有数字 = /\d/.test(报告.叙事.replace(/第\s*\d+\s*回合/g, ''));
  断言('★ 叙事无数字', !有数字, 报告.叙事);
  console.log(`      叙事: ${报告.叙事}`);
}

console.log('\n══ ⑨ 七行动都能出（气够时）══');
{
  const 结果: string[] = [];
  for (const 招 of ['集气', '防御', '轻攻击', '重攻击', '绝招', '嘴炮', '道具']) {
    const 变 = 造变量({ 战斗: { 气: 10 } });
    const { 报告 } = 出一手(变, 招);
    结果.push(`${招}:${报告.ok ? '✓' : '✗' + (报告.原因 ?? '')}`);
  }
  console.log('      ' + 结果.join('  '));
  断言('★ 七行动全部可出', 结果.every(s => s.includes('✓')), 结果);
}

console.log('\n══ ⑩ 不存在的行动被挡住 ══');
{
  const { 报告 } = 出一手(造变量(), '不存在的招');
  断言('被挡住', 报告.ok === false, 报告);
  断言('给了原因', !!报告.原因, 报告.原因);
}

