function 对象非空(o: Record<string, unknown>) { return o && Object.keys(o).length > 0; }

console.log('\n══ ③ 贡献与心相的消耗 ══');
{
  const 耗贡献 = 养成表.find(x => x.贡献 > 0);
  if (耗贡献) {
    const id = `养成_${耗贡献.地点}_${耗贡献.动作}_${耗贡献.事件}`;
    const 变 = 造变量();
    const 前 = 变.世界.贡献度;
    const { 新变 } = 结算行动(变, id);
    console.log(`  「${耗贡献.事件}」耗贡献 ${耗贡献.贡献}：${前} → ${新变.世界.贡献度}`);
    断言('★ 贡献被扣了', 新变.世界.贡献度 === 前 - 耗贡献.贡献, {
      前, 后: 新变.世界.贡献度, 应扣: 耗贡献.贡献,
    });
  }
  const 耗心 = 养成表.find(x => x.心相耗 < 0);
  if (耗心) {
    const id = `养成_${耗心.地点}_${耗心.动作}_${耗心.事件}`;
    const 变 = 造变量(50);
    const 前 = 变.你.心相;
    const { 新变 } = 结算行动(变, id);
    console.log(`  「${耗心.事件}」心相耗 ${耗心.心相耗}：${前} → ${新变.你.心相}`);
    断言('★ 心相被改了', 新变.你.心相 !== 前, { 前, 后: 新变.你.心相 });
    断言('心相在 0~100', 新变.你.心相 >= 0 && 新变.你.心相 <= 100, 新变.你.心相);
  }
}

console.log('\n══ ④ 角色好感能加上 ══');
{
  // 找一条带好感的
  let 找到: any = null;
  for (const x of 养成表) {
    for (const 档 of ['平常', '高昂', '低落'] as const) {
      const 好 = x.好感[档];
      if (好 && Object.keys(好).some(k => ['唐中翎', '唐升', '唐惟元', '唐默铃', '叶云裳'].includes(k))) {
        找到 = { x, 档, 好 };
        break;
      }
    }
    if (找到) break;
  }
  if (找到) {
    const { x, 好 } = 找到;
    const id = `养成_${x.地点}_${x.动作}_${x.事件}`;
    // 用能命中该档的心相值
    const 值 = 档值(好 === x.好感['高昂'] ? 90 : 好 === x.好感['低落'] ? 10 : 50);
    const 变 = 造变量(值);
    const 谁 = Object.keys(好)[0];
    const 前 = Number(变.关系[谁]?.好感 ?? 0);
    const { 新变, 报告 } = 结算行动(变, id);
    const 后 = Number(新变.关系[谁]?.好感 ?? 0);
    console.log(`  「${x.事件}」影响 ${谁} 好感 ${好[谁] >= 0 ? '+' : ''}${好[谁]}：${前} → ${后}`);
    console.log(`    变化表: ${JSON.stringify(报告.数值变化)}`);
    if (报告.ok) {
      断言('★ 角色好感被改了', 后 !== 前, { 谁, 前, 后 });
    }
  } else {
    console.log('  （没找到带角色好感的条目）');
  }
}

function 档值(期: string) { return 期 === '高昂' ? 90 : 期 === '低落' ? 10 : 50; }

console.log('\n══ ⑤ 叙事无数字，且带心相分量 ══');
{
  const x = 养成表.find(b => b.权重 > 0);
  if (x) {
    const id = `养成_${x.地点}_${x.动作}_${x.事件}`;
    for (const [心, 名] of [[10, '低落'], [50, '平常'], [90, '高昂']] as [number, string][]) {
      const { 报告 } = 结算行动(造变量(心), id);
      // 去掉可能出现的「第N年」这类
      const 净 = 报告.叙事.replace(/第\s*\d+\s*年/g, '');
      断言(`${名}档叙事无数字`, !/\d/.test(净), 报告.叙事);
    }
    const { 报告: 高报 } = 结算行动(造变量(90), id);
    const { 报告: 低报 } = 结算行动(造变量(10), id);
    console.log(`  高昂: ${高报.叙事.slice(0, 90)}`);
    console.log(`  低落: ${低报.叙事.slice(0, 90)}`);
    断言('★ 叙事体现了心相分量', 高报.叙事 !== 低报.叙事, { 高: 高报.叙事, 低: 低报.叙事 });
  }
}

