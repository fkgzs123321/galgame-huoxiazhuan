console.log('\n══ ⑦ ★ 事件目录也接进可做列表了 ══');
{
  const 变 = 造变量();
  变.世界.年 = 1; 变.世界.月 = 4; 变.世界.旬 = '上旬';
  const 可选 = 当前可做(变);
  const 目录项 = 可选.filter((o: any) => o.id?.startsWith('目录_'));
  console.log(`  可做 ${可选.length} 项，其中来自事件目录 ${目录项.length} 项`);
  for (const d of 目录项) console.log(`    ${d.名}`);
  断言('★ 目录条目进了可做列表', 目录项.length > 0, 目录项.length);
  断言('目录条目不额外扣行动', 目录项.every((d: any) => d.耗行动 === 0));

  // 与 原作事件表 那批去重（同名的不该出现两次）
  const 名s = 可选.map((o: any) => o.名);
  const 重复 = 名s.filter((n, i) => 名s.indexOf(n) !== i);
  断言('★ 与事件表去重了（没有同名重复）', 重复.length === 0, 重复);

  // ★ 路线影响 —— 要用**真有分支**的那一旬，不能用「各线共用」的旬。
  //   早先我挑了 2年3月上旬，那一旬 7 条全是「各线共用」（那旬本就没分线），
  //   于是三种路线都返回同样结果、断言失败 —— 是**测试的样本挑错了**，
  //   不是引擎错。真实有分支的是 2年8月中/下旬（时=58/59）。
  const 变2 = 造变量();
  变2.世界.年 = 2; 变2.世界.月 = 8; 变2.世界.旬 = '中旬';
  const 取线 = (线: string) => {
    const v = 造变量();
    v.世界.年 = 2; v.世界.月 = 8; v.世界.旬 = '中旬';
    v.世界.路线 = 线;
    return 当前可做(v).filter((o: any) => o.id?.startsWith('目录_')).map((o: any) => o.名);
  };
  const 崆峒 = 取线('崆峒留学');
  const 客栈 = 取线('不留学 住客栈');
  const 青城 = 取线('青城留学');
  console.log(`  2年8月中旬 崆峒线: ${崆峒.join('、') || '（无）'}`);
  console.log(`             客栈线: ${客栈.join('、') || '（无）'}`);
  console.log(`             青城线: ${青城.join('、') || '（无）'}`);
  断言('★ 不同路线出不同的事',
    JSON.stringify(崆峒) !== JSON.stringify(客栈) || JSON.stringify(客栈) !== JSON.stringify(青城),
    { 崆峒, 客栈, 青城 });
  // 共用条目应当三条线都在
  const 共用名 = '唐门报信';
  断言('★ 共用条目在任何路线都出',
    [崆峒, 客栈, 青城].every(a => a.includes(共用名)),
    { 崆峒, 客栈, 青城 });
  void 变2;
}

