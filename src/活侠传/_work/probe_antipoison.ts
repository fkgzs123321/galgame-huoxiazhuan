/**
 * 复验：面板显示「抗毒 15」是否正确。
 *
 * 结论：正确。`抗毒: 15` 是**预览数据里的基础值**，不是装备加成。
 * 引擎把基础值原样传递（没有装备改抗毒），这没问题。
 * （我先前把探针里的基础值写成 0，才误以为引擎算错。）
 */
import { 装备后输入, 装备明细, 物表, 算加成 } from '../脚本/物品';

const 变 = {
  你: {
    // ★ 与 界面/preview.ts 的真实基础值一致
    轻功: 22, 心相: 44, 抗毒: 15,
    战斗: { 攻击: 14, 防御: 18, 暗器威力: 16 },
  },
  装备: { 兵器: '柴刀', 防具: '粗布衣', 暗器袋: '鹿皮囊', 饰品: '' },
};

console.log('穿的:', JSON.stringify(变.装备));
console.log('物表里带抗毒的:', Object.entries(物表).filter(([, d]) => d.加成?.抗毒).map(([n]) => n).join('、') || '（无）');
console.log();

for (const x of 装备明细(变)) {
  console.log(`  ${x.槽} = ${x.名}  ${JSON.stringify(x.加成)}`);
}
console.log();

const r = 装备后输入(变);
console.log('输出:', JSON.stringify(r));
console.log();
console.log('抗毒 15（基础）→', r.抗毒, r.抗毒 === 15 ? '✓ 引擎原样传递' : '✗ 被改了');
console.log('攻击 14（基础）+2 →', r.攻击, r.攻击 === 16 ? '✓' : '✗');
console.log('暗器威力 16（基础）+12 →', r.暗器威力, r.暗器威力 === 28 ? '✓' : '✗');
