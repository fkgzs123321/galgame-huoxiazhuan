console.log('══ ① LCG 确定性 ══');
{
  const a = 造随机(12345);
  const b = 造随机(12345);
  const 序A = [a.next(), a.next(), a.next()];
  const 序B = [b.next(), b.next(), b.next()];
  断言('同种子 → 同序列', JSON.stringify(序A) === JSON.stringify(序B), { 序A, 序B });
  断言('值都在 0~1', 序A.every(v => v >= 0 && v < 1), 序A);

  const c = 造随机(54321);
  断言('不同种子 → 不同序列', c.next() !== 序A[0]);
}

