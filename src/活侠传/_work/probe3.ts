/**
 * 精确验证：防御到底有没有减半。
 * 直接看报告里的原始字段。
 */
import { 出一手 } from '../脚本/战斗结算';

function 造变量() {
  return {
    世界: { 随机种子: 5000 },
    你: { 轻功: 22, 八系: { 拳掌: 10, 暗器: 20 }, 战斗: { 攻击: 16, 防御: 21, 生命上限: 100 } },
    战斗: {
      状态: '进行中', 对手: '唐布衣', 回合: 0,
      我方血: 100, 我方血上限: 100, 对方血: 170, 对方血上限: 170,
      气: 0, 对方气: 0,
      我方状态: {}, 对方状态: {}, 日志: '', 摘要: '', 我方防御: false,
    },
  };
}

console.log('══ 逐字段看 ══');
for (const 招 of ['轻攻击', '防御']) {
  const r = 出一手(造变量(), 招);
  console.log(`\n【我方出「${招}」】`);
  console.log('  ok:', r.报告.ok, ' 原因:', r.报告.原因 ?? '(无)');
  console.log('  对方行动:', r.报告.对方行动);
  console.log('  我方命中:', r.报告.我方命中, ' 我方伤害:', r.报告.我方伤害);
  console.log('  对方命中:', r.报告.对方命中, ' 对方伤害:', r.报告.对方伤害);
  console.log('  防御生效:', r.报告.我方防御生效);
  console.log('  我方血:', 造变量().战斗.我方血, '→', r.新变.战斗.我方血);
  console.log('  交战:', r.报告.交战);
}
