/** 按名字取一本 */
export function 取秘籍(名: string): 秘籍 | undefined {
  return 秘籍表.find(b => b.名 === 名);
}

/** 判一条条件 */
function 满足(c: { 目标: string; 比较: string; 值: number }, 值表: Record<string, number>): boolean {
  const 有 = Number(值表[c.目标]) || 0;
  switch (c.比较) {
    case '>=': return 有 >= c.值;
    case '>':  return 有 >  c.值;
    case '<=': return 有 <= c.值;
    case '<':  return 有 <  c.值;
    case '=':  return 有 === c.值;
    default:   return false;
  }
}

/**
 * 当前能不能练。
 * ★ 只看**入门那一段**（层为 null 或最小层）。
 *   分段门槛里更高的层是「练到那儿再要什么」，不该卡在入门。
 */
export function 能练吗(名: string, 值表: Record<string, number>): { 能: boolean; 缺: string[] } {
  const b = 取秘籍(名);
  if (!b) return { 能: false, 缺: ['没有这本秘籍'] };
  // 取最靠前的一段
  const 入选 = b.门槛.filter(x => x.层 === null);
  const 首段 = 入选.length ? 入选 : b.门槛.slice(0, 1);
  const 缺: string[] = [];
  for (const 段 of 首段) {
    for (const c of 段.条件) {
      if (!满足(c, 值表)) 缺.push(c.目标 + ' ' + c.比较 + ' ' + c.值);
    }
  }
  return { 能: 缺.length === 0, 缺 };
}

/** 练到第 n 层要满足什么（进阶用） */
export function 进阶门槛(名: string, 层: number): Array<{ 目标: string; 比较: string; 值: number }> {
  const b = 取秘籍(名);
  if (!b) return [];
  return b.门槛.find(x => x.层 === 层)?.条件 ?? [];
}

export default { 秘籍表, 取秘籍, 能练吗, 进阶门槛 };
