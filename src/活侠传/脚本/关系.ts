/** 把开局网写进变量（幂等：已有就不覆盖） */
export function 初始化关系网(变: any): number {
  if (Object.keys(网(变)).length > 0) return 0;
  let n = 0;
  for (const [a, b, 类型, 强度, 双向] of 开局关系网) {
    const r = 建关系(变, a, b, 类型, 强度, 双向);
    if (r?.可以) n++;
  }
  return n;
}

/** 开局：谁知道什么（对应原作开局已发生的 ch0_6） */
export function 初始化认知(变: any): number {
  const 开局事 = '你名叫赵活，唐门外姓弟子';
  let n = 0;
  // 在正心堂的人看见了
  for (const 谁 of ['唐中翎', '唐布衣', '唐铮', '唐升', '唐惟元']) {
    if (让他知道(变, 谁, 开局事)) n++;
  }
  return n;
}

