/** 取关系网（不存在就给空网，不抛） */
function 网(变: any): Record<string, any> {
  if (!变.关系网 || typeof 变.关系网 !== 'object') 变.关系网 = {};
  return 变.关系网;
}

/** 建一条 NPC↔NPC 关系。★ 键由引擎排序，不手写 */
export function 建关系(变: any, a: string, b: string, 类型: string, 强度 = 50, 双向 = true) {
  return L.建关系(网(变), a, b, 类型, 强度, 双向);
}

/** 查两个人之间是什么 */
export function 查关系(变: any, a: string, b: string, 从谁?: string) {
  return L.查关系(网(变), a, b, 从谁 ?? a);
}

/** 加减关系强度（★ 关系是走出来的，不是设出来的） */
export function 改关系(变: any, a: string, b: string, 增: number) {
  return L.改关系(网(变), a, b, 增);
}

/** 断关系（不删，记「曾经」） */
export function 断关系(变: any, a: string, b: string) {
  return L.断关系(网(变), a, b);
}

/** 这个人身边一圈 */
export function 身边一圈(变: any, 谁: string) {
  return L.与谁有关(网(变), 谁);
}

/** 自我体检 —— 幂等性靠它守住 */
export function 查网(变: any) {
  return L.查网(网(变));
}

// ══════════════════════════════════════════════════════════════
// 二、★★ 认知边界 —— 本卡最要紧的一层
// ══════════════════════════════════════════════════════════════

/**
 * 这个人知道什么。
 * ★ 每人的 `认知` 字段是「他知道的事」的清单，不是「他不知道的」。
 *   没写进去 = 他不知道 —— 默认无知，而不是默认全知。
 */
export function 他知道什么(变: any, 谁: string): string[] {
  const 条 = 变.关系?.[谁];
  if (!条) return [];
  return String(条.认知 || '')
    .split('、')
    .map((s: string) => s.trim())
    .filter(Boolean);
}

/** 让他知道一件事（幂等 —— 已经知道就不重复写） */
export function 让他知道(变: any, 谁: string, 事: string): boolean {
  if (!变.关系?.[谁]) return false;
  const 现有 = 他知道什么(变, 谁);
  if (现有.includes(事)) return false;
  现有.push(事);
  变.关系[谁].认知 = 现有.join('、');
  return true;
}

/**
 * ★★ 传消息：一件事从 `起点` 出发，沿关系网扩散。
 *
 * 这是「AI 能不能让某人恰好说起某事」的判据：
 *   · 在网内传得到 → 那人可以知道
 *   · 传不到 → 那人**不该**知道，让他说出来就是穿帮
 *
 * @param 起点 事情发生的地方 / 目击者
 * @param 事 事由（写进认知清单的字串）
 * @param 跳数 最多传几手（默认 2：熟人 → 熟人的熟人）
 * @returns 学到这件事的人名
 */
export function 传消息(变: any, 起点: string, 事: string, 跳数 = 2): string[] {
  const 学到: string[] = [];
  if (让他知道(变, 起点, 事)) 学到.push(起点);

  // 逐层扩散：先找直接相识的，再找他们相识的
  let 当前层 = [起点];
  const 已访 = new Set([起点]);

  for (let 手 = 0; 手 < 跳数; 手++) {
    const 下一层: string[] = [];
    for (const 谁 of 当前层) {
      for (const 邻 of 身边一圈(变, 谁)) {
        if (已访.has(邻.对方)) continue;
        // ★ 强度太低传不到 —— 泛泛之交不会替你传话
        if (Number(邻.强度) < 30) continue;
        已访.add(邻.对方);
        下一层.push(邻.对方);
        if (让他知道(变, 邻.对方, 事)) 学到.push(邻.对方);
      }
    }
    当前层 = 下一层;
    if (!当前层.length) break;
  }
  return 学到;
}

/** 两个人的共同熟人（判断「他会从谁那里听说」） */
export function 共同熟人(变: any, a: string, b: string): string[] {
  const A = new Set(身边一圈(变, a).map((x: any) => x.对方));
  return 身边一圈(变, b)
    .map((x: any) => x.对方)
    .filter((n: string) => A.has(n));
}

/** 两个人搭得上吗（引擎的 转几手） */
export function 搭得上吗(变: any, 从: string, 到: string) {
  return L.转几手(网(变), 从, 到);
}

