/**
 * 活侠传 · 关系与认知边界
 *
 * ★ 职责：把引擎 E15（关系网）接到本卡。
 *   它撑起本卡一个关键机制：**谁知道什么**。
 *
 * ★ 为什么这个机制重要：
 *   弟子 A 在伙房听说的事，二师兄当晚就可能知道 —— 也可能永远不知道。
 *   这决定了 AI 能不能让某个角色「恰好说起」某件事。
 *   如果不管这张网，AI 就会让所有人都无所不知，人物立刻失真。
 *
 * ★ 引擎真实签名（从 引擎.js 读出）：
 *     对键(a, b)                       → '甲|乙'（排序后）
 *     建关系(网, a, b, 类型, 强度, 双向) → { 可以, 建了, 新的 }
 *     查关系(网, a, b, 从谁)            → { 类型, 强度, 看法, 正向 } | null
 *     改关系(网, a, b, 增)              → { 可以, 从, 到, 变了 }
 *     断关系(网, a, b)                  → { 可以, 曾经是 }
 *     与谁有关(网, 谁)                  → [{ 对方, 类型, 强度, 双向, 曾经 }]
 *     转几手(网, 从, 到)                → { 步数, 路 }   步数 -1 = 搭不上
 *     查网(网)                          → { 有没有错, 错, 共几对 }
 */

import lib from './引擎.esm';
