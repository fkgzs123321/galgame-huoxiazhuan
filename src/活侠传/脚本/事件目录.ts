/** 某一旬的目录（不含路线筛选） */
export function 该旬目录(年: number, 月: number, 旬: number): 目录项[] {
  const 时 = (年 - 1) * 36 + (月 - 1) * 3 + (旬 - 1);
  return 事件目录.filter(x => x.时 === 时);
}

/**
 * 某一旬在指定路线下的事件。
 *
 * ★「各线共用」的判定要认两种写法：
 *     · 空字符串（提取时没标路线）
 *     · 字面量「各线共用」（提取时 colspan 跨了所有路线列）
 *   早先只判了 `!x.路线`，于是「各线共用」被当成一条真路线，
 *   按任意具体路线筛都会把它漏掉 —— 该旬路线(x, '崆峒留学') 返回 0。
 *   自测抓到的。
 */
const 共用 = '各线共用';

export function 该旬路线(年: number, 月: number, 旬: number, 路线 = ''): 目录项[] {
  const 时 = (年 - 1) * 36 + (月 - 1) * 3 + (旬 - 1);
  return 事件目录.filter(x => {
    if (x.时 !== 时) return false;
    // 共用条目：任何路线都出
    if (!x.路线 || x.路线 === 共用) return true;
    // 有明确路线的：只在匹配时出
    return x.路线 === 路线;
  });
}

/** 这一旬有没有路线分支（有则值得在界面上提示） */
export function 有分支(年: number, 月: number, 旬: number): boolean {
  const 时 = (年 - 1) * 36 + (月 - 1) * 3 + (旬 - 1);
  const 线s = new Set(
    事件目录.filter(x => x.时 === 时 && x.路线 && x.路线 !== 共用).map(x => x.路线),
  );
  return 线s.size >= 2;
}

/** 这一旬涉及哪些路线 */
export function 该旬路线名(年: number, 月: number, 旬: number): string[] {
  const 时 = (年 - 1) * 36 + (月 - 1) * 3 + (旬 - 1);
  return [...new Set(
    事件目录.filter(x => x.时 === 时 && x.路线 && x.路线 !== 共用).map(x => x.路线),
  )];
}

/** 全部路线名（去重，不含「各线共用」） */
export function 所有路线(): string[] {
  return [...new Set(事件目录.map(x => x.路线).filter(r => r && r !== 共用))];
}

/** 某一年的事件 */
export function 该年目录(年: number): 目录项[] {
  return 事件目录.filter(x => x.年 === 年);
}

/** 目录里有没有这一条（按名字查，模糊） */
export function 有这事(名: string): boolean {
  return 事件目录.some(x => x.名.includes(名));
}

export default { 事件目录, 该旬目录, 该旬路线, 所有路线, 该年目录, 有这事, 有分支, 该旬路线名 };
