/** 血量 → 档位词（与引擎 `受伤档` 同口径，但这里不需要引擎也能算） */
function 受伤词(剩余: number, 上限: number): string {
  const p = (Number(上限) || 1) <= 0 ? 0 : (Number(剩余) || 0) / Number(上限) * 100;
  if (p <= 0) return '倒下了';
  if (p < 20) return '到了极限';
  if (p < 50) return '伤得不轻';
  if (p < 80) return '挂了彩';
  return '没怎么吃亏';
}

/** 去掉字符串里的数字（引擎的 `不可逆` 形如「我方受伤 37%」） */
function 去数字(s: string): string {
  return String(s).replace(/[0-9]+(\.[0-9]+)?\s*%?/g, '').replace(/\s+/g, '').trim() || '受了伤';
}

