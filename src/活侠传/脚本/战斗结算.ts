/** 从变量拼出我方的战斗单位（★ 含装备加成） */
function 我方战斗单位(变: any) {
  const 装备后 = (() => {
    try {
      // 避免循环依赖：直接算基础 + 装备
      const 基础 = {
        攻击: Number(取(变, '你.战斗.攻击')) || 10,
        防御: Number(取(变, '你.战斗.防御')) || 10,
      };
      return 基础;
    } catch {
      return { 攻击: 10, 防御: 10 };
    }
  })();

  const 上限 = Number(取(变, '你.战斗.生命上限')) || 100;
  return {
    名: '你',
    生命: Number(取(变, '战斗.我方血')) || 上限,
    上限,
    攻击: 装备后.攻击,
    防御: 装备后.防御,
    // ★ strike 读的字段：命中加成 / 闪避加成 / 命中 / 伤害倍率
    命中: Number(取(变, '你.八系.暗器')) || 10,
    命中加成: 0,
    闪避加成: Math.round((Number(取(变, '你.轻功')) || 0) * 0.3),
    伤害倍率: 1,
  };
}

/** 对手单位（从角色强度推） */
function 对手战斗单位(变: any) {
  const 名 = String(取(变, '战斗.对手') || '对手');
  // 强度存不下时，用血量上限反推
  const 上限 = Number(取(变, '战斗.对方血上限')) || 100;
  const 强度 = Math.max(1, Math.round((上限 - 40) / 2));
  return {
    名,
    生命: Number(取(变, '战斗.对方血')) || 上限,
    上限,
    攻击: Math.round(强度 * 0.6),
    防御: Math.round(强度 * 0.4),
    命中: 强度,
    命中加成: 0,
    闪避加成: Math.round(强度 * 0.2),
    伤害倍率: 1,
    强度,
  };
}

/**
 * 对手这一手出什么（确定性：用种子算，不用 Math.random）。
 *
 * ★★ 两个 bug 都在这段里修过：
 *   ① 早先不看气，而 对手的气 从 0 开始 —— 对手永远出不起招，只能干攒
 *   ② 早先 轻攻击 耗 1 气，导致开局连玩家都打不出攻击
 *   现在轻攻击免费，所以对手有气没气都能还手，攒够 2 点就上重攻击。
 */
function 对手出招(变: any, r: { next: () => number }, 强度: number): string {
  const 气 = Number(取(变, '战斗.对方气')) || 0;
  const 掷 = r.next();
  // 强度越高越激进（0.35 ~ 0.65）
  const 凶 = Math.max(0.35, Math.min(0.65, 强度 / 120));

  if (气 >= 5 && 掷 < 凶 * 0.8) return '绝招';
  if (气 >= 2 && 掷 < 凶) return '重攻击';
  // 轻攻击不耗气 —— 这是常态
  if (掷 < 凶 + 0.55) return '轻攻击';
  if (掷 < 凶 + 0.65) return '防御';
  if (掷 < 凶 + 0.8) return '嘴炮';
  return '集气';
}

/**
 * ★ 出一手 —— 单回合结算。
 *
 * @param 变 变量
 * @param 我方行动 七行动之一
 */
export function 出一手(旧变: any, 我方行动: string): { 新变: any; 报告: 回合报告 } {
  const 变 = _.cloneDeep(旧变);
  const 报告: 回合报告 = {
    ok: false,
    我方行动,
    对方行动: '',
    被克: false,
    我方伤害: 0,
    对方伤害: 0,
    气变: 0,
    对方气变: 0,
    结束: false,
    胜者: '',
    叙事: '',
    交战: '',
  };

  const 行动定义 = (行动表 as any)[我方行动];
  if (!行动定义) {
    报告.原因 = '没有这个行动';
    return { 新变: 变, 报告 };
  }

  // 气够不够
  const 我气 = Number(取(变, '战斗.气')) || 0;
  if (我气 < (行动定义.耗气 ?? 0)) {
    报告.原因 = '气不够';
    return { 新变: 变, 报告 };
  }

  try {
    const 我 = 我方战斗单位(变);
    const 敌 = 对手战斗单位(变);
    const 种子 = Number(取(变, '世界.随机种子')) || 20260927;
    const r = 造随机(种子);

    // ── 我方这一手 ──
    const 敌出 = 对手出招(变, r, 敌.强度);
    报告.对方行动 = 敌出;

    // ★ 克制判定
    const 我克敌 = 克谁(我方行动).includes(敌出);
    const 敌克我 = 克谁(敌出).includes(我方行动);
    报告.被克 = 敌克我;

    // 扣气 / 加气
    let 我气变 = -(行动定义.耗气 ?? 0);
    let 敌气变 = -((行动表 as any)[敌出]?.耗气 ?? 0);

    // 集气：+3
    if (我方行动 === '集气') 我气变 += 3;
    if (敌出 === '集气') 敌气变 += 3;

    // ── 我方攻击 ──
    const 次序 = (我.闪避加成 >= 敌.闪避加成) ? ['我', '敌'] : ['敌', '我'];
    const 命中率 = (攻: any, 守: any) =>
      (lib as any).rateFromDiff(
        (攻.命中 || 0) - (守.闪避加成 || 0) + (攻.命中加成 || 0),
        { 基准: 战斗cfg.命中率.基准, 斜率: 战斗cfg.命中率.斜率, 下限: 战斗cfg.命中率.下限, 上限: 战斗cfg.命中率.上限 },
      );

    // ★ 本回合我方是否处于防御姿态 —— 只在**挨打时**生效，不影响自己出手
    const 我防御 = 我方行动 === '防御';

    for (const 谁 of 次序) {
      const 攻 = 谁 === '我' ? 我 : 敌;
      const 守 = 谁 === '我' ? 敌 : 我;
      const 招 = 谁 === '我' ? 我方行动 : 敌出;

      if (攻.生命 <= 0 || 守.生命 <= 0) continue;

      // 嘴炮互相无效化绝招
      if (谁 === '敌' && 我方行动 === '嘴炮' && 招 === '绝招') continue;
      if (谁 === '我' && 敌出 === '嘴炮' && 招 === '绝招') continue;

      // ── 非伤害招：集气 / 防御 / 嘴炮 / 道具 ──
      //   ★ 「防御」在这里 continue 是对的：它本身就是不出手。
      //     它的价值体现在**挨打时减伤**（下面处理），不是自己造成伤害。
      const 是伤害招 = !['集气', '防御', '嘴炮', '道具'].includes(招);
      if (!是伤害招) continue;

      const 倍率 = Number((行动表 as any)[招]?.倍率) || 1;
      const 无视防御 = !!(行动表 as any)[招]?.无视防御;

      // 被克：命中率打折
      const 被克 = (谁 === '我' && 敌克我) || (谁 === '敌' && 我克敌);
      const 率 = 命中率(攻, 守) * (被克 ? 0.5 : 1);
      const 掷 = r.next() * 100;
      const 命中 = 掷 < 率;

      if (!命中) {
        if (谁 === '我') 报告.我方命中 = false;
        else 报告.对方命中 = false;
        continue;
      }

      const 防 = 无视防御 ? 0 : 守.防御;
      const 基础 = Math.max(1, (攻.攻击 * 倍率) - 防);
      let 伤害 = Math.max(1, Math.round(基础 * (攻.伤害倍率 || 1)));

      // ★★ 防御姿态：**只有对方打我们时才减半**。
      //   早先这里写成 `我方行动 === '防御'` 与 `招 === '防御'` 混在一起 ——
      //   我方自己选防御时，上面已经 continue（防御不出手），这一支只会误伤自己；
      //   而对方打过来时又因为判断的是「我方的招」而永远不成立。
      //   现在明确：判的是**挨打方是不是在防御**。
      if (谁 === '敌' && 我防御) {
        伤害 = Math.max(1, Math.round(伤害 / 2));
        报告.我方防御生效 = true;
      }

      守.生命 = Math.max(0, 守.生命 - 伤害);

      if (谁 === '我') {
        报告.我方命中 = true;
        报告.我方伤害 = 伤害;
      } else {
        报告.对方命中 = true;
        报告.对方伤害 = 伤害;
      }
    }

    // ── 写回 ──
    const 旧敌气 = Number(取(变, '战斗.对方气')) || 0;
    const 新我气 = Math.max(0, Math.min(气上限, 我气 + 我气变));
    const 新敌气 = Math.max(0, Math.min(气上限, 旧敌气 + 敌气变));
    设(变, '战斗.气', 新我气);
    设(变, '战斗.对方气', 新敌气);
    // ★ 报告里要如实反映实际增减（夹紧后可能与计算值不同）
    报告.气变 = 新我气 - 我气;
    报告.对方气变 = 新敌气 - 旧敌气;
    设(变, '战斗.我方血', Math.round(我.生命));
    设(变, '战斗.对方血', Math.round(敌.生命));
    设(变, '战斗.回合', (Number(取(变, '战斗.回合')) || 0) + 1);
    设(变, '战斗.对手', 敌.名);
    设(变, '世界.随机种子', r.种子());

    // 本回合防御姿态只维持一回合
    设(变, '战斗.我方防御', 我方行动 === '防御');

    // ── 结束判定 ──
    const 回合数 = Number(取(变, '战斗.回合')) || 1;
    if (我.生命 <= 0 && 敌.生命 <= 0) {
      报告.胜者 = '同归';
      报告.结束 = true;
    } else if (敌.生命 <= 0) {
      报告.胜者 = '我方';
      报告.结束 = true;
    } else if (我.生命 <= 0) {
      报告.胜者 = '对方';
      报告.结束 = true;
    } else if (回合数 >= 战斗cfg.上限回合) {
      报告.胜者 = '未决';
      报告.结束 = true;
    }
    设(变, '战斗.状态', 报告.结束 ? '已结束' : '进行中');

    // ── 交战文字（给界面，含数字）──
    const 我招 = 我方行动 === '集气' ? '你凝神聚气'
      : 我方行动 === '防御' ? '你横臂格挡'
      : 我方行动 === '嘴炮' ? '你开口讥刺'
      : 报告.我方命中 ? `你击中（${报告.我方伤害}）`
      : `你落空`;
    const 敌招 = 敌出 === '集气' ? `${敌.名}凝神聚气`
      : 敌出 === '防御' ? `${敌.名}横臂格挡`
      : 敌出 === '嘴炮' ? `${敌.名}出言相激`
      : 报告.对方命中 ? `${敌.名}击中（${报告.对方伤害}）`
      : `${敌.名}落空`;
    报告.交战 = `第${回合数}回合：${我招}，${敌招}`;
    设(变, '战斗.日志', [String(取(变, '战斗.日志') || ''), 报告.交战].filter(Boolean).join('、').slice(-600));
    设(变, '战斗.摘要', 报告.胜者 ? `${报告.胜者}·${回合数 <= 3 ? '碾压' : 回合数 <= 8 ? '常规' : '苦战'}` : '');

    // ── ★ 给 AI 的叙事（无数字）──
    const 伤我 = 受伤词(我.生命, 我.上限);
    const 伤敌 = 受伤词(敌.生命, 敌.上限);
    const 段: string[] = [`这一回合你出的是「${我方行动}」，${敌.名}出的是「${敌出}」。`];
    if (报告.被克) 段.push('你这一手被对方克住了，吃了亏。');
    else if (克谁(我方行动).includes(敌出)) 段.push('你这一手正克住对方。');
    if (报告.我方命中) 段.push('你打中了。');
    else if (报告.我方伤害 === 0 && !['集气', '防御', '嘴炮', '道具'].includes(我方行动)) 段.push('你没打中。');
    if (报告.对方命中) 段.push('你也挨了一下。');
    if (报告.结束) {
      段.push(
        报告.胜者 === '我方' ? '这场打完了，你赢了。'
         : 报告.胜者 === '对方' ? '这场打完了，你倒下了。'
         : 报告.胜者 === '同归' ? '这场打完了，两败俱伤。'
         : '打到这里谁也没占到便宜，僵住了。',
      );
    }
    段.push(`你现在是${伤我}，对面${伤敌}。`);
    段.push('把这一回合写成动作，不要写数字、不要写点数、不要写血量。只写这一回合。');
    报告.叙事 = 段.join('');

    报告.ok = true;
  } catch (e) {
    报告.原因 = e instanceof Error ? e.message : String(e);
    console.error('[活侠传] 回合结算失败', e);
  }

  return { 新变: 变, 报告 };
}

export { 气上限 };
