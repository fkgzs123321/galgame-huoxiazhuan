// 确定性随机
// ══════════════════════════════════════════════════════════════

/**
 * 整数散列（murmur3 的 finalizer）。
 *
 * ★ 为什么需要它：LCG 的 `(A*s + C) / 2^32` 里，s 每加 1 只让结果变动
 *   `A/2^32 ≈ 0.0004` —— **相邻种子会掷出几乎相同的值**。
 *   而本卡的种子是逐场递增的，那意味着「连着打几场架结果都差不多」。
 *   （这个缺陷是自测发现的：种子 1000~1030 的首值全部落在 0.624~0.635。）
 *
 *   先用散列把种子打散，相邻种子就会跳到完全不同的位置。
 *   纯整数运算，确定性、可复现，不使用 Math.random。
 */
function 散列(x: number): number {
  let h = x >>> 0;
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b) >>> 0;
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35) >>> 0;
  h ^= h >>> 16;
  return h >>> 0;
}

/**
 * LCG 生成器 —— 与原作 `FreeRandomState` 同构（线性同余）。
 *
 * ★ 不用 Math.random：那样同一回合重渲染会给出不同结果，
 *   玩家会看到「同一场战斗两次结果不一样」，本卡不允许。
 * ★ 但只用 LCG 不够：种子先过一遍 `散列()`，否则相邻种子近似。
 */
export function 造随机(种子: number) {
  let s = 散列(Math.floor(种子) || 1);
  // 再空转几圈，让低位也参与进来
  for (let i = 0; i < 4; i++) s = (Math.imul(1664525, s) + 1013904223) >>> 0;

  const A = 1664525;
  const C = 1013904223;
  return {
    next(): number {
      s = (Math.imul(A, s) + C) >>> 0;
      return s / 4294967296; // 归一到 0..1
    },
    种子(): number {
      return s;
    },
  };
}

