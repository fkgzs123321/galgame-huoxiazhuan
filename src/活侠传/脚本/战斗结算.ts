/**
 * 活侠传 · 战斗结算
 *
 * ★ 职责：把一场打斗跑完，并输出**两份不同的结果**：
 *   · 给界面的：逐回合日志、血量、伤害数字
 *   · 给 AI 的：只用「写法约束」——碾压/常规/苦战/僵持，**不含任何数字**
 *
 * ★ 引擎真实签名（从 引擎.js 读出）：
 *     fight(cfg, rng, rateFromDiff)  cfg = { 我方, 对方, 上限回合, 计有效值 }
 *     rng()                          → 0..1（★ 引擎不自己造随机，由外部注入）
 *     rateFromDiff(diff, cfg)        cfg = { 基准, 斜率, 下限, 上限 }
 *     summarize(r, cfg)              → { 结果, 回合数, 我方状态, 不可逆, 写法约束 }
 *
 * ★ 为什么 rng 由外部注入：确定性伪随机。
 *   同一种子 → 同一结果，可复现、可回看。**禁用 Math.random。**
 */

