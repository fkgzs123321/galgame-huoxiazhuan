/**
 * 应用一组产出（如 `{ 锻造: 8, 体力: -12 }`）。
 * 返回实际发生的变化 —— 因为夹紧会吃掉一部分。
 */
function 应用产出(变: any, 产出: Record<string, number>): Record<string, number> {
  const 实际: Record<string, number> = {};

  for (const [字段, 原值] of Object.entries(产出)) {
    // ★★ 角色好感：原作事件的效果里大量出现（唐中翎 -1、叶云舟 +1 …）。
    //   这是**动态键**，静态的 字段路径 表放不下，所以在这里按名字查。
    //   只认已经在 `关系.<名>` 里建档的人 —— 没建档的说明还没结识，
    //   凭空建一条会污染关系表（原作也是先遇上才建档）。
    if (!字段路径[字段]) {
      const 条 = 取(变, `关系.${字段}`);
      if (条 && typeof 条 === 'object') {
        // 双向分开：事件的「XX好感+1」指**他对你的观感**
        const 旧 = Number(条.好感) || 0;
        条.好感 = 夹(旧 + 原值, -100, 100);
        实际[字段] = 条.好感 - 旧;
        continue;
      }
      // ★ 不静默吞掉：未知字段直接报出来，避免又长出一个 schema 外的脏键
      console.warn(`[活侠传] 产出字段「${字段}」未在 字段路径 表里，也不是已建档的角色，已忽略`);
      continue;
    }

    const 路径 = 字段路径[字段];
    const 旧 = Number(取(变, 路径)) || 0;
    const 新 = 旧 + 原值;

    if (路径.endsWith('.当前')) {
      const 上限 = Number(取(变, 路径.replace('.当前', '.上限'))) || 9999;
      设(变, 路径, 夹(新, 0, 上限));
    } else {
      设(变, 路径, Math.max(0, 新));
    }
    实际[字段] = (Number(取(变, 路径)) || 0) - 旧;
  }
  return 实际;
}

