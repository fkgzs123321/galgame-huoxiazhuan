const 取 = (变: any, 路径: string): any => {
  const 段 = 路径.split('.');
  let 当: any = 变;
  for (const k of 段) {
    if (当 == null || typeof 当 !== 'object') return undefined;
    当 = 当[k];
  }
  return 当;
};

const 设 = (变: any, 路径: string, 值: unknown): void => {
  const 段 = 路径.split('.');
  let 当: any = 变;
  for (let i = 0; i < 段.length - 1; i++) {
    if (当[段[i]] == null || typeof 当[段[i]] !== 'object') 当[段[i]] = {};
    当 = 当[段[i]];
  }
  当[段[段.length - 1]] = 值;
};

/** 幅度夹紧（引擎 E5 护栏的一部分） */
const 夹 = (v: unknown, lo: number, hi: number) => _.clamp(Number(v) || 0, lo, hi);

