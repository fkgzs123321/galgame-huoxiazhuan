/**
 * ★ 核心：结算一次行动。
 *
 * @param 旧变 当前 MVU 变量（会被深拷贝，不修改入参）
 * @param 行动id 行动表或单元表里的 id
 * @returns 新变量 + 报告
 */
export function 结算行动(旧变: any, 行动id: string): { 新变: any; 报告: 结算报告 } {
  const 变 = _.cloneDeep(旧变);
  const 报告: 结算报告 = {
    ok: false,
    行动名: '',
    判定: '无需判定',
    数值变化: {},
    叙事: '',
    跨旬: false,
    新错过数: 0,
  };

  // ── 找行动 ──
  const 行动 = 行动表.find((a: any) => a.id === 行动id);
  const 单元 = 单元表.find((u: any) => u.id === 行动id);
  // ★ 原作事件：来自 脚本/原作事件.ts（提取自原作 story-branch-timeline）
  //   ★ 不要把事件的选项效果塞进 `产出` —— 那等于替玩家做了选择。
  //     （早先版本写了 `产出: 事件.选项?.[0]?.效果`，导致事件一触发就自动改属性，
  //      被自测抓到。）
  const 事件 = 原作事件表.find(e => e.id === 行动id);
  // ★ 原作养成指令：id 形如 `养成_地点_动作_事件`
  //   效果**随当前心相档位**取（这是原作的核心机制）
  const 养成项 = 行动id.startsWith('养成_') ? 找养成项(行动id) : undefined;
  const 源: any = 行动 || 单元 || 事件 || 养成项;
  if (!源) {
    报告.原因 = '没有这个行动';
    return { 新变: 变, 报告 };
  }
  报告.行动名 = 源.名;

  // ── ① 前置 ──
  //   ★ 事件的 `前置` 有两类：
  //     · 事件 id（如 S_1_4_3_叶氏一）—— 需先做过那件事
  //     · 条件 id（如 天赋_自恋）—— 查 前置表
  //   这里分开处理，避免「前置未定义」的误报。
  if (事件) {
    const 事件前置 = (事件.前置 ?? []).filter(p => 原作事件表.some(e => e.id === p));
    const 条件前置 = (事件.前置 ?? []).filter(p => !事件前置.includes(p));
    const 做过 = String(取(变, '前置.已解锁') || '').split('、').filter(Boolean);
    if (!事件前置.every(p => 做过.includes(p))) {
      报告.原因 = '条件不满足';
      报告.叙事 = '';
      return { 新变: 变, 报告 };
    }
    if (!判一组(条件前置, 变)) {
      报告.原因 = '条件不满足';
      报告.叙事 = '';
      return { 新变: 变, 报告 };
    }
  } else if (!判一组((源 as any).前置, 变)) {
    报告.原因 = '条件不满足';
    // ★ 不给 AI 任何提示 —— 这是原作 `~x` 的设计
    报告.叙事 = '';
    return { 新变: 变, 报告 };
  }

  // ── ② 行动点 ──
  const 耗 = Number(源.耗行动 ?? 源.行动点 ?? 1);
  const 余 = Number(取(变, '世界.行动次数')) || 0;
  if (余 < 耗) {
    报告.原因 = '这一旬的力气用完了';
    return { 新变: 变, 报告 };
  }
  设(变, '世界.行动次数', 余 - 耗);

  // ── ③ 判定（技艺类干活不判定，修行类判定）──
  const 要判定 = ['train', 'throw', 'meditate', 'patrol'].includes(行动id);
  if (要判定) {
    const r = 掷判定(变, 源);
    报告.判定 = r.成 ? '成功' : '失败';
    报告.档位 = r.档;
  }

  // ── ④ 产出 ──
  //   ★ 三种来源：
  //     · 行动表/单元表 → `产出`（如 { 锻造: 8, 体力: -12 }）—— 干活有固定收益
  //     · 原作事件     → **不在这里应用数值**（选择交给玩家）
  //     · 原作养成指令 → 按**当前心相档位**取效果（原作的核心机制）
  if (源.产出) {
    // 判定失败 → 产出减半（努力没白费，但事倍功半）
    const 系数 = 报告.判定 === '失败' ? 0.5 : 1;
    const 缩放: Record<string, number> = {};
    for (const [k, v] of Object.entries(源.产出 as Record<string, number>)) {
      缩放[k] = Math.round(v * 系数);
    }
    报告.数值变化 = 应用产出(变, 缩放);
  } else if (养成项) {
    // ★★ 养成指令：收益随「心相」档位变化 ——
    //     低落 0~32   效果打折甚至反效果
    //     平常 33~64  基础效果
    //     高昂 65~100 额外收益
    const x = 养成项._养成;
    const 值 = Number(取(变, '你.心相')) || 50;
    const 档 = 心相档(值);
    const 效果 = (x.效果?.[档] ?? {}) as Record<string, number>;
    const 好感 = (x.好感?.[档] ?? {}) as Record<string, number>;

    报告.档位 = 档;
    报告.数值变化 = 应用产出(变, { ...效果, ...好感 });
    // 贡献与心相的消耗（原作这两列是独立于效果的）
    if (x.贡献) {
      设(变, '世界.贡献度', Math.max(0, (Number(取(变, '世界.贡献度')) || 0) - x.贡献));
    }
    if (x.心相耗) {
      设(变, '你.心相', Math.max(0, Math.min(100, (Number(取(变, '你.心相')) || 50) + x.心相耗)));
    }
    报告.叙事 = 造养成叙事(x, 档, 报告.数值变化);
  } else if (事件) {
    // ★★ 原作事件**不预设数值后果**。
    //
    //   为什么：原作每条事件有好几个选项，后果各不相同 ——
    //   比如「照镜子」三个选项分别是 性情-2 / 学问+1 / 心相-20、性情-1、修养-1、命运+1。
    //   早先版本取「第一个选项」当默认后果，那是错的：
    //   它等于替玩家做了选择，而且选项本身还可能有前置。
    //
    //   正确做法：引擎只负责「这条事件发生了 + 扣行动点 + 记进已解锁」，
    //   具体选了哪个、后果是什么，由 AI 在叙事里体现，再通过变量更新回写。
    //   选项文本给 AI 参考（AI 不该凭空编选项）。
    报告.选项提示 = 事件.选项?.map(o => o.说法) ?? [];
    报告.叙事 = 造事件叙事(事件, 变);
  }

  // ── ⑤ 记「本旬已用」──
  const 已用 = String(取(变, '前置.本旬已用') || '');
  const 名单 = 已用.split('、').filter(Boolean);
  名单.push(源.名);
  设(变, '前置.本旬已用', 名单.join('、'));

  // ── ⑥ 首次解锁的条件 ──
  const 解 = 已解锁名(变);
  设(变, '前置.已解锁', 解.join('、'));
  设(变, '前置.可见条件', 可见提示(变).join('、'));

  // ── ⑦ 门派阶段 ──
  const 旧阶 = Number(取(变, '世界.门派规模')) || 1;
  const 新阶 = Math.max(旧阶, 算门派阶段(变));
  if (新阶 > 旧阶) {
    设(变, '世界.门派规模', 新阶);
    报告.阶段推进 = { 从: 旧阶, 到: 新阶, 名: 门派阶段门槛[新阶 - 1].名 };
  }

  // ── ⑧ 行动点用尽 → 跨旬 ──
  if ((Number(取(变, '世界.行动次数')) || 0) <= 0) {
    跨旬(变);
    报告.跨旬 = true;

    // ★ 跨旬才扫过期 —— 时间变了，窗口可能已关
    const 新错过 = 扫过期(变);
    if (新错过.length) {
      const 旧错 = String(取(变, '前置.已错过') || '')
        .split('、')
        .filter(Boolean);
      设(变, '前置.已错过', [...旧错, ...新错过].join('、'));
      报告.新错过数 = 新错过.length;
      // ★★ 明细不进报告给 AI 的那份 —— 只记数
    }
  }

  // ── ⑨ 叙事指令（★ 不含任何数字）──
  报告.ok = true;
  // ★ 事件已经有专门的叙事（含原作选项），别再被通用叙事覆盖 ——
  //   早先这里无条件赋值，把 造事件叙事 的产物冲掉了（自测日志露出来的）。
  if (!报告.叙事) {
    报告.叙事 = 造叙事(源.名, 报告, 变);
  } else {
    // 补上跨旬/阶段推进这类通用信息
    const 通用 = 造叙事(源.名, 报告, 变);
    const 尾巴 = 通用.split('。').filter(s => s.includes('旬过去了') || s.includes('门中气象')).join('。');
    if (尾巴) 报告.叙事 += 尾巴 + '。';
    else 报告.叙事 += '只写这一段，别预报后面的事。';
  }

  return { 新变: 变, 报告 };
}

/** 给 AI 的叙事指令：只说发生了什么，不说数值 */
function 造叙事(名: string, 报告: 结算报告, 变: any): string {
  const 段: string[] = [];
  段.push(`<user> 做了「${名}」。`);

  if (报告.判定 === '成功') {
    段.push('做得不错，达到了预期。');
  } else if (报告.判定 === '失败') {
    段.push('不算顺利，勉强做成了一半。写出他哪里没做好，不要写成被打断或意外。');
  }

  if (报告.跨旬) {
    const 年 = 取(变, '世界.年');
    const 月 = 取(变, '世界.月');
    const 旬 = 取(变, '世界.旬');
    段.push(`这一旬过去了，现在是第 ${年} 年 ${月} 月${旬}。写一个自然的收束。`);
  }
  if (报告.阶段推进) {
    段.push(`门中气象有变（${报告.阶段推进.名}）。用一两个细节带出来，不要直说。`);
  }
  段.push('只写这一段，别预报后面的事。');
  return 段.join('');
}

/** 给 AI 的事件叙事指令 —— 不含任何数字 */
function 造事件叙事(事件: 原作事件, 变: any): string {
  const 段: string[] = [];
  段.push(`这一旬遇上了「${事件.名}」。`);
  if (事件.类别) 段.push(`这是${事件.类别}类的事。`);
  if (事件.地点) 段.push(`地点在${事件.地点}。`);

  if (事件.选项?.length) {
    // ★ 把原作选项给 AI —— 别让它凭空编
    段.push(`原作里这件事有几个走向：${事件.选项.map(o => `「${o.说法}」`).join('、')}。`);
    段.push('你可以照这些走向写，也可以顺着玩家的选择自然发展 —— 但别把选项摆成菜单让玩家挑。');
  }
  if (事件.门槛 !== undefined) {
    段.push('这件事带运气成分，写的时候别把结果写死。');
  }
  if (事件.注) {
    // 注里可能有数值 → 去掉数字再给
    段.push(事件.注.replace(/[+-]?\d+(\.[0-9]+)?/g, '').replace(/\s+/g, '') + '。');
  }
  // ★ 收尾只说一次（早先与通用叙事拼起来会重复「别预报后面的事」）
  return 段.join('');
}

/**
 * 从养成指令的 id 反查它是哪一条。
 * id 形如 `养成_唐家大院_焚香_课外书籍`
 */
function 找养成项(id: string): any {
  for (const x of 养成表) {
    if (`养成_${x.地点}_${x.动作}_${x.事件}` === id) {
      return {
        名: x.事件 || x.动作,
        地点: x.地点,
        耗行动: 1,
        _养成: x,
      };
    }
  }
  return undefined;
}

/** 给 AI 的养成叙事 —— 不含数字，但要说清这一档的分量 */
function 造养成叙事(指令: any, 档: string, 变化: Record<string, number>): string {
  const 段: string[] = [];
  const 事 = 指令.事件 || 指令.动作;
  段.push(`<user> 在${指令.地点}做了「${事}」。`);

  // ★ 心相档位影响写法分量 —— 这是原作机制，得让 AI 知道
  if (档 === '高昂') {
    段.push('他今天精神头足，做什么都顺手。写得轻快些。');
  } else if (档 === '低落') {
    段.push('他今天提不起劲，事情做得勉强。写得沉一点，但别写成被打断或出事。');
  }

  // 有没有真正产生变化
  const 有变 = Object.values(变化).some(v => Number(v) !== 0);
  if (!有变) 段.push('这件事本身没什么收获，但日子就是这么过的。');

  if (指令.备注) {
    段.push(指令.备注.replace(/[+-]?\d+/g, '').replace(/\s+/g, ''));
  }
  return 段.join('');
}

