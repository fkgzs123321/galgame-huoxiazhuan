export interface 结算报告 {
  ok: boolean;
  行动名: string;
  /** 判定结果：成功 / 失败 / 无需判定 */
  判定: '成功' | '失败' | '无需判定';
  档位?: string;
  /** ★ 给界面的：完整数值变化 */
  数值变化: Record<string, number>;
  /** ★ 给 AI 的：不含数字的叙事指令 */
  叙事: string;
  /** 是否跨旬 */
  跨旬: boolean;
  /** 新错过（数量，明细不给 AI） */
  新错过数: number;
  /** 门派阶段是否推进 */
  阶段推进?: { 从: number; 到: number; 名: string };
  /** ★ 原作事件带的可选说法（给 AI 参考，不含数值） */
  选项提示?: string[];
  /** 失败原因（前置不满足等） */
  原因?: string;
}

