/**
 * 活侠传 · 行动结算
 *
 * ★ 职责：把「玩家选了一个行动」这件事跑完。
 *   流程：判前置 → 扣行动点 → 掷判定 → 应用产出 → 扫过期 → 出报告
 *
 * ★ 设计原则：
 *   1. **纯函数**：吃旧变量，吐新变量 + 报告。不碰 IO，可单测、可重放
 *   2. **引擎只算**：所有数值变化都经 lib.* ，本文件不自己写公式
 *   3. **报告分两份**：
 *      · 给 AI 的（叙事清单）—— 只说「做成了/没做成」，不给数字
 *      · 给玩家的（界面）—— 完整数值变化
 *      ★ 这两份绝不能混，混了就等于把数值漏给 AI
 *
 * ★ 时间推进：
 *   行动点归零 → 跨旬。跨旬时清 `本旬已用`、扫一次过期窗。
 *   时间由本文件推进，**AI 不得自行改年/月/旬**。
 */

