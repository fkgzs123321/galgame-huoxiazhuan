/**
 * 用引擎跑一次判定。
 *
 * ★ 引擎真实签名（从 引擎.js 读出，不是猜的）：
 *     judge({ action, values, weights, base, diffMult, targetMod, stageMod, envMod })
 *     → { success, tier, tier_label, effect_mult, diff, success_rate, roll }
 *
 * ★ 骰子不接收外部 seed —— 引擎内部维护 LCG 状态（`_lcgState`），
 *   用 `judgeSeedOut()` 取、需要时用返回值写回。同一状态重放结果一致。
 */
function 掷判定(变: any, 行动: any, 难度: keyof typeof 标定.难度乘数 = '普通') {
  try {
    const res = (lib as any).judge({
      action: 行动.id || 行动.名,
      values: {
        拳掌: Number(取(变, '你.八系.拳掌')) || 0,
        暗器: Number(取(变, '你.八系.暗器')) || 0,
        轻功: Number(取(变, '你.轻功')) || 0,
        修养: Number(取(变, '你.修养')) || 0,
        学问: Number(取(变, '你.学问')) || 0,
        嘴力: Number(取(变, '你.嘴力')) || 0,
      },
      weights: { 拳掌: 1, 暗器: 1.2, 轻功: 1, 修养: 0.6, 学问: 0.8, 嘴力: 0.8 },
      base: 标定.对手基准.开局,
      diffMult: 标定.难度乘数[难度],
    });

    // ★ 失败也分级：大失败 / 失败 都算「没做成」，但档位记下来给前端
    return {
      成: !!res?.success,
      档: String(res?.tier_label ?? ''),
      倍率: Number(res?.effect_mult) || 1,
      差值: Number(res?.diff) || 0,
    };
  } catch (e) {
    console.warn('[活侠传] 判定失败，按无需判定处理', e);
    return { 成: true, 档: '', 倍率: 1, 差值: 0 };
  }
}

