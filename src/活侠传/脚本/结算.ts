const 旬序 = ['上旬', '中旬', '下旬'] as const;

/** 跨一旬。返回是否跨了年 */
function 跨旬(变: any): void {
  const 当 = String(取(变, '世界.旬') || '上旬');
  const i = 旬序.indexOf(当 as (typeof 旬序)[number]);
  if (i < 2) {
    设(变, '世界.旬', 旬序[i + 1]);
  } else {
    设(变, '世界.旬', '上旬');
    const 月 = Number(取(变, '世界.月')) || 1;
    if (月 >= 12) {
      设(变, '世界.月', 1);
      设(变, '世界.年', (Number(取(变, '世界.年')) || 1) + 1);
    } else {
      设(变, '世界.月', 月 + 1);
    }
  }
  // ★ 新的一旬：清空「本旬已用」，行动点回满
  设(变, '前置.本旬已用', '');
  设(变, '世界.行动次数', Number(取(变, '世界.行动上限')) || 3);
  // 节点名同步
  const 年 = 取(变, '世界.年');
  const 月 = 取(变, '世界.月');
  const 旬 = 取(变, '世界.旬');
  设(变, '世界.当前节点', `第${年}年_${月}月${旬}`);
}

