/** 当前能做什么（给界面渲染按钮用） */
export function 当前可做(变: any): 可选项[] {
  const 基础 = 能做什么(变);

  // ★ 叠加原作事件：这些是「到了这一旬就该发生」的事，不是玩家点的行动。
  //   它们与原作 story-branch-timeline 对齐，带真实时间窗与前置。
  const 年 = Number(取(变, '世界.年')) || 1;
  const 月 = Number(取(变, '世界.月')) || 1;
  const 旬 = String(取(变, '世界.旬') || '上旬');
  const 已错过 = String(取(变, '前置.已错过') || '').split('、').filter(Boolean);
  const 已完成 = String(取(变, '前置.已解锁') || '').split('、').filter(Boolean);

  const 事件 = 当前该出的(年, 月, 旬, [...已错过, ...已完成])
    // 前置也得满足
    .filter(e => 判一组(e.前置, 变))
    // 行动点够
    .filter(e => e.耗行动 <= (Number(取(变, '世界.行动次数')) || 0))
    .map(e => ({
      id: e.id,
      名: e.名,
      地点: e.地点,
      耗行动: e.耗行动,
      // 标记来源，界面可以区分「日常行动」与「原作事件」
      来源: '事件' as const,
      类别: e.类别,
    }));

  // ★★ 叠加原作养成指令：312 条，按当前位置抽几条。
  //   原作的日常不是「选一个抽象行动」，而是「在某地做某件具体的事」。
  const 养成 = 取养成候选(变);

  // ★★★ 叠加原作事件目录（全四年 181 条，按当前路线筛）。
  //   与上面的「事件」不同：那些带选项与数值（第一年 24 条），
  //   这些只有名字与详情页，但**覆盖到第三年**，且带**路线分支**。
  const 路线 = String(取(变, '世界.路线') || '');
  const 目录项 = 该旬路线(年, 月, 旬 === '上旬' ? 1 : 旬 === '中旬' ? 2 : 3, 路线)
    .filter(d => !已完成.includes(d.名) && !已错过.includes(d.名))
    .filter(d => !事件.some(e => e.名 === d.名))  // 与上面那批去重
    .map(d => ({
      id: `目录_${d.时}_${d.名}`,
      名: d.名,
      耗行动: 0,                                   // 目录只提示该发生什么，不额外扣行动
      来源: '事件' as const,
      类别: d.路线 ? `路线·${d.路线}` : '主线',
    }));

  return [...基础, ...事件, ...养成, ...目录项];
}

/**
 * 从原作养成表里抽当前可做的几条。
 *
 * ★ 为什么不像行动表那样全列出来：312 条太多，界面放不下。
 *   原作的做法是「按权重随机抽」——所以这里也用权重抽样。
 * ★ 用确定性伪随机：同种子同结果，重渲染不会变。
 */
function 取养成候选(变: any): 可选项[] {
  const 地点 = String(取(变, '世界.当前地点') || '');
  const 心相值 = Number(取(变, '你.心相')) || 50;
  const 档 = 心相档(心相值);
  const 掷 = ((Number(取(变, '世界.随机种子')) || 20260927) % 1000) / 1000;

  // 优先当前位置；位置没数据就用「唐家大院」（唐门本部）
  let 候选 = 地点 ? 养成表.filter(x => x.地点 === 地点) : [];
  if (!候选.length) 候选 = 养成表.filter(x => x.地点 === '唐家大院');
  if (!候选.length) return [];

  // 去掉权重为 0 的
  候选 = 候选.filter(x => x.权重 > 0);

  // 按权重抽 3 条（用不同偏移，保证不重复）
  const 出: 可选项[] = [];
  const 已抽 = new Set<string>();
  for (let i = 0; i < 3 && i < 候选.length; i++) {
    const 偏移 = (掷 + i * 0.37) % 1;
    let 总 = 候选.reduce((s, x) => s + x.权重, 0);
    let 落 = 偏移 * 总;
    let 选 = 候选[候选.length - 1];
    for (const x of 候选) {
      落 -= x.权重;
      if (落 <= 0) {
        选 = x;
        break;
      }
    }
    const 键 = 选.地点 + 选.动作 + 选.事件;
    if (已抽.has(键)) continue;
    已抽.add(键);

    // 这一档的实际效果（给界面显示）
    const 效果 = 选.效果[档] ?? {};
    出.push({
      id: `养成_${选.地点}_${选.动作}_${选.事件}`,
      名: 选.事件 || 选.动作,
      地点: 选.地点,
      耗行动: 1,
      来源: '养成' as const,
      档,
      效果,
    } as 可选项);
  }
  return 出;
}

/** 能否做某个行动（用于按钮置灰） */
export function 可以做(变: any, id: string): boolean {
  const 行动 = 行动表.find((a: any) => a.id === id);
  const 单元 = 单元表.find((u: any) => u.id === id);
  const 源: any = 行动 || 单元;
  if (!源) return false;
  if (!判一组(源.前置, 变)) return false;
  const 耗 = Number(源.耗行动 ?? 源.行动点 ?? 1);
  return (Number(取(变, '世界.行动次数')) || 0) >= 耗;
}

