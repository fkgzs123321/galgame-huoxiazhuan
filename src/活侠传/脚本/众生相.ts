/** 按归类取 */
export function 取类(类: string): 众生[] {
  return 众生表.filter(x => x.类 === 类);
}

/** 按关键词找（谁跟这地方/这人有关） */
export function 找相关(词: string): 众生[] {
  return 众生表.filter(x => x.关键词.includes(词));
}

/**
 * 给界面的：此地有谁 —— **只回人名**。
 *
 * ★ 区别于 找相关()：那个是按关键词搜、结果里混着事件名，
 *   适合喂给 AI 写「这儿可能遇上的事」；
 *   界面要拿名字去取立绘，混进事件名就会出现空白框。
 */
export function 此地人名(地点: string): string[] {
  return 众生表
    .filter(x => x.有人名 && x.关键词.includes(地点))
    .map(x => x.名);
}

/** 给 AI 的一行速览：某地可能会遇见谁（含事件与群体） */
export function 此地有谁(地点: string): string[] {
  return 找相关(地点).map(x => x.名 + (x.人数 > 1 ? `（${x.人数} 人）` : ''));
}

export default { 众生表, 取类, 找相关, 此地人名, 此地有谁 };
