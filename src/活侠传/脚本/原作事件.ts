/** 按时间取当前该出现的事件 */
export function 当前该出的(年: number, 月: number, 旬: string, 已错过: string[] = []): 原作事件[] {
  const s = 旬 === '上旬' ? 1 : 旬 === '中旬' ? 2 : 3;
  const now = (年 - 1) * 36 + (月 - 1) * 3 + (s - 1);
  return 原作事件表.filter(e => {
    if (已错过.includes(e.id)) return false;
    const w = e.窗 as { 类型: string; 值?: [number, number, number]; 每?: number };
    if (w.类型 === '特定' && w.值) {
      const t = (w.值[0] - 1) * 36 + (w.值[1] - 1) * 3 + (w.值[2] - 1);
      return now === t;
    }
    if (w.类型 === '周期' && w.每) return now % w.每 === 0;
    return false;
  });
}

