/** 心相值 → 档位（原作分界 32 / 64） */
export function 心相档(值: number): 心相档 {
  const v = Number(值) || 0;
  if (v <= 32) return '低落';
  if (v <= 64) return '平常';
  return '高昂';
}

/** 按地点筛（界面用） */
export function 地点指令(地点: string): 养成指令[] {
  return 养成表.filter(x => x.地点 === 地点);
}

/**
 * 按权重随机挑一条 —— 用确定性伪随机（同种子同结果）。
 * ★ 不用 Math.random：那样同一回合重渲染结果会变。
 */
export function 抽一条(地点: string, 掷: number): 养成指令 | null {
  const 选 = 地点指令(地点).filter(x => x.权重 > 0);
  if (!选.length) return null;
  const 总 = 选.reduce((s, x) => s + x.权重, 0);
  let 落 = (掷 % 1) * 总;
  for (const x of 选) {
    落 -= x.权重;
    if (落 <= 0) return x;
  }
  return 选[选.length - 1];
}

export default { 养成表, 心相档, 地点指令, 抽一条 };
