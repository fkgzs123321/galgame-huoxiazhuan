/** 以当前武学点，从 from 能升到几级 */
export function 能升到几级(变: any, from: number) {
  const 点 = Number(变.你?.武学点) || 0;
  let lv = from;
  let 用 = 0;
  for (let i = 0; i < 200; i++) {
    const c = Number(升级代价(lv + 1)) || 0;
    if (用 + c > 点) break;
    用 += c;
    lv++;
  }
  return { 到: lv, 用了: 用 };
}

