/**
 * 用一件消耗品。
 *
 * ★ 效果由引擎的 consume 施加，本模块只负责扣数量。
 * ★★ 上限必须取**人物自己的上限**（`你.体力.上限`），不是物品写死的数字。
 *    早先版本把 `上限` 写在物表里（999），结果体力能涨到 75 突破上限 50 —— 自测抓到的。
 */
export function 使用(变: any, 名: string, 次数 = 1) {
  const 有 = Number(变.物品?.[名]?.数量) || 0;
  if (有 < 次数) return { 可以: false, 原因: '数量不够' };

  const 定 = 取定义(名);
  if (!定.效果) return { 可以: false, 原因: `${名}不是能用的东西` };

  const 资源: Record<string, number> = {
    体力: Number(变.你?.体力?.当前) || 0,
    内力: Number(变.你?.内力?.当前) || 0,
    心相: Number(变.你?.心相) || 0,
  };

  // ★ 上限取人物当前上限
  const 上限: Record<string, number> = {
    体力: Number(变.你?.体力?.上限) || 9999,
    内力: Number(变.你?.内力?.上限) || 9999,
    心相: 100,
  };

  const r = L.consume(资源, { 效果: 定.效果, 上限 }, 次数);

  // 写回
  if (定.效果.体力 !== undefined) 变.你.体力.当前 = Number(r.现在.体力) || 0;
  if (定.效果.内力 !== undefined) 变.你.内力.当前 = Number(r.现在.内力) || 0;
  if (定.效果.心相 !== undefined) 变.你.心相 = Number(r.现在.心相) || 0;

  变.物品[名].数量 = 有 - 次数;
  if (变.物品[名].数量 <= 0) delete 变.物品[名];

  return { 可以: true, 用掉: 次数, 效果: 定.效果 };
}

