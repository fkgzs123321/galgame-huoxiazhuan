// 二、穿脱（★ 用引擎的 equip，槽位对不上会被它挡住）
// ══════════════════════════════════════════════════════════════

export function 穿上(变: any, 槽: string, 名: string) {
  if (!变.装备 || typeof 变.装备 !== 'object') 变.装备 = { 兵器: '', 防具: '', 暗器袋: '', 饰品: '' };
  // 物必须在背包里
  if (!变.物品?.[名]) return { 可以: false, 原因: '身上没有这件东西' };
  const 定 = 取定义(名);
  // 类别要对得上槽（暗器袋归暗器袋，别把飞刀插头上）
  if (定.类 !== 槽 && !(定.类 === '暗器' && 槽 === '暗器袋')) {
    return { 可以: false, 原因: `${名}不是${槽}` };
  }
  const r = L.equip(变.装备, 槽, 名);
  if (!r?.可以) return r;
  // ★ 换下来的东西不会消失 —— 只是不在身上了。数量不减（装备是"占用"而非"消耗"）
  return r;
}

/**
 * 脱下。
 * ★ 引擎的 `unequip` 返回 `{ 卸下: 旧值 }` —— 没有 `可以` 字段。
 *   这里统一成 `{ 可以, 卸下 }`，免得调用方要记两套形状。
 */
export function 脱下(变: any, 槽: string) {
  if (!变.装备 || typeof 变.装备 !== 'object') {
    return { 可以: false, 原因: '没有装备栏' };
  }
  const r = L.unequip(变.装备, 槽);
  return { 可以: true, 卸下: r?.卸下 ?? '' };
}

