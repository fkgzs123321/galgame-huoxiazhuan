/** 某物的实际加成（已按品质放大） */
export function 算加成(名: string): Record<string, number> {
  const 定 = 取定义(名);
  return L.实际加成({ 品质: 定.品质 ?? '凡', 加成: 定.加成 ?? {} }, 品质档位表);
}

/**
 * ★★ 装备后的人物输入 —— 基础值 + 四件装备的加成。
 * 前端与判定都用这个，保证「装备真的有用」。
 *
 * ★ 引擎的 `equipBonus(穿着表, 物表, 品质倍率)` 里，
 *   `物表` 是**按物品名索引**的（`物表[_id]`），不是按槽位。
 *   早先版本按槽位索引 → 查不到 → 加成恒为 0（静默失效，被自测抓到）。
 */
export function 装备后输入(变: any): Record<string, number> {
  const 基础 = {
    攻击: Number(变.你?.战斗?.攻击) || 0,
    防御: Number(变.你?.战斗?.防御) || 0,
    暗器威力: Number(变.你?.战斗?.暗器威力) || 0,
    闪避: Number(变.你?.轻功) || 0,
    心相: Number(变.你?.心相) || 0,
    抗毒: Number(变.你?.抗毒) || 0,
  };
  const 穿着 = 变.装备 ?? {};

  // ★ 按**物品名**索引，不是按槽位
  const 名表化: Record<string, any> = {};
  for (const 名 of Object.values(穿着)) {
    if (!名 || typeof 名 !== 'string') continue;
    const 定 = 取定义(名);
    名表化[名] = { 品质: 定.品质 ?? '凡', 加成: 定.加成 ?? {} };
  }
  const 倍 = Object.fromEntries(品质档位表.map(x => [x.名, x.倍率]));
  return L.装备后输入(基础, 穿着, 名表化, 品质档位表) ?? 基础;
}

/** 每个槽位现在的加成（界面显示用） */
export function 装备明细(变: any): Array<{ 槽: string; 名: string; 加成: Record<string, number> }> {
  const 穿着 = 变.装备 ?? {};
  const 出: Array<{ 槽: string; 名: string; 加成: Record<string, number> }> = [];
  for (const 槽 of ['兵器', '防具', '暗器袋', '饰品']) {
    const 名 = 穿着[槽];
    if (!名) continue;
    出.push({ 槽, 名, 加成: 算加成(名) });
  }
  return 出;
}

