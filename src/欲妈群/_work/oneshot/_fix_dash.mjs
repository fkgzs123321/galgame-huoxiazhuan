import fs from 'fs';
const F = ['_work/data/_basic_data.mjs', '_work/data/_basic_data_2.mjs'];
const 换 = [
  ['手术室——刀口深浅由她定', '手术室：刀口深浅由她定'],
  ['开始裂——酒一开', '开始裂。酒一开'],
  ['摘完才开口——那是同传箱里练出来的', '摘完才开口，那是同传箱里练出来的'],
  ['缺的是跟人说话——白天', '缺的是跟人说话。白天'],
  ['晒的是声音——一段一段的', '晒的是声音，一段一段的'],
  ['什么都敢说——这是她唯一的出口', '什么都敢说，这是她唯一的出口'],
  ['只剩一个动作——把那句被挑走的话学一遍', '只剩一个动作：把那句被挑走的话学一遍'],
  ['她出声最快——那是她身上唯一一处', '她出声最快，那是她身上唯一一处'],
  ['她只是觉得——他在，她就不空', '她只是觉得他在，她就不空'],
  ['你不是他妈了」——她当场就会哭', '你不是他妈了」，她当场就会哭'],
  ['连输两周——第三周', '连输两周，第三周'],
  ['她身上几乎没有汗味', '她身上没什么汗味'],
];
let n = 0;
for (const f of F) {
  let s = fs.readFileSync(f, 'utf8');
  for (const [a, b] of 换) if (s.includes(a)) { s = s.replace(a, b); n++; }
  fs.writeFileSync(f, s, 'utf8');
}
console.log('源头改 ' + n + ' 处');
const 剩 = F.map(f => (fs.readFileSync(f, 'utf8').match(/——|似乎|几乎|仿佛/g) || []).length).reduce((a, b) => a + b, 0);
console.log('源头残留禁则 ' + 剩 + ' 处');
