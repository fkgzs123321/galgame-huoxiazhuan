import fs from 'fs';
let n = 0;
const ed = (f, pairs) => {
  let t = fs.readFileSync(f, 'utf8'), hit = 0;
  for (const [a, b] of pairs) { const c = t.split(a).length - 1; if (c) { t = t.split(a).join(b); hit += c; } else console.log('  ⚠ 未命中 ' + f.split(/[\\/]/).pop() + ' 「' + a.slice(0, 30) + '」'); }
  fs.writeFileSync(f, t, 'utf8'); n += hit;
  console.log('✓ ' + f.split(/[\\/]/).pop().padEnd(30) + hit + ' 处');
};

