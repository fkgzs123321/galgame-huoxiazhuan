// 把「行为类型表」与「六、状态修正速查」换成 E3 的契参数（面板就用这一套）
import fs from 'fs';
const F = '世界书/[mvu_plot]D20对抗判定系统.txt';
let t = fs.readFileSync(F, 'utf8');
const eol = t.includes('\r\n') ? '\r\n' : '\n';
let n = 0;

// ① 行为类型表（旧：侦察轮修正/行动轮DC/反应轮对抗）→ 换成"每条选项自己带技能/等级/主对"
const i1 = t.indexOf('| 行为类型 | 侦察轮修正 | 行动轮DC | 反应轮对抗 | 说明 |');
const i2 = t.indexOf('- 情境加成：', i1);
if (i1 > 0 && i2 > i1) {
  const 新 = [
    '每条选项**自己带三个参数**，公式因此不同（这就是"每个选项的判定公式不同"）：',
    '',
    '| 参数 | 取值 | 作用 |',
    '|---|---|---|',
    '| `技能` | 观察／行动／意志 | 决定用他哪一项能力值当 P 的主项 |',
    '| `等级` | 微／中／强／极 | 决定基础要求：**微 15 ／ 中 35 ／ 强 45 ／ 极 55** |',
    '| `主对` | 识破／拦住／扛住／全场 | 决定三轮权重，以及拿她的哪一项当对手：识破→勇气／拦住→痴迷／扛住→兴奋／全场→三项平均 |',
    '',
    '**要求值 R = clamp(基础要求 × 难度乘 × (1 + 她强度/100 × 0.15) + 阶段修正, 0, 100)**',
    '- 难度乘（★乘法，不是加法）：普通 **0.55** ／ 困难 **0.95** ／ 地狱 **1.35**',
    '- 阶段修正（加在**她的要求**上，不是扣他的分）：阶段1 **0** ／ 阶段2 **4** ／ 阶段3 **9** ／ 阶段4 **15** ／ 阶段5 **24**',
    '',
  ].join(eol);
  t = t.slice(0, i1) + 新 + t.slice(i2);
  n++; console.log('✓ 行为类型表 → E3 契参数');
}

// ② 「六、状态修正速查」整节 → 说明"参数在面板，这里只记口径"
{
  const j1 = t.indexOf('## 六、状态修正速查');
  const j2 = t.indexOf('\n## ', j1 + 5);
  if (j1 > 0) {
    const 新 = [
      '## 六、能力值 P 怎么算（三轮是三视角，不是三次掷骰）',
      '',
      '| 轮 | 取哪些值 | 权重 |',
      '|---|---|---|',
      '| 侦察轮 P1 | 他 `技能.观察` ×3 ＋ 他 `心理.理智` ×1 ＋ 他 `警觉度` ×1 | ÷5 |',
      '| 行动轮 P2 | 他 `技能.{本条选项的技能}` ＋ 意志判定修正 | ×1 |',
      '| 反应轮 P3 | 他 `技能.意志` ×3 ＋ 她 `后门进度` ×1 | ÷4 |',
      '',
      '**P = (P1×w1 + P2×w2 + P3×w3) ÷ (w1+w2+w3)**，权重 w 由这一条的 `主对` 给（见第五节）。',
      '',
      '★ 三轮**只是三个视角**：引擎规范要求"能力值＝加权平均"（权重归一化），所以三轮是**算 P 的三个分量**，不是三次骰子。',
      '★ 骰子只有一颗：`V = LCG(seed) × 100`，由前端面板跑，同一回合结果固定。',
      '',
    ].join(eol);
    t = t.slice(0, j1) + 新 + t.slice(j2 + 1);
    n++; console.log('✓ 状态修正速查 → P 的三个分量表');
  }
}

// ③ 每日大赛的「3 轮 D20」→ 竞赛是叙述评分，不掷骰
const a = '- 每日一赛，3 轮 D20：准备轮（准备度vs主题难度）→ 表现轮（表现vs评委评分）→ 结果轮（群友反应vs影响）';
if (t.includes(a)) {
  const b = '- 每日一赛，按三轮**叙述评分**（准备度 vs 主题难度 → 表现 vs 评委评分 → 群友反应 vs 影响）：这一项由你按人设与剧情写，**不掷骰**；名次与积分由前端按 `今日得分` 排。';
  t = t.replace(a, b); n++; console.log('✓ 每日大赛三轮口径');
}

fs.writeFileSync(F, t, 'utf8');
console.log('\n共 ' + n + ' 处');
