// 思维链重做：改成纯文字（不带标签）＋ 卡里那条默认关闭 ＋ 清理 5 处对 <thinking> 的死引用
import fs from 'fs';
const eolOf = t => (t.includes('\r\n') ? '\r\n' : '\n');
let n = 0;
const ed = (f, pairs) => {
  let t = fs.readFileSync(f, 'utf8'); const eol = eolOf(t); let hit = 0;
  for (const [a, b] of pairs) {
    const A = a.split('\n').join(eol), B = b.split('\n').join(eol);
    const c = t.split(A).length - 1;
    if (!c) { console.log('  ⚠ 未命中 ' + f.split(/[\\/]/).pop() + ' 「' + a.slice(0, 34) + '」'); continue; }
    t = t.split(A).join(B); hit += c;
  }
  fs.writeFileSync(f, t, 'utf8'); n += hit;
  console.log('✓ ' + f.split(/[\\/]/).pop().padEnd(30) + hit + ' 处');
};

