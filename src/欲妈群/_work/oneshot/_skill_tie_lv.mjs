// 给 skills 的 conventions.md 补一条：「铁律」是保留词 + 清单内不许混用强调等级
import fs from 'fs';
const F = '.skills/tavern-cards/references/conventions.md';
let t = fs.readFileSync(F, 'utf8');
if (t.includes('「铁律」是保留词')) { console.log('已有，跳过'); process.exit(0); }

const add = `## 「铁律」是保留词，别当语气词用

**「铁律」在本工作区有明确定位**：它指**最高优先级、编号的宪章条款**——
见 \`independent-narrative-app/SKILL.md\` 的「全局执行铁律（最高优先级）」：
> 铁律 0–12 **高于所有 \`references/*.md\`、模板和阶段建议**。分册只能细化铁律，不能覆盖、绕过或把"必须"降级为建议。

所以：

| 层级 | 能叫「铁律」吗 | 本卡示例 |
|---|---|---|
| 世界宪法 / 卡级硬约束 / 编号宪章 | ✅ 可以 | \`[mvu_plot]防口胡与世界观铁律\`、\`私密通用规范 · 信息隔离铁律\`、\`共感假阳具系统 · 绝对唯一性（铁律）\` |
| **给某个模型的当轮操作约束、字段格式细则、路径规则** | ❌ **不许** | 变量更新规则里的「路径规则」、输出格式细则 |

反例（真实踩过）：把「\`变量更新规则._path_rules\`」的标题写成「★★★ 路径**铁律**（违反则更新失败）★★★」——
它只是给变量模型的操作细则，层级远低于宪章；用「铁律」会让这个词失去区分度。

### 同一份清单里不许混用强调等级

**清单标题已经声明了严重性（如"违反则更新失败"），条目就不要逐条再标 \`★★★\` / \`★\`。**
要么全都不标，要么全部同一等级——**只有一处例外时，那处才配得上加强**。

反例：原有 5 条都没标 ★，新加的 2 条却标了 \`★★★\` → 同清单内等级乱套，读的人无法判断谁更重要。

### 顺带：规则条目禁 Markdown 粗体

\`**这样**\` 的星号在规则/条目文本里一律不许出现（详见 \`references/rules-check.md\` 的禁则扫描）。
要强调就用「」或直接换行，别用 \`**\`。

---

`;

const anchor = '## 条目名称前缀';
const i = t.indexOf(anchor);
if (i < 0) { console.log('⚠ 找不到锚点'); process.exit(1); }
fs.writeFileSync(F, t.slice(0, i) + add + t.slice(i), 'utf8');
console.log('✅ 已插入「铁律是保留词」章节（' + add.length + ' 字符）');
