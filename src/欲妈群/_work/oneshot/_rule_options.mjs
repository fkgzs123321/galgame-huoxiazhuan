// ── ① D20 条目第五节：加「每轮必须重摆」铁律
{
  const F = CARD + '/世界书/[mvu_plot]D20对抗判定系统.txt';
  let t = fs.readFileSync(F, 'utf8');
  const eol = t.includes('\r\n') ? '\r\n' : '\n';
  const 锚 = '## 五、她每轮摆的选项 = 写进 `局面.当前选项`（面板据此渲染）';
  if (t.indexOf(锚) < 0) { console.log('⚠ 第五节锚点未命中'); }
  else {
    const 新 = [
      '## 五、她每轮摆的选项 = 写进 `' + '局面.当前选项' + '`（面板据此渲染）',
      '',
      '> ★★ **铁律：每一轮回复，你都必须把四格重新摆满。**',
      '> 面板上那四个按钮**不是存下来的** —— 它是**你上一轮写进变量的**。',
      '> 玩家点掉一格 → 面板当场跑判定、**清空那一格** → 把结果推给你',
      '> → **你写这一轮时，必须把四格重新写成新的四条**（被点掉的那格也要给新内容）。',
      '> **不重摆 = 下一轮面板上没有按钮，玩家无事可做 —— 这是硬伤，比写得不好严重。**',
      '> 新一轮的四条要反映她这一轮的**新打算**，不要照抄上一轮。',
      '',
    ].join(eol);
    t = t.replace(锚, 新);
    // 把「清空那一格」那句改清楚
    t = t.replace(
      '- 他点了「顺着」或「拒」之后，**面板当场跑完判定、清空那一格，并把结果推给你**。只按推来的结果写这一轮。',
      '- 时序：玩家点了「顺着」或「拒」→ 面板当场跑完判定、**清空那一格**、把结果推给你 →\n  **你按结果写这一轮，并在同一轮的 JSONPatch 里把四格重新摆成新的四条**（含被点掉的那格）。'
    );
    fs.writeFileSync(F, t, 'utf8');
    console.log('✓ D20 条目第五节：加了「每轮重摆」铁律');
  }
}

