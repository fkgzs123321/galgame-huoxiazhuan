// 重复审计 6 项一次性落地
import fs from 'fs';

const log = [];
const edit = (file, fn, tag) => {
  const before = fs.readFileSync(file, 'utf8');
  const after = fn(before);
  const d = before.length - after.length;
  if (after !== before) fs.writeFileSync(file, after, 'utf8');
  log.push([tag, file.split(/[\\/]/).pop(), d]);
};

