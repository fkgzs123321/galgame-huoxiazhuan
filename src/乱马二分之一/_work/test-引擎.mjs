// ════════════════════════════════════════════════════════════
// test-引擎.mjs · 面板引擎 + 契约值 的验收
//
// 测四件事：
//   一 引擎本身（抽自 引擎能力/*.txt）行为正确
//   二 契约值合法（状态表每项都有「意义」、范围完整）
//   三 ★ 标定：三个时点的成功率命中 60 / 75 / 90，且四条验收清单全过
//   四 真打一场（fight 逐回合真跑），摘要与注入纪律都在
//
// 用法: node src/乱马二分之一/_work/test-引擎.mjs
// ════════════════════════════════════════════════════════════
import fs from 'node:fs';
import { 契约 } from './契约值.mjs';

let pass = 0, fail = 0;
const ok = (c, n, extra = '') => { c ? (pass++, console.log('  [OK]   ' + n)) : (fail++, console.log('  [FAIL] ' + n + (extra ? '  → ' + extra : ''))); };
const 段 = t => console.log('\n' + t);
const 约 = (a, b, tol = 1) => Math.abs(a - b) <= tol;

// ── 载入引擎（与面板同一份）──
const src = fs.readFileSync('src/乱马二分之一/脚本/引擎.js', 'utf8');
let 种子 = 20260922;
const getvar = p => (p === 'stat_data.主角.$骰子种子' ? 种子 : null);
const lib = new Function('getvar', src)(getvar);

console.log('='.repeat(74));
console.log('乱马二分之一 · 引擎 + 契约值 验收');
console.log('='.repeat(74));

// ════════════════════════════════════════════════════════════
段('一、引擎本体（抽自 引擎模板/引擎能力/，可 diff 复核）');
// ════════════════════════════════════════════════════════════
const 应有 = ['judge', 'judgeTier', 'judgePower', 'judgeRequire', 'derive', 'overall',
  'rateFromDiff', 'snapshot', 'entrance', 'strike', 'fight', 'multi', 'summarize', 'injectRule', '受伤档'];
ok(应有.every(k => typeof lib[k] === 'function'), '15 个入口方法全部就位',
  应有.filter(k => typeof lib[k] !== 'function').join(','));

// bug① 不复现
let 矛盾 = 0;
for (let d = -60; d <= 60; d++) for (const s of [true, false]) {
  const t = lib.judgeTier(d, s);
  if (!s && String(t.key).startsWith('critical_success')) 矛盾++;
  if (s && String(t.key).startsWith('critical_failure')) 矛盾++;
}
ok(矛盾 === 0, '档位与成败同源（穷举 121×2，原实现会命中）', 矛盾 + ' 例');

// bug② 不复现
ok(lib.judgeRequire(60, 1, 0, -20) < lib.judgeRequire(60, 1, 0, 0), '阶段修正是真参数，不是占位 0');

// 难度乘法
ok(lib.judgeRequire(30, 0.8, 0, 0) === 24 && lib.judgeRequire(60, 2.0, 0, 0) === 100,
   '难度用乘法且夹紧 0~100');

// LCG
lib._lcgState = 20260922; const s1 = [lib._roll(), lib._roll()];
lib._lcgState = 20260922; const s2 = [lib._roll(), lib._roll()];
ok(s1[0] === s2[0] && s1[1] === s2[1], 'LCG 同种子同序列（可复现，禁 Math.random）');

// 权重归一化
ok(lib.judgePower({ a: 60, b: 40 }, { a: 1.5, b: 1 }) === lib.judgePower({ a: 60, b: 40 }, { a: 15, b: 10 }),
   '权重整体放大 10 倍，能力值不变（归一化）');

// C4 derive
const dv = lib.derive(契约.派生表, { 早乙女流: 60, 体格: 80, 灵巧: 80, 湿度: 0 });
ok(dv.攻击 === 70 && dv.命中 === 72 && dv.防御 === 34, 'C4 派生：攻击/命中/防御 计算正确',
   JSON.stringify(dv));
ok(dv.攻击 > dv.防御 * 1.5, '攻击与防御不同量级 → 伤害不会恒为 1（否则一场永远打不完）',
   dv.攻击 + ' vs ' + dv.防御);
ok(lib.derive(契约.派生表, { 灵巧: 80, 体格: 80, 湿度: 100 }).闪避 ===
   lib.derive(契约.派生表, { 灵巧: 80, 体格: 80, 湿度: 0 }).闪避 - 15,
   '湿度每 100 点使闪避 −15（身上越湿越滑手）');

// ════════════════════════════════════════════════════════════
段('二、契约值合法性（机制层规范 T2：填不出「意义」的状态不许存在）');
// ════════════════════════════════════════════════════════════
ok(契约.状态表.every(s => s.意义 && s.意义.length >= 8),
   '每个状态都写了「意义」(' + 契约.状态表.length + ' 个)',
   契约.状态表.filter(s => !s.意义).map(s => s.名).join(','));
ok(契约.状态表.every(s => Array.isArray(s.范围) && s.范围.length === 2 && s.范围[1] > s.范围[0]),
   '每个状态的范围合法');
ok(契约.状态表.every(s => s.初值 >= s.范围[0] && s.初值 <= s.范围[1]), '初值落在范围内');

const 行动总耗 = Object.values(契约.行动).reduce((a, x) => a + x.耗气, 0);
ok(Object.keys(契约.行动).length === 7, '七个行动齐备');
ok(契约.行动.绝招.耗气 === 5 && 契约.气上限 === 10,
   '绝招耗气 5 / 气上限 10 → 一局最多两发绝招（真取舍）');
ok(契约.克制链.length === 4, '克制链四条');

const 强度值 = Object.values(契约.角色强度);
ok(强度值.every(v => v % 10 === 0 && v >= 0 && v <= 90), '角色强度都落在 T0~T9 的档位上');
ok(契约.角色强度['八宝斋'] === 90 && 契约.角色强度['早乙女乱马'] === 60,
   '八宝斋 T9 / 乱马 T6 → 「乱马打不过八宝斋」是数值事实');

// ════════════════════════════════════════════════════════════
段('三、★ 标定：三个时点命中 60 / 75 / 90（从目标反推，不盲搜）');
// ════════════════════════════════════════════════════════════
const 值表 = 卷 => {
  const o = {};
  for (const s of 契约.状态表) o[s.名] = s.名 === '气势' ? s.初值 : s.初值 + (卷 - 1) * s.每卷成长;
  return o;
};
const P = 卷 => lib.overall(值表(卷), 契约.总评权重, 契约.总评忽略);
const S = (P值, R值) => Math.max(5, Math.min(95, 50 + P值 - R值));

const 时点 = 契约.标定.三个时点;
const 基准 = 契约.标定.对手基准;
const 难度 = 契约.标定.难度乘数;

const 曲线 = {};
for (const 档 of ['轻松', '普通', '挑战', '地狱']) {
  曲线[档] = ['开局', '中期', '后期'].map(k => {
    const R = 基准[k] * 难度[档];
    return Math.round(S(P(时点[k]), R) * 10) / 10;
  });
}

console.log('    P（总评）：开局 ' + P(时点.开局).toFixed(2) +
  ' ／ 中期 ' + P(时点.中期).toFixed(2) + ' ／ 后期 ' + P(时点.后期).toFixed(2));
for (const 档 of ['轻松', '普通', '挑战', '地狱']) {
  console.log('    ' + 档.padEnd(4) + '  ' + 曲线[档].join(' ／ '));
}

const 普通 = 曲线.普通, 目标 = 契约.标定.目标成功率.普通;
ok(约(普通[0], 目标.开局), '普通档 开局 ≈ ' + 目标.开局, String(普通[0]));
ok(约(普通[1], 目标.中期), '普通档 中期 ≈ ' + 目标.中期, String(普通[1]));
ok(约(普通[2], 目标.后期), '普通档 后期 ≈ ' + 目标.后期, String(普通[2]));

// 验收清单① 三档全程单调
let 单调 = true;
for (let i = 0; i < 3; i++) {
  if (!(曲线.轻松[i] >= 曲线.普通[i] && 曲线.普通[i] >= 曲线.挑战[i] && 曲线.挑战[i] >= 曲线.地狱[i])) 单调 = false;
}
ok(单调, '清单①：四档全程单调（三个时点都查）');

// 验收清单② 不出现 100 或 0
const 全部 = Object.values(曲线).flat();
ok(全部.every(v => v > 0 && v < 100), '清单②：没有任何一档出现 100% 或 0%', '极值 ' + Math.max(...全部) + '/' + Math.min(...全部));

// 验收清单③ 成长要真有用
const 初 = P(1), 满 = P(38);
ok(S(满, 基准.开局) - S(初, 基准.开局) > 30, '清单③：单把等级从初值拉满，成功率显著上升',
   S(初, 基准.开局).toFixed(1) + ' → ' + S(满, 基准.开局).toFixed(1));

// 验收清单④ 对手强度拉满要显著变难
ok(S(P(时点.后期), 基准.开局) - S(P(时点.后期), 基准.后期 * 难度.地狱) > 30,
   '清单④：单把对手强度拉满，成功率显著下降',
   S(P(时点.后期), 基准.开局).toFixed(1) + ' → ' + S(P(时点.后期), 基准.后期 * 难度.地狱).toFixed(1));

// ════════════════════════════════════════════════════════════
段('四、真打一场（fight 逐回合真跑，不是叙事安排）');
// ════════════════════════════════════════════════════════════
const 造单位 = (名, 总评, 风格) => {
  const f = 契约.风格[风格] || {};
  const 派生 = lib.derive(契约.派生表, { 早乙女流: 总评, 体格: 总评, 灵巧: 总评, 湿度: 0 });
  return {
    名, 总评,
    上限: 100, 生命: 100,
    攻击: Math.round(派生.攻击 * (f.伤害乘 || 1)),
    防御: Math.round(派生.防御 * (f.防御乘 || 1)),
    出手值: 总评 + (f.出手值 || 0),
    命中: 契约.战斗.命中率,
    闪避: 契约.战斗.命中率,
    有效值: 100,
  };
};

种子 = 20260922; lib._lcgState = 种子;
const 场 = lib.fight({
  我方: 造单位('早乙女乱马', 62, '风快攻'),
  对方: 造单位('响良牙', 58, '火爆发'),
  上限回合: 契约.战斗.上限回合,
  计有效值: true,
}, () => lib._r());

ok(场.胜者 !== '未决', '★ 普通对局在 8 回合内分出胜负（不是场场打满）',
   '结果 ' + 场.胜者 + ' ／ ' + 场.回合数 + ' 回合');
ok(场.回合数 <= 契约.战斗.上限回合, '回合数不超过上限 ' + 契约.战斗.上限回合);
ok(Array.isArray(场.日志) && 场.日志.length === 场.回合数, '日志逐回合都在（玩家能自己验算）');
ok(场.日志.every(r => Array.isArray(r.动作)), '每回合都有动作明细');
ok(场.摘要 && 场.摘要.结果 && 场.摘要.写法约束, '摘要含结果与写法约束');
ok(!JSON.stringify(场.摘要).match(/掷值|命中率|公式/), '摘要里不含掷值与命中率（注入纪律）');
const 注入 = lib.injectRule();
ok(/不要自己重算/.test(注入) && /不要写出掷值/.test(注入), '注入纪律：不许重算、不许写数值');

// 确定性：同种子同结果
const 再跑 = (() => {
  lib._lcgState = 20260922;
  return lib.fight({
    我方: 造单位('早乙女乱马', 62, '风快攻'),
    对方: 造单位('响良牙', 58, '火爆发'),
    上限回合: 契约.战斗.上限回合, 计有效值: true,
  }, () => lib._r());
})();
ok(再跑.胜者 === 场.胜者 && 再跑.回合数 === 场.回合数,
   '同种子 → 同一结果（面板重渲染不会变）', 场.胜者 + ' vs ' + 再跑.胜者);

// 强度差真的说话：乱马 vs 八宝斋
const 强者 = (() => {
  lib._lcgState = 20260922;
  return lib.fight({ 我方: 造单位('早乙女乱马', 62, '风快攻'), 对方: 造单位('八宝斋', 90, '山防守'), 上限回合: 12, 计有效值: true }, () => lib._r());
})();
ok(强者.胜者 === '对方', '乱马打八宝斋（62 vs 90）→ 输。强度差不靠叙事安排', 强者.胜者);

// ── 收尾 ──
console.log('\n' + '='.repeat(74));
console.log('通过 ' + pass + ' / 失败 ' + fail);
console.log('='.repeat(74));
process.exit(fail ? 1 : 0);
