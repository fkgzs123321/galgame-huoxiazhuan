// ── 8. 判定引擎（注入通道，只能 var）──
文件['判定引擎.txt'] = `@@generate_before
<%
var _判 = getvar('stat_data.局面.判定结果', { defaults: {} }) || {};
var _战 = getvar('stat_data.局面.战斗结果', { defaults: {} }) || {};
var _出 = '';
if (_判 && _判.success_rate !== undefined) {
  _出 += '本次判定（引擎已经算完，直接采信）：' + '\\n'
    + '  动作：' + String(_判.action || '') + '\\n'
    + '  档位：' + String(_判.tier_label || '') + '　效果倍数：' + String(_判.effect_mult || 1) + '\\n'
    + '  不要自己重算，不要写出掷值与成功率。结算完之后把 局面.判定结果 写成空表。' + '\\n';
}
if (_战 && _战.结果) {
  _出 += '本次战斗（引擎已经算完，直接采信）：' + '\\n'
    + '  结果：' + String(_战.结果 || '') + '　回合数：' + String(_战.回合数 || '') + '\\n'
    + '  我方：' + String(_战.我方状态 || '') + '\\n'
    + '  对方：' + String(_战.对方状态 || '') + '\\n';
  if (_战.不可逆 && _战.不可逆.length) {
    _出 += '  不可逆：' + _战.不可逆.join('；') + '\\n';
  }
  _出 += '  不要自己重算胜负，不要写出掷值、命中率、伤害数字。' + '\\n';
  if (_战.写法约束 && _战.写法约束.length) {
    _出 += '  按写法约束写：' + _战.写法约束.join('；') + '\\n';
  }
  _出 += '  结算完之后把 局面.战斗结果 写成空表。' + '\\n';
}
%>
<%= _出 %>
`;

for (const [名, 内容] of Object.entries(文件)) {
  fs.writeFileSync(path.join(目录, 名), 内容.split('\n').join('\r\n'));
  console.log('写入 ' + 名.padEnd(18) + 内容.length + ' 字符');
}
