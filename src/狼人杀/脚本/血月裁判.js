// 玩家行动校验（UI 是唯一入口，但裁判自校验防 UI bug / 越权）
async function 校验行动(s, 行动) {
  const 行 = { ...行动 };
  const 目标合法 = (t) => t === '旅人' || 存活NPC(s).includes(t);
  if (行.涂门 && !(s.$物品.草汁在身 === '旅人' && s.$物品.草汁存量 > 0 && 目标合法(行.涂门))) 行.涂门 = '';
  if (行.麻沸散 && !(s.$物品.药囊在身 === '旅人' && s.$物品.麻沸散已用 === '否' && 目标合法(行.麻沸散))) 行.麻沸散 = '';
  if (行.银匕随身 && s.$物品.银匕在身 !== '旅人') 行.银匕随身 = false;
  if (行.狼票 && !(s._玩家.身份 === '狼' && 目标合法(行.狼票) && 行.狼票 !== '旅人')) 行.狼票 = '';
  if (行.镜验 && !(s.$物品.铜镜在身 === '旅人' && 目标合法(行.镜验) && 行.镜验 !== '旅人')) 行.镜验 = '';
  if (行.同屋) {
    const 同意 = 行.同屋 !== '旅人' && 目标合法(行.同屋) && 行.同屋 !== '旅人'
      && (s.人物[行.同屋]?.好感 || 0) >= 参.同屋好感门槛;
    if (!同意) { 行.同屋拒绝 = 行.同屋; 行.同屋 = ''; }
  }
  return 行;
}

// ═══ 死亡处理（统一：名单/物灭/玩家标记）═══
function 死亡处理(s, 名, 死因) {
  const d = typeof 死因 === 'string' ? 死因 : '死亡';
  if (名 === '旅人') {
    s._玩家.存活 = '死亡';
    return;
  }
  s.$人物[名].存活 = d;
  s._世界.存活名单 = 存活NPC(s).filter((n) => n !== 名).join('|');
  for (const 物 of 四神职) {
    if (s.$物品[物 + '在身'] === 名) s.$物品[物 + '在身'] = ''; // 人死物灭
  }
}

// ═══ 1. 指派（先分组后落人，三组互斥）═══
// 触发：MESSAGE_SENT（玩家第一条消息）。竞态兜底：EJS 门控块对未指派态输出空态占位。
async function 指派() {
  await 写(async (s) => {
    const 池 = shuffle([...名单11, '旅人']);
    const 狼 = 池.slice(0, 4);
    const 余 = 池.slice(4);
    const 神源 = shuffle(余.slice(0, 4));
    const 神职 = {};
    四神职.forEach((职, i) => { 神职[神源[i]] = 职; });

    // 写真相（$ 层，AI 不可见）
    for (const n of 名单11) {
      s.$人物[n].身份 = 狼.includes(n) ? '狼' : (神职[n] || '民');
      s.$人物[n].持物 = 神职[n] || '';
    }
    s._玩家.身份 = 狼.includes('旅人') ? '狼' : (神职['旅人'] || '民');
    // 注意：不写 $物品.X在身 —— 物在藏处未取，取物后才有「在身」

    // 狼队互认：NPC 狼不落文本（脚本按 $身份 现算狼队名单）；玩家狼的同伴进脚本变量
    if (狼.includes('旅人')) {
      await 写脚本变量((v) => { v.同伴 = 狼.filter((x) => x !== '旅人').join('、'); });
    }

    // 玩家血梦/藏处 → 脚本变量（AI 永不可见，UI 身份卡渲染）
    const v0 = await 脚本变量();
    v0.血梦 = ''; v0.玩家藏处 = ''; v0.玩家被种夜 = 0; v0.镜验 = {}; v0.暴露 = {}; v0.互疑 = {};
    v0.同屋 = {}; v0.银匕随身 = '';
    if (s._玩家.身份 === '狼') {
      v0.血梦 = '血月之夜的梦里，你看见了同伴的脸：' + v0.同伴 + '。还有一种从骨髓里泛上来的饿，你不明白那是什么。';
    } else if (四神职.includes(s._玩家.身份)) {
      const 藏处 = 抽一(藏处池);
      v0.玩家藏处 = 藏处;
      v0.血梦 = '梦里有一只手把' + 物名[s._玩家.身份] + '塞进你掌心，一个声音说：它藏在' + 藏处 + '。守住它，守住你的命。';
    } else {
      v0.血梦 = '你梦见漫山遍野的红，雪是热的。有人在很远的地方哭，你听不清是谁。醒来时枕头是湿的，你不记得自己为什么哭。';
    }
    await replaceVariables(v0, { type: 'script' });

    // NPC 神职藏处（脚本变量）
    await 写脚本变量((v) => {
      v.藏处 = {};
      for (const [人, 职] of Object.entries(神职)) if (人 !== '旅人') v.藏处[职] = 抽一(藏处池);
    });

    s._世界.阶段 = '夜';
    s._世界.公开事实 = '第 1 夜开始了。血月升起，暴风雪封山。';
    s._世界.今日广播 = '[入夜] 血月升起。各回离屋，落闩入睡。夜里发生的事，明早谁也不会记得。';
  });
}

