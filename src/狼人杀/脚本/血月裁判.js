// 下毒入口（玩家 UI 独立事务）
async function 下毒(下毒者, 目标) {
  const s0 = 读().stat_data;
  if (s0.$物品.毒药已用 === '是' || s0.$物品.药囊在身 !== 下毒者) return;
  const 存在 = 目标 === '旅人' ? s0._玩家.存活 === '存活' : 存活NPC(s0).includes(目标);
  if (!存在 || 目标 === 下毒者) return;

  await 写(async (s) => {
    await 毒杀结算(s, 下毒者, 目标);
    if (目标 === '旅人') await 胜负结算(s);
  });
}

