// 把某一位的 8 个阶段文件（熟练度×5 + 目的进度×3）组装成一个「阶段.yaml」
// 内容全部来自已有文件（手工写的），本脚本只做：搬运 + EJS 包装 + 插入「手段」栏 + 去重
const fs = require('fs');
const path = require('path');
const DIR = 'E:/Games/写卡/tavern_helper_template/src/旮旯给木-同级生2/世界书/角色/屏幕外的她';

const 档标签 = ['★ 生涩', '★ 开始有自己的一套', '★ 清楚每一种手段长什么样', '★ 连着用、下手很重', '★ 直奔目标，铺垫全省'];
const 熟档 = [['新手', 1, 20], ['上手', 21, 40], ['沉浸', 41, 60], ['狂热', 61, 80], ['收官', 81, 100]];

// ★ 「手段」= 她遇到障碍怎么办 / 遇到无聊怎么办（E6），按老练度递进。手工内容。
const 手段 = {
  丰娆: [
    '遇到慢的地方快进，遇到新的人先暂停看全 —— 还没有章法，全凭想看',
    '开始给自己的路线排序：这一层先看谁，下一层再看谁',
    '清楚哪一段会出新的人、哪一段是空的 —— 空的一眼都不看',
    '连着踩互斥的线，为了看全，宁可把你推进坏结局',
    '直奔还没看过的那几个，铺垫全省',
  ],
  舒晏: [
    '她还在试：每点一次都会停下来想，这个反应是不是她要的那一个',
    '开始试同一条路的不同点法，看会不会炸',
    '已经知道怎么让它更难了，而且乐在其中',
    '把关系同时铺开，让 <user> 谁都顾不上',
    '不铺了 —— 直接点最后那一下，看他还剩什么',
  ],
  唐响: [
    '一次只推一格，怕一下子玩坏',
    '开始挑最狠的那条，推之前凑近屏幕看',
    '不看选项的文字了，只看等级 —— 哪个最高点哪个',
    '不光挑，还自己加码：一天开两次',
    '什么都试过了，一边玩一边在搜别的',
  ],
  沈眠: [
    '点得很慢，一条一条看，什么都不急着做',
    '知道哪条会让他被救，于是避开那条',
    '把光标放在选项上很久不动 —— 她等得起',
    '开始让两个人对上，然后什么都不做，看他们怎么办',
    '所有人的路她都封了，最后那一下她自己点',
  ],
  莫漾: [
    '躺着点，鼠标放在肚子上，有一搭没一搭',
    '开始挂机：切到别的窗口刷手机，回来接着随手点',
    '连选项都懒得看 —— 哪个离鼠标近点哪个',
    '她也没多投入，但每天差不多同一个点会打开它',
    '她忘了自己在玩什么',
  ],
  纪清: [
    '先把所有人的初始数据抄进表格，才点第一个选项',
    '开始对账：每次数值变了都要核一遍算得对不对',
    '开了三个窗口对照，游戏只是她的实验台',
    '把「哪一段最高效」都试出来 —— 同一种做法做两遍对照',
    '开始清理零碎项，每一个没走到的小分支都要补',
  ],
  郁灼: [
    '翻着选项一路点，遇到能选的就选最狠的那个',
    '知道哪种标法最刺激，开始专门挑带「极」的',
    '学会跳过剧情了，只在有用的那几屏停下来',
    '开始自己加码 —— 一天开两次，白天一次晚上一次',
    '这个游戏对她已经不够了，一边玩一边在搜别的',
  ],
};

const 人名 = process.argv.slice(2);
if (!人名.length) { console.log('用法: node 组装_她的阶段.cjs <人名...>'); process.exit(1); }

const 读 = p => { try { return fs.readFileSync(p, 'utf8'); } catch { return null; } };
const 加缩进 = t => t.split('\n').map(l => l.trim() ? '  ' + l : l).join('\n');

for (const 人 of 人名) {
  const 目录 = path.join(DIR, 人);
  const 手段表 = 手段[人];
  if (!手段表) { console.log('✗ 没有 ' + 人 + ' 的手段数据'); continue; }

  const 头部 = `熟练度与目的进度（★ 一个条目、两个变量，各自精准裁剪，只渲染当前那一档）

怎么触发: 她.人设 === '${人}' 时本条目才加载；内部再按下面两个变量各裁出一档，其余不渲染
熟练度（0~100）: 她运用「手段」的老练度。★ 引擎四处读它 —— 误点概率 / 反抗成功率惩罚 / 离线痕迹扫描强度 / 她上线多久
  ${熟档.map(([n, a, b]) => `${n} ${a}~${b}`).join(' ｜ ')}
目的进度（0~100）: 她这一局做到哪了。★ 按她自己那一套的「推进 / 退回」规则变
  起步 0~33 ｜ 推进 34~66 ｜ 快到 67~100

<% { %>
<%_ const 熟 = getvar('stat_data.她.熟练度', { defaults: 1 }); _%>
<%_ const 进 = getvar('stat_data.她.目的进度', { defaults: 0 }); _%>

【熟练度 · 只渲染当前这一档】`;

  let 熟练段 = '';
  熟档.forEach(([名, a, b], i) => {
    let 原 = 读(path.join(目录, `熟练度_${名}.yaml`));
    if (!原) { console.log(`✗ ${人}/熟练度_${名}.yaml 缺失`); return; }
    // 去掉头两行（_怎么触发 / 区间），并把「★ 本档的边界」统一成「她的边界」
    原 = 原.split('\n').filter(l => !/^_怎么触发:/.test(l) && !/^区间:/.test(l)).join('\n').trim();
    原 = 原.replace(/^★ 本档的边界:/m, '她的边界:');
    // 从「她做得到」处插入「她的手段」
    原 = `她的手段（${档标签[i]}）: ${手段表[i]}\n` + 原;
    const 标签 = i === 0 ? '<%_ if (熟 <= 20) { _%>' : (i === 熟档.length - 1 ? '<%_ } else { _%>' : `<%_ } else if (熟 <= ${b}) { _%>`);
    熟练段 += `\n${标签}\n${名}\n${加缩进(原)}\n`;
  });
  熟练段 += '<%_ } _%>\n';

  let 目的段 = `\n【目的进度 · 只渲染当前这一档】`;
  [['起步', 0, 33], ['推进', 34, 66], ['快到', 67, 100]].forEach(([名, a, b], i) => {
    let 原 = 读(path.join(目录, `目的进度_${名}.yaml`));
    if (!原) { console.log(`✗ ${人}/目的进度_${名}.yaml 缺失`); return; }
    原 = 原.split('\n').filter(l => !/^_怎么触发:/.test(l) && !/^区间:/.test(l)).join('\n').trim();
    原 = 原.replace(/^★ 本档的边界:/m, '她的边界:');
    // 去掉与「熟练度」重复的「她的样子」明细，只留指路
    原 = 原.replace(/^她的样子[^\n]*:\n[\s\S]*?(?=\n她怎么玩:)/m, '她的样子: 见上面「熟练度」那一档\n');
    const 标签 = i === 0 ? '<%_ if (进 <= 33) { _%>' : (i === 2 ? '<%_ } else { _%>' : `<%_ } else if (进 <= ${b}) { _%>`);
    目的段 += `\n${标签}\n${名}\n${加缩进(原)}\n`;
  });
  目的段 += '<%_ } _%>\n<% } %>\n';

  const out = 头部 + '\n' + 熟练段 + 目的段;
  fs.writeFileSync(path.join(目录, '阶段.yaml'), out, 'utf8');
  console.log(`✓ ${人}/阶段.yaml  ${Buffer.byteLength(out, 'utf8')} 字节 / ${out.length} 字符`);
}
