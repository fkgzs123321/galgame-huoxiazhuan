let miss = 0;
for (const [file, from, to] of 替换) {
  const p = R + file;
  const s = fs.readFileSync(p, 'utf8');
  if (!s.includes(from)) {
    console.log('未命中:', file, '|', from.slice(0, 30));
    miss++;
    continue;
  }
  const n = s.split(from).length - 1;
  fs.writeFileSync(p, s.split(from).join(to));
  console.log('已改', n, '处:', file);
}
console.log('\n未命中', miss);
