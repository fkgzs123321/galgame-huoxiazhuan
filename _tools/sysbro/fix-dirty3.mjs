let n = 0;
const 文件集 = new Set();
const walk = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = d + e.name;
    if (e.isDirectory()) walk(p + '/');
    else if (e.name.endsWith('.txt')) 文件集.add(p);
  }
};
walk(R);

for (const p of 文件集) {
  let s = fs.readFileSync(p, 'utf8');
  let hit = 0;
  for (const [a, b] of 表) {
    const c = s.split(a).length - 1;
    if (c) {
      s = s.split(a).join(b);
      hit += c;
    }
  }
  if (hit) {
    fs.writeFileSync(p, s);
    n += hit;
  }
}
